# --------------------------------------------------------------------------- formatting
def fnum(x: float, d: int = 2, plus: bool = False) -> str:
    """A number for LaTeX text or math: true minus sign, optional explicit plus."""
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "---"
    s = f"{abs(float(x)):.{d}f}"
    if float(x) < 0 and float(s) != 0.0:
        return r"\ensuremath{-}" + s
    if plus and float(s) != 0.0:
        return r"\ensuremath{+}" + s
    return s


def fci(lo: float, hi: float, d: int = 2) -> str:
    return f"[{fnum(lo, d)}, {fnum(hi, d)}]"


def fint(x: float) -> str:
    return f"{int(round(float(x))):,}".replace(",", "{,}")


def macro(name: str, value: str) -> None:
    assert re.fullmatch(r"[A-Za-z]+", name), name
    assert name not in NUMS, f"macro defined twice: {name}"
    NUMS[name] = value


def tex_escape(s: str) -> str:
    return (
        s.replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
    )


def stack(cell: str) -> str:
    """A header cell whose ``~~`` marks line breaks, as a shortstack.

    A line that opens with ``[`` is guarded with ``{}`` so that the line break
    before it does not read it as its optional argument.
    """
    if "~~" not in cell:
        return cell
    parts = [("{}" + x) if x.startswith("[") else x for x in cell.split("~~")]
    return r"\shortstack{" + r"\\".join(parts) + "}"


def write_tab(
    name: str, sources: list[str], colspec: str, header: list[str], body: list[str]
) -> None:
    """One booktabs tabular; ``body`` lines are complete rows or rules."""
    header = [stack(h) for h in header]
    lines = [
        "% AUTO-GENERATED by writeup/make_appendix_running_tex.py -- do not edit.",
        *[f"% Source: {s}" for s in sources],
        r"\begin{tabular}{" + colspec + "}",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    (GEN / f"appendix_running_{name}.tex").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )
    WRITTEN.append(name)


def row(cells: list[str]) -> str:
    return " & ".join(cells) + r" \\"


def panel(title: str, ncol: int) -> str:
    return r"\multicolumn{" + str(ncol) + r"}{l}{\emph{" + title + r"}} \\"


# --------------------------------------------------------------------------- notebooks
def nb_output(path: Path, marker: str) -> str:
    """All saved text output of the first cell whose output contains ``marker``."""
    nb = json.loads(path.read_text(encoding="utf-8"))
    for cell in nb["cells"]:
        parts = []
        for out in cell.get("outputs", []):
            txt = "".join(out.get("text", "")) if "text" in out else ""
            if not txt and "data" in out:
                txt = "".join(out["data"].get("text/plain", ""))
            parts.append(txt)
        joined = "\n".join(parts)
        if marker in joined:
            return joined
    raise KeyError(f"{path.name}: no saved output contains {marker!r}")


