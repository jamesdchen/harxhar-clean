def restofday() -> None:
    """Direct rest-of-day forecasts against the one-step construction (QLIKE)."""
    src = RES / "linear_subsection_restofday" / "score_rest_of_day.csv"
    d = pd.read_csv(src, dtype={"clock": str, "bar": str})
    assert (d["train_win"] == 2000).all()
    e = d[d["clock"] != "1530"]
    last = d[d["clock"] == "1530"]
    bucket_lab = {
        "baseline": "HAR + calendar",
        "live_feasible": "live-feasible (16 columns)",
        "all_features": "all features",
    }
    est_lab = {"ridge": "ridge", "reclasso": "lasso", "reclasticnet": "elastic net"}
    body = []
    meds: dict[str, list[float]] = {}
    better: list[int] = []
    worse_sig: list[int] = []
    for b in ["baseline", "all_features"]:  # live_feasible commented out
        for est in ["ridge", "reclasso", "reclasticnet"]:
            g = e[(e["bucket"] == b) & (e["estimator"] == est)]
            assert len(g) == 12, (b, est, len(g))
            g15 = last[(last["bucket"] == b) & (last["estimator"] == est)]
            med = float(g["pct_plain_vs_onestep"].median())
            nb_ = int(
                (
                    (g["pct_plain_vs_onestep"] < 0) & (g["p_plain_vs_onestep"] < ALPHA)
                ).sum()
            )
            nw = int(
                (
                    (g["pct_plain_vs_onestep"] > 0) & (g["p_plain_vs_onestep"] < ALPHA)
                ).sum()
            )
            npw = int((g["pct_plain_vs_onestep"] > 0).sum())
            meds.setdefault(b, []).append(med)
            better.append(nb_)
            worse_sig.append(nw)
            body.append(
                row(
                    [
                        bucket_lab[b],
                        est_lab[est],
                        f"{fint(g['n'].min())}--{fint(g['n'].max())}",
                        fnum(med, 1),
                        str(nb_),
                        str(nw),
                        str(npw),
                        fnum(float(g15["pct_plain_vs_onestep"].abs().iloc[0]), 3),
                    ]
                )
            )
        if b != "all_features":
            body.append(r"\midrule")
    write_tab(
        "restofday",
        [
            src.relative_to(ROOT).as_posix()
            + ' ("plain" columns: qlike_plain, pct_plain_vs_onestep, p_plain_vs_onestep)'
        ],
        "llrrrrrr",
        [
            "column set",
            "estimator",
            "sessions",
            r"median~~$\Delta$QLIKE (\%)",
            "clocks~~better",
            "clocks~~worse",
            "clocks higher~~(point)",
            r"15:30~~$|\Delta|$ (\%)",
        ],
        body,
    )
    for b, nm in (
        ("baseline", "Base"),
        ("live_feasible", "Live"),
        ("all_features", "All"),
    ):
        v = meds[b]
        # most negative first: the range reads "from -x to -y"
        macro(f"runappRd{nm}Lo", fnum(min(v), 0))
        macro(f"runappRd{nm}Hi", fnum(max(v), 0))
    macro("runappRdBetterLo", str(min(better)))
    macro("runappRdBetterHi", str(max(better)))
    assert max(worse_sig) == 0, "the direct forecast is never significantly worse"
    macro("runappRdNlo", fint(d["n"].min()))
    macro("runappRdNhi", fint(d["n"].max()))
    macro("runappRdFirst", str(d["first"].min()))
    macro("runappRdLast", str(d["last"].max()))
    macro("runappRdLastMax", fnum(float(last["pct_plain_vs_onestep"].abs().max()), 3))
    macro("runappRdAlpha", fnum(ALPHA, 2))
    # extreme plain back-transforms (QLIKE above 1 on either side), named in the text
    ext = e[(e["qlike_plain"] > 1) | (e["qlike_onestep"] > 1)]
    macro("runappRdExtremeN", str(len(ext)))
    macro("runappRdCells", str(len(e)))
    assert not (ext["p_plain_vs_onestep"] < ALPHA).any(), (
        "no extreme cell is a significant comparison"
    )
    big = ext.sort_values("qlike_plain").iloc[-1]
    macro("runappRdExtremeQ", fnum(float(big["qlike_plain"]), 1))
    macro("runappRdExtremeOne", fnum(float(big["qlike_onestep"]), 3))
    macro("runappRdExtremeClock", f"{big['clock'][:2]}:{big['clock'][2:]}")
    macro(
        "runappRdExtremeCell",
        f"{bucket_lab[big['bucket']]} {est_lab[big['estimator']]}",
    )
    # 15:30 all-features ridge: the plain back-transform's rare extreme values
    r15 = last[
        (last["bucket"] == "all_features") & (last["estimator"] == "ridge")
    ].iloc[0]
    macro("runappRdAllRidgeLast", fnum(float(r15["qlike_plain"]), 2))

    restofday_trade()


def restofday_trade() -> None:
    """Optional: the trading test of the direct forecast (another workstream's output).

    Its table is that workstream's generated/appendix_running_restofday_trading.tex;
    this writes only the numbers the prose quotes, to a separate macro file, and only
    when the test's pooled CSV exists (the section inputs both under IfFileExists).
    """
    src = (
        RES / "linear_subsection_restofday" / "trading_test" / "trading_test_pooled.csv"
    )
    out = GEN / "appendix_running_restofday_trade_numbers.tex"
    if not src.exists():
        if out.exists():
            out.unlink()
        return
    t = pd.read_csv(src)
    t = t[t["pool"] == "10:00-15:30"]
    nums: dict[str, str] = {}

    def cell(est: str, bucket: str, variant: str, fill: str) -> pd.Series:
        r = t[
            (t["estimator"] == est)
            & (t["bucket"] == bucket)
            & (t["variant"] == variant)
            & (t["fill"] == fill)
        ]
        assert len(r) == 1, (est, bucket, variant, fill)
        return r.iloc[0]

    for bucket, nm in (
        ("live_feasible", "Lf"),
        ("all_features", "Af"),
        ("baseline", "Ba"),
    ):
        for fill, fx in (("mid", ""), ("crossed", "X")):
            r = cell("ridge", bucket, "plain", fill)
            nums[f"runappTt{nm}Cur{fx}"] = fnum(r["Sharpe_current"])
            nums[f"runappTt{nm}Dir{fx}"] = fnum(r["Sharpe_direct"])
            nums[f"runappTt{nm}D{fx}"] = fnum(r["dSharpe"], 2, plus=True)
            nums[f"runappTt{nm}Ci{fx}"] = fci(r["dSharpe_pct_lo"], r["dSharpe_pct_hi"])
        r = cell("ridge", bucket, "plain", "mid")
        nums[f"runappTt{nm}BuyCur"] = fnum(r["pct_buy_current"], 1)
        nums[f"runappTt{nm}BuyDir"] = fnum(r["pct_buy_direct"], 1)
        nums[f"runappTt{nm}Q"] = fnum(r["pct_qlike_direct_vs_current"], 1)
        nums[f"runappTt{nm}VsShort"] = fnum(r["dSharpe_direct_vs_short"], 2)
        nums[f"runappTt{nm}VsShortCi"] = fci(
            r["dSharpe_direct_vs_short_pct_lo"], r["dSharpe_direct_vs_short_pct_hi"]
        )
    ridge = t[(t["estimator"] == "ridge") & (t["variant"] == "plain")]
    n_int = len(ridge)
    n_zero = int(((ridge["dSharpe_pct_lo"] < 0) & (ridge["dSharpe_pct_hi"] > 0)).sum())
    nums["runappTtRidgeIntervals"] = str(n_int)
    nums["runappTtRidgeZero"] = str(n_zero)
    mid = t[t["fill"] == "mid"]
    nums["runappTtCombos"] = str(len(mid))
    nums["runappTtAhead"] = str(int((mid["dSharpe"] > 0).sum()))
    exc = (mid["dSharpe_pct_lo"] > 0) & (mid["dSharpe_basic_lo"] > 0)
    exc_neg = (mid["dSharpe_pct_hi"] < 0) & (mid["dSharpe_basic_hi"] < 0)
    nums["runappTtExclFor"] = str(int(exc.sum()))
    nums["runappTtExclAgainst"] = str(int(exc_neg.sum()))
    lines = [
        "% AUTO-GENERATED by writeup/make_appendix_running_tex.py -- do not edit.",
        f"% Source: {src.relative_to(ROOT).as_posix()} (pool 10:00-15:30; per-bar ridge, plain back-transform unless counted over all)",
    ]
    lines += [r"\newcommand{\%s}{%s}" % (k, v) for k, v in nums.items()]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


