"""Build the running appendix's tables and prose numbers from executed outputs.

The running appendix (writeup/sections/appendix_running.tex) collects the side
analyses that sit outside the paper's main line.  This script writes

  writeup/generated/appendix_running_<item>.tex   one booktabs tabular per table
  writeup/generated/appendix_running_numbers.tex  \\newcommand macros (\\runapp...)
                                                  for every number quoted in prose

and nothing else.  Every number is read from a committed results CSV, a study's
saved summary, or an executed notebook's saved output text; nothing is typed in
by hand.  Each generated file names its source in a comment.  A few gates assert
that two outputs of the same quantity agree before either is used.

The one optional input is the direct rest-of-day trading test, which another
workstream writes to results/linear_subsection_restofday/trading_test/.  When a
``summary.csv`` lands there this script renders it as
appendix_running_restofday_trade.tex (the section inputs it under
\\IfFileExists); until then that file is not written.

Run:  python writeup/make_appendix_running_tex.py
"""

