def repick() -> None:
    """The 30-minute re-pick (unhedged): pooled rules and the eight forecasts."""
    src_a = RP / "rule_table_intraday_blk2.csv"
    src_x = RP / "rule_table_intraday_crossed_blk2.csv"
    a = pd.read_csv(src_a).set_index("rule")
    x = pd.read_csv(src_x).set_index("rule")
    assert (a.index == x.index).all()
    for r in a.index:  # the two files carry the same midpoint Sharpe
        assert abs(a.loc[r, "Sharpe_ann"] - x.loc[r, "Sharpe mid"]) < TOL, r
    labels = {
        "always short": "always short",
        "always short, flat at 15:30": "always short, flat at 15:30",
        "sign(s)": r"$\mathrm{sign}(s^{\mathrm m})$",
        "always short, sign(s) close": r"always short, $\mathrm{sign}(s^{\mathrm m})$ at 15:30",
    }
    body = [panel(r"(a) four rules, block-diagonal ridge", 8)]
    for r, lab in labels.items():
        body.append(
            row(
                [
                    lab,
                    fnum(a.loc[r, "mean_daily"], 3),
                    fnum(a.loc[r, "t_mean"], 2),
                    fnum(a.loc[r, "Sharpe_ann"], 2),
                    fnum(x.loc[r, "Sharpe crossed-spread"], 2),
                    fnum(x.loc[r, "crossings/day"], 1),
                    fnum(x.loc[r, "break-even half-spread % prem"], 2),
                    fnum(a.loc[r, "pct_buy"], 1),
                ]
            )
        )
    # (b) the eight forecasts, censored implied re-inverted as in the main text
    pdir = RP / "rule_by_strategy" / "pooled"
    s = pd.read_csv(pdir / "rule_by_strategy_sign_s.csv", index_col=0)
    sh = pd.read_csv(pdir / "rule_by_strategy_always_short.csv", index_col=0)
    assert abs(sh["Sharpe_ann"].iloc[0] - a.loc["always short", "Sharpe_ann"]) < TOL
    body.append(r"\midrule")
    body.append(panel(r"(b) $\mathrm{sign}(s^{\mathrm m})$ for each forecast", 8))
    for f, r in s.iterrows():
        body.append(
            row(
                [
                    tex_escape(str(f)).replace("fixed 1e-4", r"$\alpha=10^{-4}$"),
                    fnum(r["mean"], 3),
                    fnum(r["t_mean"], 2),
                    fnum(r["Sharpe_ann"], 2),
                    fnum(r["Sharpe_crossed"], 2),
                    "---",
                    "---",
                    "---",
                ]
            )
        )
    write_tab(
        "repick",
        [
            src_a.relative_to(ROOT).as_posix(),
            src_x.relative_to(ROOT).as_posix(),
            (pdir / "rule_by_strategy_sign_s.csv").relative_to(ROOT).as_posix(),
        ],
        "lrrrrrrr",
        [
            "",
            "mean/day",
            "$t$",
            "Sharpe~~(mid)",
            "Sharpe~~(crossed)",
            "crossings~~per day",
            r"break-even half-~~spread (\% prem.)",
            r"\% bars~~bought",
        ],
        body,
    )
    macro("runappRpNdays", fint(a["n_days"].iloc[0]))
    macro("runappRpAsMid", fnum(a.loc["always short", "Sharpe_ann"]))
    macro("runappRpAsX", fnum(x.loc["always short", "Sharpe crossed-spread"]))
    macro("runappRpFlatMid", fnum(a.loc["always short, flat at 15:30", "Sharpe_ann"]))
    macro(
        "runappRpFlatX",
        fnum(x.loc["always short, flat at 15:30", "Sharpe crossed-spread"]),
    )
    macro("runappRpSignMid", fnum(a.loc["sign(s)", "Sharpe_ann"]))
    macro("runappRpSignX", fnum(x.loc["sign(s)", "Sharpe crossed-spread"]))
    macro("runappRpHybMid", fnum(a.loc["always short, sign(s) close", "Sharpe_ann"]))
    macro(
        "runappRpHybX",
        fnum(x.loc["always short, sign(s) close", "Sharpe crossed-spread"]),
    )
    assert (x["Sharpe crossed-spread"] < 0).all(), (
        "every re-pick rule is negative at the crossed spread"
    )
    # the prose: the hybrid is the least negative crossed rule; sign(s) beats always short at the mid
    assert x["Sharpe crossed-spread"].idxmax() == "always short, sign(s) close"
    assert a.loc["sign(s)", "Sharpe_ann"] > a.loc["always short", "Sharpe_ann"]
    macro("runappRpXMin", fnum(x["Sharpe crossed-spread"].min()))
    macro("runappRpXMax", fnum(x["Sharpe crossed-spread"].max()))
    macro("runappRpMidMin", fnum(a["Sharpe_ann"].min()))
    macro("runappRpMidMax", fnum(a["Sharpe_ann"].max()))
    macro("runappRpXingLo", fnum(x["crossings/day"].min(), 1))
    macro("runappRpXingHi", fnum(x["crossings/day"].max(), 1))
    macro("runappRpBeLo", fnum(x["break-even half-spread % prem"].min()))
    macro("runappRpBeHi", fnum(x["break-even half-spread % prem"].max()))
    txt = nb_output(NB_RP, "median half-spread")
    m = re.search(
        r"median half-spread ([\d.]+) pts = ([\d.]+)% of midpoint premium", txt
    )
    assert m, "re-pick half-spread line"
    macro("runappRpHalfSpread", m.group(2))
    # the prose: the median half-spread is above every rule's break-even half-spread
    assert float(m.group(2)) > x["break-even half-spread % prem"].max()
    m = re.search(r"are the (\d+) with a censored vendor implied volatility", txt)
    assert m, "re-pick censored-bar count"
    macro("runappRpCensored", m.group(1))
    assert float(m.group(1)) > 0
    macro("runappRpEightMidLo", fnum(s["Sharpe_ann"].min()))
    macro("runappRpEightMidHi", fnum(s["Sharpe_ann"].max()))
    macro("runappRpEightXLo", fnum(s["Sharpe_crossed"].min()))
    macro("runappRpEightXHi", fnum(s["Sharpe_crossed"].max()))
    macro("runappRpRidgeReinv", fnum(s.loc[RIDGE, "Sharpe_ann"]))


