"""Tables and macros of the economics re-score on the pooled linear reruns of 2026-10-19 (2026-10-20).

NEW files only; nothing here touches the paper of record's economics files (make_rehaul_economics.py,
rehaul_econ_*.tex, \\rhe... macros), and nothing is \\input by the paper text: the author decides whether to wire them.

DATA  results/econ_rerun_2026-10-20/levels.csv, pairs.csv (experiments/econ_rerun_2026_10_20.py): the sign strategy on
  the 0DTE SPXW closing straddle driven by the 16:00 forecast of each rerun model, with the rules, days, costs and
  tests of make_rehaul_economics.py.  Panel A: the pooled linear models fit on all 48 half-hour intervals; Panel B:
  the same models fit on the 13 regular-hours intervals.  If the CSVs are missing the script names the step that
  makes them and stops; it writes nothing.

WRITES
  writeup/generated/rehaul_econ_rerun_numbers.tex  \\rher... macros (macro-only)
  writeup/generated/rehaul_econ_rerun_levels.tex   table tab:rh_econ_rerun_levels  (each model against the short
                                                   straddle and against the OLS of its panel)
  writeup/generated/rehaul_econ_rerun_pairs.tex    table tab:rh_econ_rerun_pairs   (full predictor set minus HAR
                                                   benchmark; 48 minus 13 intervals)

MACROS  \\rher<Stat><Panel><Model><Set>, Panel A (48 intervals) or B (13), Model Ols / Ridge / Lasso / Enet, Set Har /
  Full; Stat:
    ShMid, ShX       SR at mid-quotes and at quoted bid/ask prices (614 post-warmup days, year-by-year annualization)
    TMean            HAC t of the mean mid return (866 days)
    Buys, Hit        % of days long the straddle, % of days with a positive mid return
    DShShort, DShXShort, TShort, TXShort, LWpShort    dSR against the short straddle, HAC t of the daily return
                     difference (mid, bid/ask), Ledoit-Wolf bootstrap p (b = 5, 614 days)
    DShOls, TOls, LWpOls      the same against the OLS of the panel (not for the OLS row)
  \\rherDShFull<Panel><Model>, \\rherTFull..., \\rherLWpFull...: full set minus HAR benchmark;
  \\rherDShPanel<Model><Set>, \\rherTPanel..., \\rherLWpPanel...: 48 minus 13 intervals;
  \\rherShortSh, \\rherShortShX, \\rherShortT: the short straddle; \\rherNdays, \\rherSzDays, \\rherHACLag, \\rherBoot.

Run:  python writeup/make_rehaul_econ_rerun.py [--preview DIR]
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "econ_rerun_2026-10-20"
GEN = ROOT / "writeup" / "generated"
PREFIX = "rehaul_econ_rerun_"
LEVELS = (0.10, 0.05, 0.01)
PANEL = {"48": "A", "13": "B"}
PANEL_TITLE = {"48": "Panel A: Pooled on all 48 half-hour intervals",
               "13": "Panel B: Pooled on the 13 regular-hours intervals"}
MODEL = {"ols": "Ols", "ridge": "Ridge", "lasso": "Lasso", "enet": "Enet"}
MODEL_NAME = {"ols": "OLS", "ridge": "Ridge", "lasso": "Lasso", "enet": "Elastic net"}
SET = {"baseline": "Har", "all_features": "Full"}
SET_NAME = {"baseline": "HAR benchmark", "all_features": "Full predictor set"}
ROWS = (("ols", "baseline"), ("ridge", "baseline"), ("lasso", "baseline"), ("enet", "baseline"),
        ("ridge", "all_features"), ("lasso", "all_features"), ("enet", "all_features"))
HEADER = "% AUTO-GENERATED by writeup/make_rehaul_econ_rerun.py -- do not edit; re-run the script.\n"


def p2(z: float) -> float:
    return math.erfc(abs(float(z)) / math.sqrt(2.0))


def stars(t) -> str:
    if t is None or not math.isfinite(float(t)):
        return "^{\\phantom{***}}"
    n = sum(p2(t) < lv for lv in LEVELS)
    return "^{" + "*" * n + ("\\phantom{" + "*" * (3 - n) + "}" if n < 3 else "") + "}"


def f2(x) -> str:
    return "--" if x is None or not math.isfinite(float(x)) else f"{float(x):.2f}"


def fp(x) -> str:
    return "--" if x is None or not math.isfinite(float(x)) else f"{float(x):.3f}"


def key(panel, model, pset) -> str:
    return f"p{panel}_{model}_{pset}"


def load():
    missing = [p for p in (RES / "levels.csv", RES / "pairs.csv") if not p.is_file()]
    if missing:
        print("missing inputs: " + ", ".join(str(p.relative_to(ROOT)) for p in missing), file=sys.stderr)
        print("make them with:  python experiments/econ_rerun_2026_10_20.py", file=sys.stderr)
        print("(that step needs results/atm_straddle_0dte_1530/daily_a0.parquet and the rerun forecasts; "
              "see results/econ_rerun_2026-10-20/BLOCKED.md if present)", file=sys.stderr)
        raise SystemExit(2)
    lv = pd.read_csv(RES / "levels.csv").set_index("key")
    pr = pd.read_csv(RES / "pairs.csv")
    pr = {(r.comparison, r.a, r.b): r for r in pr.itertuples(index=False)}
    return lv, pr


def macros(lv, pr) -> list[tuple[str, str, str]]:
    out = []  # (name, value, comment)
    s = lv.loc["always_short"]
    out += [("rherShortSh", f2(s.sh_mid), "short straddle, SR mid, 614 post-warmup days"),
            ("rherShortShX", f2(s.sh_x), "short straddle, SR at quoted bid/ask prices"),
            ("rherShortT", f2(s.t_mean_mid), "short straddle, HAC t of the mean mid return, 866 days"),
            ("rherNdays", "866", "option days (HAC t, mean, hit rate)"),
            ("rherSzDays", "614", "post-warmup days of every printed SR"),
            ("rherHACLag", "14", "Newey-West lag floor(1.5 n^(1/3)) on 866 days"),
            ("rherBoot", "4999", "bootstrap draws of the Ledoit-Wolf test")]
    for panel in ("48", "13"):
        P = PANEL[panel]
        ols = key(panel, "ols", "baseline")
        for m, s_ in ROWS:
            k = key(panel, m, s_)
            tag = f"{P}{MODEL[m]}{SET[s_]}"
            r = lv.loc[k]
            out += [(f"rherShMid{tag}", f2(r.sh_mid), f"{k}: SR mid"),
                    (f"rherShX{tag}", f2(r.sh_x), f"{k}: SR bid/ask"),
                    (f"rherTMean{tag}", f2(r.t_mean_mid), f"{k}: HAC t of the mean mid return"),
                    (f"rherBuys{tag}", f"{r.buys_pct:.1f}", f"{k}: % of days long"),
                    (f"rherHit{tag}", f"{r.hit_pct:.1f}", f"{k}: % of days with a positive mid return")]
            c = pr[("vs_short", k, "always_short")]
            out += [(f"rherDShShort{tag}", f2(c.dsh_mid), f"{k} minus short straddle: dSR mid"),
                    (f"rherDShXShort{tag}", f2(c.dsh_x), f"{k} minus short straddle: dSR bid/ask"),
                    (f"rherTShort{tag}", f2(c.t_dmean_mid), f"{k} minus short straddle: HAC t, mid"),
                    (f"rherTXShort{tag}", f2(c.t_dmean_x), f"{k} minus short straddle: HAC t, bid/ask"),
                    (f"rherLWpShort{tag}", fp(c.lw_p_boot_614), f"{k} vs short straddle: Ledoit-Wolf bootstrap p, 614 days")]
            if k != ols:
                c = pr[("vs_ols", k, ols)]
                out += [(f"rherDShOls{tag}", f2(c.dsh_mid), f"{k} minus {ols}: dSR mid"),
                        (f"rherTOls{tag}", f2(c.t_dmean_mid), f"{k} minus {ols}: HAC t, mid"),
                        (f"rherLWpOls{tag}", fp(c.lw_p_boot_614), f"{k} vs {ols}: Ledoit-Wolf bootstrap p")]
        for m in ("ridge", "lasso", "enet"):
            c = pr[("all_vs_har", key(panel, m, "all_features"), key(panel, m, "baseline"))]
            tag = f"{P}{MODEL[m]}"
            out += [(f"rherDShFull{tag}", f2(c.dsh_mid), f"{m}, panel {panel}: full set minus HAR benchmark, dSR mid"),
                    (f"rherDShXFull{tag}", f2(c.dsh_x), "same, bid/ask"),
                    (f"rherTFull{tag}", f2(c.t_dmean_mid), "same, HAC t mid"),
                    (f"rherLWpFull{tag}", fp(c.lw_p_boot_614), "same, Ledoit-Wolf bootstrap p")]
    for m, s_ in ROWS:
        c = pr[("48_vs_13", key("48", m, s_), key("13", m, s_))]
        tag = f"{MODEL[m]}{SET[s_]}"
        out += [(f"rherDShPanel{tag}", f2(c.dsh_mid), f"{m} {s_}: 48 minus 13 intervals, dSR mid"),
                (f"rherDShXPanel{tag}", f2(c.dsh_x), "same, bid/ask"),
                (f"rherTPanel{tag}", f2(c.t_dmean_mid), "same, HAC t mid"),
                (f"rherLWpPanel{tag}", fp(c.lw_p_boot_614), "same, Ledoit-Wolf bootstrap p")]
    names = [n for n, *_ in out]
    assert len(names) == len(set(names)), "duplicate macro"
    assert all(n.isalpha() for n in names), [n for n in names if not n.isalpha()]
    return out


def numbers_tex(ms) -> str:
    lines = [HEADER, "% \\rher... macros: economics re-score on the pooled linear reruns of 2026-10-19 "
             "(results/econ_rerun_2026-10-20/)\n"]
    for n, v, c in ms:
        lines.append(f"\\providecommand{{\\{n}}}{{}}\\renewcommand{{\\{n}}}{{{v}}}  % {c}\n")
    return "".join(lines)


def cell(est, t) -> str:
    return f"${est}{stars(t)}$"


def tcell(t) -> str:
    return f"$({f2(t)})^{{\\phantom{{***}}}}$"


def pcell(p) -> str:
    return f"$[{fp(p)}]^{{\\phantom{{***}}}}$" if p is not None and math.isfinite(float(p)) else ""


def levels_tex(lv, pr) -> str:
    s = lv.loc["always_short"]
    L = [HEADER, "% Economics re-score: each rerun model against the short straddle and the OLS of its panel\n",
         "\\ifdefined\\rherNdays\\else\\input{generated/rehaul_econ_rerun_numbers}\\fi\n",
         "\\begin{table}[tbp]\n\\centering\n\\small\n\\begin{threeparttable}\n",
         "\\caption{Sign strategy on the pooled linear reruns}\n\\label{tab:rh_econ_rerun_levels}\n",
         "\\begin{tabular}{@{}llrrrrr@{}}\n\\toprule\n",
         " & & \\multicolumn{2}{c}{$\\SR$} & \\multicolumn{2}{c}{$\\Delta\\SR$ vs.\\ short straddle} & $\\Delta\\SR$ vs.\\ OLS \\\\\n",
         "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(l){7-7}\n",
         " & Predictors & Mid & Bid--ask & Mid & Bid--ask & Mid \\\\\n\\midrule\n",
         f"Short straddle & -- & ${f2(s.sh_mid)}$ & ${f2(s.sh_x)}$ & & & \\\\\n",
         f" & & $({f2(s.t_mean_mid)})$ & & & & \\\\[2pt]\n"]
    for panel in ("48", "13"):
        ols = key(panel, "ols", "baseline")
        L.append("\\addlinespace[4pt]\n" + f"\\multicolumn{{7}}{{@{{}}l}}{{\\textit{{{PANEL_TITLE[panel]}}}}} \\\\\n\\addlinespace[2pt]\n")
        for m, s_ in ROWS:
            k = key(panel, m, s_)
            r = lv.loc[k]
            c = pr[("vs_short", k, "always_short")]
            o = pr.get(("vs_ols", k, ols))
            L.append(f"{MODEL_NAME[m]} & {'HAR' if s_ == 'baseline' else 'Full'} & ${f2(r.sh_mid)}$ & ${f2(r.sh_x)}$ & "
                     f"{cell(f2(c.dsh_mid), c.t_dmean_mid)} & {cell(f2(c.dsh_x), c.t_dmean_x)} & "
                     f"{cell(f2(o.dsh_mid), o.t_dmean_mid) if o is not None else ''} \\\\\n")
            L.append(f" & & & & {tcell(c.t_dmean_mid)} & {tcell(c.t_dmean_x)} & {tcell(o.t_dmean_mid) if o is not None else ''} \\\\\n")
            L.append(f" & & & & {pcell(c.lw_p_boot_614)} & & {pcell(o.lw_p_boot_614) if o is not None else ''} \\\\[2pt]\n")
    L += ["\\bottomrule\n\\end{tabular}\n\\begin{tablenotes}[flushleft]\n\\footnotesize\n",
          "\\item \\textit{Notes:} The sign strategy on the closing 0DTE straddle, driven by the 15:30 forecast of the "
          "closing half hour of each pooled linear model of Table~\\ref{tab:rh_oos} (base-5 HAR horizons, penalties chosen "
          "on the pre-sample and frozen, 2,000-day window). $\\SR$ is the annualized Sharpe ratio over the "
          "\\rherSzDays{} post-warmup option days, at mid-quotes and at quoted bid/ask prices. $\\Delta\\SR$ is the row "
          "minus the short straddle, or minus the OLS of the same panel; in parentheses the HAC $t$-statistic of the "
          "daily return differential over the \\rherNdays{} option days (Newey--West, $q_{\\mathrm{NW}} = \\rherHACLag$), "
          "which tests the mean differential, and in brackets the Ledoit--Wolf studentized block-bootstrap $p$-value of "
          "the Sharpe-ratio difference (block length 5, \\rherBoot{} draws). Under the short straddle, the HAC $t$ of its "
          "mean return. A dash marks a differential that is zero on every day. $^{*}$, $^{**}$ and $^{***}$ mark the 10\\%, 5\\% and 1\\% levels of the HAC $t$.\n",
          "\\end{tablenotes}\n\\end{threeparttable}\n\\end{table}\n"]
    return "".join(L)


def pairs_tex(lv, pr) -> str:
    L = [HEADER, "% Economics re-score: full predictor set minus HAR benchmark, and 48 minus 13 intervals\n",
         "\\ifdefined\\rherNdays\\else\\input{generated/rehaul_econ_rerun_numbers}\\fi\n",
         "\\begin{table}[tbp]\n\\centering\n\\small\n\\begin{threeparttable}\n",
         "\\caption{Sign strategy on the pooled linear reruns: paired differences}\n\\label{tab:rh_econ_rerun_pairs}\n",
         "\\begin{tabular}{@{}llrrrrr@{}}\n\\toprule\n",
         " & & \\multicolumn{2}{c}{$\\SR$ at mid-quotes} & \\multicolumn{2}{c}{$\\Delta\\SR$} & \\\\\n",
         "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\n",
         " & & First & Second & Mid & Bid--ask & Same position (\\%) \\\\\n\\midrule\n",
         "\\multicolumn{7}{@{}l}{\\textit{Panel A: Full predictor set (first) minus HAR benchmark (second)}} \\\\\n\\addlinespace[2pt]\n"]

    def row(label, sub, c):
        a, b = lv.loc[c.a], lv.loc[c.b]
        return (f"{label} & {sub} & ${f2(a.sh_mid)}$ & ${f2(b.sh_mid)}$ & {cell(f2(c.dsh_mid), c.t_dmean_mid)} & "
                f"{cell(f2(c.dsh_x), c.t_dmean_x)} & ${c.same_position_pct:.1f}$ \\\\\n"
                f" & & & & {tcell(c.t_dmean_mid)} & {tcell(c.t_dmean_x)} & \\\\\n"
                f" & & & & {pcell(c.lw_p_boot_614)} & & \\\\[2pt]\n")

    for panel in ("48", "13"):
        for m in ("ridge", "lasso", "enet"):
            c = pr[("all_vs_har", key(panel, m, "all_features"), key(panel, m, "baseline"))]
            L.append(row(MODEL_NAME[m], f"{panel} intervals", c))
    L.append("\\addlinespace[4pt]\n\\multicolumn{7}{@{}l}{\\textit{Panel B: 48 intervals (first) minus 13 intervals (second)}} \\\\\n\\addlinespace[2pt]\n")
    for m, s_ in ROWS:
        c = pr[("48_vs_13", key("48", m, s_), key("13", m, s_))]
        L.append(row(MODEL_NAME[m], "HAR" if s_ == "baseline" else "Full", c))
    L += ["\\bottomrule\n\\end{tabular}\n\\begin{tablenotes}[flushleft]\n\\footnotesize\n",
          "\\item \\textit{Notes:} Each row pairs two pooled linear forecasts of the rerun design and trades both with "
          "the sign strategy of Table~\\ref{tab:rh_econ_rerun_levels}. $\\SR$ over the \\rherSzDays{} post-warmup option "
          "days; $\\Delta\\SR$ is the first minus the second, with the HAC $t$-statistic of the daily return "
          "differential over the \\rherNdays{} option days in parentheses ($q_{\\mathrm{NW}} = \\rherHACLag$; a test of "
          "the mean differential) and the Ledoit--Wolf block-bootstrap $p$-value of the Sharpe-ratio difference in "
          "brackets. Same position: the share of the \\rherNdays{} days on which the two forecasts take the same side. "
          "$^{*}$, $^{**}$ and $^{***}$ mark the 10\\%, 5\\% "
          "and 1\\% levels of the HAC $t$.\n",
          "\\end{tablenotes}\n\\end{threeparttable}\n\\end{table}\n"]
    return "".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=Path, help="write into this directory instead of writeup/generated")
    a = ap.parse_args()
    lv, pr = load()
    out_dir = a.preview or GEN
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {"numbers": numbers_tex(macros(lv, pr)), "levels": levels_tex(lv, pr), "pairs": pairs_tex(lv, pr)}
    for name, text in files.items():
        p = out_dir / f"{PREFIX}{name}.tex"
        assert p.name.startswith(PREFIX)  # never one of the paper of record's rehaul_econ_* files
        p.write_text(text, encoding="utf-8")
        print("wrote", p.relative_to(ROOT) if p.is_relative_to(ROOT) else p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
