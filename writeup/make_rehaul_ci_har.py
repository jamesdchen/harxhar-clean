"""The closing-interval HAR (CI-HAR) rebuilt under the current data chain (integration plan D9, 2026-10-26): \\rhci...

READS   results/ci_har_rebuild_2026-10-26/ (RULE.txt; results_bar1600.csv, the rebuilt forecasts; gates.csv, the
        bit-for-bit gate of the old-rules rebuild against the old file; measure/{accuracy,dm_old_vs_new,sharpe}.csv and
        measure/summary.json, written by experiments/ci_har_rebuild_measure_2026_10_26.py).  Every number is read from
        those files; none is recomputed here.  Since the switch (D9) the master table and every consumer read the rebuilt
        file for the key sub_ols_baseline (experiments/master_table_close.py CI_HAR_REBUILT).
WRITES  writeup/generated/rehaul_ci_har_numbers.tex   \\rhci... macros (definitions only) for the closing-interval
        appendix (A_closing.tex).  T_close = the 1,082 trading days 2020-01-03 .. 2024-04-30.

Run:  python writeup/make_rehaul_ci_har.py     (repository root)
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CI = ROOT / "results" / "ci_har_rebuild_2026-10-26"
GEN = HERE / "generated"
OUT_NUM = GEN / "rehaul_ci_har_numbers.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_ci_har.py -- do not edit; re-run the script."
T_CLOSE = "T_oos 2020-01-03..2024-04-30"  # measure's label of the 1,082-day span (T_close in the paper)


def thousands(x: int) -> str:
    return f"{x:,}".replace(",", "{,}")


def num(x: float, nd: int = 2) -> str:
    s = f"{x:.{nd}f}"
    if float(s) == 0:
        s = s.lstrip("-")
    return "\\ensuremath{-}" + s[1:] if s.startswith("-") else s


def pval(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def date_txt(d: pd.Timestamp) -> str:
    return f"{d.day} {d:%B %Y}"


def main() -> None:
    M: list[tuple[str, str, str]] = []

    def add(name: str, value: str, note: str) -> None:
        assert name.isalpha(), name
        M.append(("rhci" + name, value, note))

    f = pd.read_csv(CI / "results_bar1600.csv", parse_dates=["date"])
    g = pd.read_csv(CI / "gates.csv")
    acc = pd.read_csv(CI / "measure" / "accuracy.csv")
    dmo = pd.read_csv(CI / "measure" / "dm_old_vs_new.csv")
    sh = pd.read_csv(CI / "measure" / "sharpe.csv").set_index("which")
    summ = json.loads((CI / "measure" / "summary.json").read_text())
    gate = g[g["check"].str.startswith("GATE")].iloc[0]
    noop = g[g["check"].str.startswith("NO-OP")].iloc[0]
    assert bool(noop["pass"]), "the no-op check of the rebuild failed"
    # the gate's pass rule (build.log): stamps and target bit for bit, forecasts within 1e-13 relative
    assert bool(gate["bitequal_true_adj"]) and bool(gate["bitequal_true_raw"]) and gate["maxrel_pred_adj"] <= 1e-13
    add("First", date_txt(f["date"].min()), "first forecast of the rebuilt CI-HAR")
    add("Last", date_txt(f["date"].max()), "last forecast")
    add("NForecasts", thousands(len(f)), "16:00 forecasts of the rebuilt file")
    add("OldFirst", date_txt(pd.Timestamp("2018-06-25")), "first forecast of the earlier file (RULE.txt)")
    add(
        "GateMaxRel",
        "\\ensuremath{" + f"{gate['maxrel_pred_adj']:.1e}".replace("e-", "\\times 10^{-") + "}}",
        "old-rules rebuild vs old file: max relative forecast difference",
    )
    add("EarlyRowsOld", str(summ["early_close_rows"]["old"]), "forecast rows on NYSE early-close days, earlier file")
    add("EarlyRowsNew", str(summ["early_close_rows"]["new"]), "... rebuilt file")
    bd = summ["b_days"]
    add("BDays", str(bd["n_days_old_B_ne_pool"]), "days on which the earlier B differs from the pooled design's B")
    add("BDaysOf", thousands(bd["n_common_old_pool"]), "of the earlier file's days")
    add("BDaysClose", str(bd["n_174_in_T_oos"]), "... of them in T_close")
    add("BDaysNewDiff", str(bd["n_days_new_B_ne_pool_all"]), "days on which the rebuilt B differs from the pooled B")
    a = acc[(acc["span"] == "T_oos common span (1,082)") & (acc["days"] == "own")].set_index("file")
    assert int(a.loc["old", "n"]) == int(a.loc["new", "n"]) == 1082
    add("QOldClose", f"{a.loc['old', 'qlike']:.4f}", "QLIKE, 16:00 bar, T_close, the earlier CI-HAR")
    add("QNewClose", f"{a.loc['new', 'qlike']:.4f}", "QLIKE, 16:00 bar, T_close, the rebuilt CI-HAR")
    add("MseOldClose", f"{a.loc['old', 'mse_e10']:.2f}", "MSE x 10^10, T_close, earlier")
    add("MseNewClose", f"{a.loc['new', 'mse_e10']:.2f}", "MSE x 10^10, T_close, rebuilt")
    d = dmo[dmo["span"] == T_CLOSE].iloc[0]
    add("DmOldNewClose", num(float(d["dm_qlike"])), "DM, rebuilt minus earlier, daily QLIKE on T_close")
    add("POldNewClose", pval(float(d["dm_qlike_p"])), "its p-value")
    add("DmLagClose", str(int(d["dm_hac_lag"])), "its Newey-West lag")
    q = summ["strategy"]["new"]
    add("FlipDays", str(q["q_changed_days_614"]), "post-warmup option days on which the CI-HAR sign position changes")
    add("FlipDaysAll", str(q["q_changed_days_866"]), "option days on which it changes")
    for w in ("old", "new"):
        tag = "Old" if w == "old" else "New"
        add(f"Sh{tag}", num(float(sh.loc[w, "sh_mid"])), f"D6 Sharpe ratio at mid, {w} CI-HAR")
        add(f"ShX{tag}", num(float(sh.loc[w, "sh_x"])), f"D6 Sharpe ratio at bid/ask, {w} CI-HAR")
        add(f"DShShort{tag}", num(float(sh.loc[w, "dsh_short"])), f"Sharpe gain over the short straddle, {w}")
        add(f"PShort{tag}", pval(float(sh.loc[w, "p_short"])), f"its bootstrap p, {w}")
        add(f"LongDays{tag}", str(int(sh.loc[w, "long_days_614"])), f"long days of 614, {w}")

    names = [n for n, _, _ in M]
    assert len(set(names)) == len(names), "a macro name twice"
    lines = [
        HEAD,
        "% \\rhci... macros of the rebuilt closing-interval HAR (results/ci_har_rebuild_2026-10-26; RULE.txt, measure/).",
        "% T_close: the 1,082 trading days 2020-01-03 .. 2024-04-30 (the measure files call it T_oos).",
    ]
    for name, value, note in M:
        lines.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}  % {note}")
    GEN.mkdir(parents=True, exist_ok=True)
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(M)} macros to {OUT_NUM.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
