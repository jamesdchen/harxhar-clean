"""Within-block ladder beyond HAR + RM + FOMC (results/beyond_trees_2026-10-27/RULE.txt section 2; ablation RULE.txt
addendum I) -> writeup/generated/rehaul_beyond_ladder_numbers.tex (\\rhbyL... macros) and
writeup/generated/rehaul_beyond_ladder_table.tex (tab:rh_beyond_ladder).

Reads results/ablations_2014start_w3000/scores_fomcfix (experiments/ablate_score.py --design fix): per model (LightGBM,
XGBoost) the rungs brung_<est>_<k> = BASE (add_rm_fomc) + the top k remaining-block series of the model's own patched
primary ranking, k in {1, 3, 5, 10, 20}; k = 0 is BASE, k = all is FULL.  Per rung and day type (every bar / ORDINARY /
EVENT): QLIKE change against BASE (%), its DM (HLN, daily means, lag 8) and p, the DM against FULL, and the recovery
R = (L_BASE - L_k) / (L_BASE - L_FULL).  The reading (ORDINARY days, per model), applied mechanically: CONCENTRATED if
R(5) >= 0.75; DENSE if R(20) < 0.75; otherwise INTERMEDIATE.  Requested by the author after the beyond-base results;
not pre-registered.

usage: python writeup/make_rehaul_beyond_ladder.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
sys.path.insert(0, str(REPO / "experiments"))
import ablate_arms as AA  # noqa: E402

RES = REPO / "results" / "ablations_2014start_w3000" / "scores_fomcfix"
GEN = ROOT / "generated"
OUT_NUM = GEN / "rehaul_beyond_ladder_numbers.tex"
OUT_TAB = GEN / "rehaul_beyond_ladder_table.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_beyond_ladder.py -- do not edit; re-run the script."
BASE = "add_rm_fomc"
MODELS = {"lgbm": ("Lgbm", "LightGBM"), "xgb": ("Xgb", "XGBoost")}
K_TEX = {1: "One", 3: "Three", 5: "Five", 10: "Ten", 20: "Twenty"}
SPANS = {"all": "All", "ord": "Ord", "ev": "Ev"}
LABEL = "requested by the author after the beyond-base results; not pre-registered"


def fmt(x: float, dp: int) -> str:
    v = round(float(x), dp)
    if v == 0:
        v = 0.0
    return f"{'$-$' if v < 0 else ''}{abs(v):.{dp}f}"


def fmt_p(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def mac(name: str, value: str, comment: str = "") -> str:
    assert name.isalpha(), name
    return f"\\newcommand{{\\rhbyL{name}}}{{{value}}}" + (f"  % {comment}" if comment else "")


def reading(r5: float, r20: float) -> str:
    if r5 >= 0.75:
        return "CONCENTRATED"
    if r20 < 0.75:
        return "DENSE"
    return "INTERMEDIATE"


def main() -> int:
    M = pd.read_csv(RES / "metrics.csv")
    D = pd.read_csv(RES / "dm.csv")
    checks = json.loads((RES / "checks.json").read_text())
    assert checks["pass"], checks["fail"]
    q = M.set_index(["cls", "arm", "span"])["qlike"]
    dq = D[D["loss"] == "qlike"].set_index(["cls", "arm", "vs_cls", "vs_arm", "span"])
    lines = [HEAD, f"% {RES.relative_to(REPO).as_posix()}; {LABEL}"]
    res: dict = {}
    for est, (t, _name) in MODELS.items():
        for sp, st in SPANS.items():
            lb, lf = q[(est, BASE, sp)], q[(est, "full", sp)]
            lines.append(mac(f"{t}Full{st}Pct", fmt(100 * (lf / lb - 1), 1), f"{est} FULL vs BASE, {sp}"))
            for k in AA.LADDER_K:
                arm = f"brung_{est}_{k}"
                lk = q[(est, arm, sp)]
                r = (lb - lk) / (lb - lf)
                kb, kf = (est, arm, est, BASE, sp), (est, arm, est, "full", sp)
                nm = f"{t}K{K_TEX[k]}{st}"
                lines.append(mac(f"{nm}Pct", fmt(100 * (lk / lb - 1), 1), f"{est} k={k} vs BASE, {sp}; {LABEL}"))
                lines.append(mac(f"{nm}Dm", fmt(dq.loc[kb, "dm"], 2), "DM vs BASE"))
                lines.append(mac(f"{nm}P", fmt_p(dq.loc[kb, "p"]), "p-value"))
                lines.append(mac(f"{nm}DmFull", fmt(dq.loc[kf, "dm"], 2), "DM vs FULL (positive: FULL lower)"))
                lines.append(mac(f"{nm}PFull", fmt_p(dq.loc[kf, "p"]), "p-value"))
                lines.append(mac(f"{nm}R", fmt(r, 2), "recovery (L_BASE - L_k) / (L_BASE - L_FULL)"))
                res[(est, k, sp)] = dict(
                    pct=100 * (lk / lb - 1),
                    dm=float(dq.loc[kb, "dm"]),
                    p=float(dq.loc[kb, "p"]),
                    dm_full=float(dq.loc[kf, "dm"]),
                    p_full=float(dq.loc[kf, "p"]),
                    R=float(r),
                )
        rd = reading(res[(est, 5, "ord")]["R"], res[(est, 20, "ord")]["R"])
        res[(est, "reading")] = rd
        lines.append(mac(f"{t}Reading", rd.lower(), "section 2 reading, ORDINARY days"))
        lines.append(
            mac(f"{t}Top", ", ".join(AA.LADDER[est][:5]).replace("_", "\\_"), "the model's top 5 block series")
        )
    agree = res[("lgbm", "reading")] == res[("xgb", "reading")]
    lines.append(mac("Agree", "agree" if agree else "split", "the two models' readings"))
    names = [ln.split("}", 1)[0] for ln in lines if ln.startswith("\\newcommand")]
    assert len(names) == len(set(names)), "duplicate macro"
    GEN.mkdir(parents=True, exist_ok=True)
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT_TAB.write_text(table(res), encoding="utf-8")
    flat = {f"{k[0]}|{k[1]}|{k[2]}" if len(k) == 3 else f"{k[0]}|{k[1]}": v for k, v in res.items()}
    (RES / "beyond_ladder.json").write_text(json.dumps(flat, indent=1))
    print(
        f"wrote {OUT_NUM.name} ({len(lines)} lines), {OUT_TAB.name}; readings {res[('lgbm', 'reading')]} / "
        f"{res[('xgb', 'reading')]} ({'agree' if agree else 'split'})"
    )
    return 0


def table(res: dict) -> str:
    out = [
        HEAD,
        f"% tab:rh_beyond_ladder; {LABEL}.",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\begin{threeparttable}",
        "\\caption{Within-block ladder beyond HAR, realized moments and the FOMC calendar}",
        "\\label{tab:rh_beyond_ladder}",
        "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrrrr@{}}",
        "\\toprule",
        " & \\multicolumn{4}{c}{LightGBM} & \\multicolumn{4}{c}{XGBoost} \\\\",
        "\\cmidrule(lr){2-5}\\cmidrule(l){6-9}",
        " & \\multicolumn{2}{c}{Every bar} & \\multicolumn{2}{c}{Ordinary days} & \\multicolumn{2}{c}{Every bar}"
        " & \\multicolumn{2}{c}{Ordinary days} \\\\",
        "Series added to the base ($-$: they add accuracy) & $\\Delta$ (DM) & $R$ & $\\Delta$ (DM) & $R$ & $\\Delta$ (DM)"
        " & $R$ & $\\Delta$ (DM) & $R$ \\\\",
        "\\midrule",
    ]
    for k in AA.LADDER_K:
        cells = []
        for est in MODELS:
            for sp in ("all", "ord"):
                r = res[(est, k, sp)]
                cells += [f"{fmt(r['pct'], 1)} ({fmt(r['dm'], 1)})", fmt(r["R"], 2)]
        out.append(f"Top {k} & " + " & ".join(cells) + " \\\\")
    out.append("\\midrule")
    cells = []
    for est in MODELS:
        cells += [f"\\multicolumn{{4}}{{c}}{{{res[(est, 'reading')].lower()}}}"]
    out.append("Reading (ordinary days) & " + " & ".join(cells) + " \\\\")
    top = "; ".join(
        f"{name}: " + ", ".join(s.replace("_", "\\_") for s in AA.LADDER[est][:5]) for est, (_t, name) in MODELS.items()
    )
    out += [
        "\\bottomrule",
        "\\end{tabular*}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        # 2026-10-28 (author: make the meaning of positive and negative changes abundantly clear): the sign key opens
        # the notes; pct and the DM are rung minus BASE (dm.csv: arm brung_<est>_<k> vs add_rm_fomc)
        "\\item \\textit{Sign:} $\\Delta = 100\\,(L_k/L_{\\text{base}} - 1)$, the percentage change in mean QLIKE of the"
        " row's forecast against the base, with the Diebold--Mariano statistic on daily average QLIKE in parentheses"
        " (same sign): negative, the loss falls when the series are added, i.e.\\ they add accuracy; positive, they"
        " hurt.  $R = (L_{\\text{base}} - L_k) / (L_{\\text{base}} - L_{\\text{full}})$, the share of the full set's gain"
        " over the base recovered by the top $k$ series: 1, all of it; 0, none; below 0, worse than the base.",
        # 2026-10-28 (author): the note's opening "Requested by the author after the results beyond HAR + RM + FOMC
        # (Table tab:rh_ablation_beyond), not part of the pre-specified design." removed.
        "\\item \\textit{Notes:} Base: the HAR benchmark set plus"
        " the futures' realized moments and the FOMC calendar (132 columns).  Each row adds the top $k$ series of the"
        " six remaining groups, in the model's own ranking from its 2013 pre-sample fit (the ladder of"
        " Section~\\ref{sec:rh_results_predictors}), with all their trailing averages and availability shares; FOMC-patched"
        " design, frozen hyperparameters, re-estimated at every bar.  Ordinary days exclude the 81 scheduled FOMC statement days.  Reading, fixed before scoring:"
        " concentrated if $R \\geq 0.75$ at $k = 5$, dense if $R < 0.75$ at $k = 20$, intermediate otherwise.  Top five"
        f" series: {top}.",
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.exit(main())
