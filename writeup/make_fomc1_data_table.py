"""Emit the FOMC-bucket QLIKE table from the FOMC root's scores CSV.

2026-10-06 (recalibration removed, user decision): the default source is the
plain back-transform re-score (every forecast yhat^2 * B, no smearing, no
Mincer-Zarnowitz map) written by ``experiments/score_unification.py
--convention plain`` to results/unification_plain_2026-10-06/fomc1/.  The old
calibrated-scoring CSV (results/unification_fomc1_scores.csv) is kept for the
old -> new audit only; ``--src`` reads any other CSV.

Writes writeup/generated_fomc1/table_fomc_bucket.tex. Never hand-types
QLIKE or DM digits into the Data section; data_prep.tex \\input-s the
tabular.
"""

from __future__ import annotations

import argparse
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(
    ROOT, "results", "unification_plain_2026-10-06", "fomc1", "unification_scores.csv"
)
OUT_DIR = os.path.join(ROOT, "writeup", "generated_fomc1")
OUT = os.path.join(OUT_DIR, "table_fomc_bucket.tex")

# Display order and names for the Data-section table.
ARMS: list[tuple[str, str]] = [
    ("a0_ols_har", r"baseline (HAR + calendar OLS)"),
    ("a_bucket_fomc", r"FOMC calendar bucket (OLS)"),
    ("a_bucket_all_features", r"all features (OLS)"),
    ("b1_ridge", r"ridge (joint)"),
    ("b2_lasso", r"lasso"),
    ("blk2_user", r"block-diagonal ridge"),
]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", default=SRC, help="scores CSV (default: plain re-score)")
    src = ap.parse_args().src
    df = pd.read_csv(src)
    df = df.loc[~df["arm"].astype(str).str.contains("_condvar", regex=False)].copy()
    by_arm = df.set_index("arm")
    missing = [k for k, _ in ARMS if k not in by_arm.index]
    if missing:
        raise SystemExit(f"missing arms in {src}: {missing}")
    n_vals = {int(by_arm.loc[k, "n_bars"]) for k, _ in ARMS}
    if len(n_vals) != 1:
        raise SystemExit(f"n_bars not unique across arms: {sorted(n_vals)}")
    n = next(iter(n_vals))

    lines = [
        "% AUTO-GENERATED by writeup/make_fomc1_data_table.py --- do not edit.",
        f"% Source: {os.path.relpath(src, ROOT).replace(os.sep, '/')}; n={n}; "
        "skip *_condvar; plain back-transform (2026-10-06).",
        r"\begin{tabular}{@{}lrr@{}}",
        r"\toprule",
        r"Arm & QLIKE & DM $t$ \\",
        r"\midrule",
    ]
    for key, label in ARMS:
        qlike = float(by_arm.loc[key, "qlike"])
        dm = float(by_arm.loc[key, "dm_t_vs_a0"])
        lines.append(f"{label} & {qlike:.5f} & ${dm:+.1f}$ \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
