class Beats:
    def __init__(self, root: Path, aux: dict[str, tuple[str, str]]) -> None:
        self.root = root
        self.aux = aux
        self.srcs: dict[str, Src] = {}
        self.reach: dict[str, bool] = {}
        self.stubs: dict[str, Out] = {}  # output path: stub
        self.stub_of: dict[str, str] = {}  # float file: stub \input path
        self.dead_stubs: dict[str, str] = {}  # stub \input path: the section that \input's it in an \iffalse block
        self.removed: collections.Counter[str] = collections.Counter()  # section: nested lists removed in beats/top
        self.resolved: dict[str, list[tuple[str, str, str]]] = {}  # layer: (label, number, page) from the .aux
        self.notes: list[str] = []

    def read(self, rel: str) -> Src:
        if rel not in self.srcs:
            path = self.root / rel
            if not path.is_file():
                raise BeatsError(f"missing file {rel} under {self.root}")
            with open(path, encoding="utf-8", newline="") as fh:
                self.srcs[rel] = Src(rel, fh.read())
        return self.srcs[rel]

    def resolve(self, arg: str, where: str, files: dict[str, str] | None = None) -> str:
        """The file an \\input{arg} reads, relative to the root: arg.tex if it exists, else arg (TeX's order)."""
        p = posixpath.normpath(arg)
        for c in [p] if p.endswith(".tex") else [p + ".tex", p]:
            if (files is not None and c in files) or (self.root / c).is_file():
                return c
        raise BeatsError(f"{where}: \\input{{{arg}}} names no file")

    @staticmethod
    def inputs(src: Src) -> list[tuple[str, int, int, int]]:
        """(argument, start, group start, group stop) of each \\input outside comments."""
        out = []
        for name, s, e in src.words:
            if name == "input":
                o, c = src.group(e)
                out.append((src.text[o + 1 : c - 1].strip(), s, o, c))
        return out

    def reaches_float(self, rel: str) -> bool:
        """Whether rel, or a file it \\input's, holds a float environment or an \\includegraphics."""
        if rel not in self.reach:
            self.reach[rel] = False  # cycle guard
            src = self.read(rel)
            own = bool(src.envs(FLOATS)) or any(n == "includegraphics" for n, _, _ in src.words)
            self.reach[rel] = own or any(
                self.reaches_float(self.resolve(a, src.where(s))) for a, s, _, _ in self.inputs(src)
            )
        return self.reach[rel]

    # -- stubs -------------------------------------------------------------------------------------------------

    @staticmethod
    def emit_float(out: Out, src: Src, env: Env) -> None:
        """One float's stub: \\begin{env}[placement], \\centering, its captions and labels, the omitted line."""
        nl = src.nl
        head = env.head
        j = skip_blanks(src.blank, head)
        if j < env.close and src.blank[j] == "[":
            head = read_group(src.blank, j, src.where(j), "]")
        longtable = env.name == "longtable"  # keeps its column spec; the caption ends a row
        if longtable:
            head = src.group(head)[1]
        out.keep(src.text[env.start : head])
        out.add(nl)
        spans: list[tuple[int, int]] = []
        for name, s, e in src.words:
            if name != "caption" or not env.head <= s < env.close or any(a <= s < b for a, b in spans):
                continue
            k = skip_blanks(src.blank, e + 1 if src.blank.startswith("*", e) else e)
            if src.blank.startswith("[", k):
                k = read_group(src.blank, k, src.where(k), "]")
            spans.append((s, src.group(k)[1]))
        labels = [
            (s, src.group(e)[1])
            for name, s, e in src.words
            if name == "label" and env.head <= s < env.close and not any(a <= s < b for a, b in spans)
        ]
        if not longtable:
            out.add("\\centering" + nl)
        for a, b in spans + labels:
            out.keep(src.text[a:b])
            out.add(nl)
        row = "\\\\" if longtable else ""
        if longtable:
            out.add(row + nl)
        out.add(OMITTED + row + nl)
        out.keep(src.text[env.close : env.stop])
        out.add(nl)

    def float_file_stub(self, rel: str) -> str:
        """The \\input path of the stub of float file rel (generated/X.tex -> beats/stubs/X)."""
        if rel in self.stub_of:
            return self.stub_of[rel]
        src = self.read(rel)
        for a, s, _, _ in self.inputs(src):
            if self.reaches_float(self.resolve(a, src.where(s))):
                raise BeatsError(f"{src.where(s)}: a float file that \\input's another float file; not supported")
        path = f"{STUBS}/{rel.removeprefix('generated/').removesuffix('.tex').replace('/', '_')}"
        out = Out()
        out.add(HEADER + src.nl + "% Review-layer stub of ")
        out.keep(rel)
        out.add(": the caption and label of each float, the body omitted." + src.nl)
        first: dict[int, Env] = {}
        covered: set[int] = set()
        for env in src.envs(FLOATS):
            lines = src.whole_lines(env.start, env.stop, f"\\begin{{{env.name}}}")
            first[lines[0]] = env
            covered.update(lines)
        for i, ln in enumerate(src.lines):
            live = src.live_line(i)
            if i in first:
                self.emit_float(out, src, first[i])
            elif i in covered or not live.strip():
                continue
            elif DEFINES.match(live):
                out.keep(ln.rstrip("\r\n"))
                out.add(src.nl)
            else:
                self.notes.append(f"{src.where(src.starts[i])}: neither a float nor a definition; left out of the stub")
        self.stubs[path + ".tex"] = out
        self.stub_of[rel] = path
        return path

    def inline_stub(self, src: Src, name: str, k: int, env: Env) -> str:
        """The \\input path of the stub of the k-th inline float of section file src."""
        path = f"{STUBS}/{name.replace('/', '_')}_float{k}"
        if path + ".tex" not in self.stubs:
            out = Out()
            out.add(HEADER + src.nl + "% Review-layer stub of an inline float of ")
            out.keep(src.rel)
            out.add(": its caption and label, the body omitted." + src.nl)
            self.emit_float(out, src, env)
            self.stubs[path + ".tex"] = out
        return path

    # -- section copies ----------------------------------------------------------------------------------------

    def copy_section(self, name: str, layer: str) -> Out:
        """The layer's copy of rehaul/<name>.tex (module docstring, SECTION COPIES)."""
        src = self.read(f"rehaul/{name}.tex")
        # Per line: None (copied), [] (left out) or the (kind, text) pieces that replace it.
        action: list[list[tuple[str, str]] | None] = [[] if is_comment_line(ln) else None for ln in src.lines]
        floats = src.envs(FLOATS)
        for k, env in enumerate(floats, 1):
            lines = src.whole_lines(env.start, env.stop, f"\\begin{{{env.name}}}")
            path = self.inline_stub(src, name, k, env)
            for i in lines:
                action[i] = []
            ln = src.lines[lines[0]]
            indent = ln[: len(ln) - len(ln.lstrip(" \t"))]
            action[lines[0]] = [("keep", indent), ("add", "\\input{"), ("keep", path), ("add", "}" + src.nl)]
        for arg, s, o, c in self.inputs(src):
            if any(f.start <= s < f.stop for f in floats):
                continue
            where = src.where(s)
            target = self.resolve(arg, where)
            if not target.startswith("generated/"):
                raise BeatsError(f"{where}: \\input{{{arg}}} is not a generated file; only section files are copied")
            if not self.reaches_float(target):
                continue
            path = self.float_file_stub(target)
            i = src.line_at(s)
            if src.line_at(c - 1) != i or action[i] is not None:
                raise BeatsError(f"{where}: the \\input of a float file must stand on a line of its own")
            if src.is_dead(s):
                self.dead_stubs[path] = src.rel
            a, ln = src.starts[i], src.lines[i]
            action[i] = [("keep", ln[: o + 1 - a]), ("keep", path), ("keep", ln[c - 1 - a :])]
        if layer == "top":
            for env in src.envs(LISTS):
                if env.depth == 2 and not any(f.start <= env.start < f.stop for f in floats):
                    for i in src.whole_lines(env.start, env.stop, f"the nested {env.name}"):
                        action[i] = []
                    self.removed[name] += 1
        out = Out()
        for ln, act in zip(src.lines, action):
            if act is None:
                out.keep(ln)
            for kind, t in act or []:
                (out.keep if kind == "keep" else out.add)(t)
        return out

    # -- entries -----------------------------------------------------------------------------------------------

    def marks(self, paper: Src) -> tuple[int, int, int]:
        """Line indices of \\begin{document}, \\appendix and \\end{document}, each on a line of its own."""
        found: dict[str, int] = {}
        for name, s, e in paper.words:
            if paper.is_dead(s):
                continue
            if name in ("begin", "end") and paper.arg(e) == "document":
                found.setdefault(name, paper.line_at(s))
            elif name == "appendix" and "begin" in found:
                found.setdefault(name, paper.line_at(s))
        for key, text in (("begin", "\\begin{document}"), ("appendix", "\\appendix"), ("end", "\\end{document}")):
            if key not in found or paper.live_line(found[key]).strip() != text:
                raise BeatsError(f"{paper.rel}: no line holding just {text}")
        return found["begin"], found["appendix"], found["end"]

    def sections(self, paper: Src) -> list[str]:
        """The main-text section files, in the order the body \\input's them before \\appendix."""
        doc, app, _ = self.marks(paper)
        names: list[str] = []
        for arg, s, _, _ in self.inputs(paper):
            if paper.starts[doc] <= s < paper.starts[app] and not paper.is_dead(s):
                if not arg.startswith("rehaul/"):
                    raise BeatsError(f"{paper.where(s)}: the body \\input's {arg}, not a section file")
                name = arg.removeprefix("rehaul/").removesuffix(".tex")
                if name not in names:
                    names.append(name)
        return names

    def entry(self, paper: Src, layer: str, block: Out) -> Out:
        """The layer's entry file (module docstring, ENTRIES); block is the \\newlabel block."""
        _, subtitle = LAYERS[layer]
        nl = paper.nl
        doc, app, end = self.marks(paper)
        pre = paper.starts[doc]
        title = [e for n, s, e in paper.words if n == "title" and s < pre]
        if len(title) != 1:
            raise BeatsError(f"{paper.rel}: expected one \\title in the preamble")
        title_close = paper.group(title[0])[1] - 1
        hyper = -1
        for name, s, e in paper.words:
            if name == "usepackage" and s < pre:
                k = skip_blanks(paper.blank, e)
                if paper.blank.startswith("[", k):
                    k = read_group(paper.blank, k, paper.where(k), "]")
                if "hyperref" in [p.strip() for p in paper.arg(k).split(",")]:
                    hyper = paper.line_at(s)
        if hyper < 0:
            raise BeatsError(f"{paper.rel}: hyperref is not loaded in the preamble")
        out = Out()
        out.add(f"{HEADER}{nl}% Review layer of paper_rehaul.tex: {subtitle}. Sections from beats/{layer}/, ")
        out.add(f"float stubs from {STUBS}/; the online appendix is left out.{nl}")
        for i in range(doc):
            ln, a = paper.lines[i], paper.starts[i]
            if is_comment_line(ln):
                continue
            if a <= title_close < a + len(ln):
                out.keep(ln[: title_close - a])
                out.add("\\\\\\large Review layer: " + subtitle)
                out.keep(ln[title_close - a :])
            else:
                out.keep(ln)
            if i == hyper:
                out.extend(block)
        dropped: set[int] = set()
        for a, b, closer in paper.dead:
            if pre <= a < paper.starts[app]:
                if closer != "fi":
                    raise BeatsError(f"{paper.where(a)}: an \\iffalse ... \\else block in the body; not supported")
                dropped.update(paper.whole_lines(a, b, "the \\iffalse block"))
        inputs: dict[int, tuple[int, int, str]] = {}
        for arg, s, o, c in self.inputs(paper):
            i = paper.line_at(s)
            if i in inputs or paper.line_at(c - 1) != i:
                raise BeatsError(f"{paper.where(s)}: each \\input must stand on a line of its own")
            inputs[i] = (o, c, arg)
        for i in range(doc, app):
            ln, a = paper.lines[i], paper.starts[i]
            if is_comment_line(ln) or i in dropped:
                continue
            if i not in inputs:
                out.keep(ln)
                continue
            o, c, arg = inputs[i]
            out.keep(ln[: o + 1 - a])
            out.keep(f"beats/{layer}/{arg.removeprefix('rehaul/')}")
            out.keep(ln[c - 1 - a :])
        out.keep(paper.lines[end])
        return out

    def label_block(self, layer: str, walk: Walk, nl: str) -> Out:
        """The \\newlabel lines of the labels the layer cites but does not define, from the .aux."""
        missing = sorted(walk.refs - walk.labels)
        absent = [m for m in missing if m not in self.aux]
        if absent:
            raise BeatsError(f"layer {layer}: cited, defined neither in the layer nor in the .aux: {', '.join(absent)}")
        self.resolved[layer] = [(m, self.aux[m][0], self.aux[m][1]) for m in missing]
        out = Out()
        if not missing:
            return out
        out.add(
            f"% Labels this layer cites but does not print: number and page from the full paper's .aux, no link.{nl}"
        )
        out.add("\\makeatletter" + nl)
        for m in missing:
            num, page = self.aux[m]
            out.add("\\newlabel{")
            out.keep(m)
            out.add("}{{")
            out.keep(num)
            out.add("}{")
            out.keep(page)
            out.add("}{}{}{}}" + nl)
        out.add("\\makeatother" + nl)
        return out

    # -- what an entry reads -----------------------------------------------------------------------------------

    def walk(self, entry: str, files: dict[str, str]) -> Walk:
        """Follow the live \\input's from the entry; files (output path: text) take precedence over the disk."""
        w = Walk()
        self._visit(entry, files, w)
        return w

    def _visit(self, rel: str, files: dict[str, str], w: Walk) -> None:
        if rel in w.files:
            return
        w.files.append(rel)
        src = Src(rel, files[rel]) if rel in files else self.read(rel)
        for name, s, e in src.words:
            if src.is_dead(s):
                continue
            if name == "label" and "#" not in src.arg(e):
                w.labels.add(src.arg(e))
            elif name in REFS:
                arg = src.arg(e + 1 if src.blank.startswith("*", e) else e)
                if "#" not in arg:
                    w.refs.add(arg)
            elif name == "includegraphics":
                w.bad.append(f"{src.where(s)}: \\includegraphics")
            elif name == "input":
                arg = src.arg(e)
                if arg.startswith("rehaul/") or "99_author" in arg:
                    w.bad.append(f"{src.where(s)}: \\input{{{arg}}}")
                else:
                    self._visit(self.resolve(arg, src.where(s), files), files, w)
        if not rel.startswith(STUBS + "/") and src.envs(FLOATS):
            w.bad.append(f"{rel}: a float environment outside the stubs")


def generate(root: Path, aux_path: Path) -> tuple[dict[str, Out], Beats]:
    b = Beats(root, read_aux(aux_path))
    paper = b.read(PAPER)
    names = b.sections(paper)
    outputs: dict[str, Out] = {}
    for layer in LAYERS:
        for name in names:
            outputs[f"beats/{layer}/{name}.tex"] = b.copy_section(name, layer)
    outputs.update(sorted(b.stubs.items()))
    for layer, (entry, _) in LAYERS.items():
        files = {rel: o.text() for rel, o in outputs.items()}
        files[entry] = b.entry(paper, layer, Out()).text()
        outputs[entry] = b.entry(paper, layer, b.label_block(layer, b.walk(entry, files), paper.nl))
    return outputs, b


