class Out:
    """A file under construction. add() takes the text this script writes itself (checked for digits); keep() takes
    copied source text, file names and .aux values."""

    def __init__(self) -> None:
        self.parts: list[str] = []
        self.added: list[str] = []

    def keep(self, s: str) -> None:
        self.parts.append(s)

    def add(self, s: str) -> None:
        self.parts.append(s)
        self.added.append(s)

    def extend(self, other: Out) -> None:
        self.parts += other.parts
        self.added += other.added

    def text(self) -> str:
        return "".join(self.parts)


@dataclass
class Walk:
    """What an entry reads: the files its live \\input's reach, the labels they define and cite, and problems."""

    files: list[str] = field(default_factory=list)
    labels: set[str] = field(default_factory=set)
    refs: set[str] = field(default_factory=set)
    bad: list[str] = field(default_factory=list)


def read_aux(path: Path) -> dict[str, tuple[str, str]]:
    """label: (number, page), the first two fields of each \\newlabel of the .aux (the last one wins, as in TeX)."""
    if not path.is_file():
        raise BeatsError(f"no .aux at {path}")
    text = path.read_text(encoding="utf-8", errors="replace")
    out = {}
    for m in re.finditer(r"\\newlabel(?=\{)", text):
        o = m.end()
        c = read_group(text, o, f"{path.name}: \\newlabel")
        j = skip_blanks(text, c)
        if not text.startswith("{{", j):
            continue
        num_end = read_group(text, j + 1, f"{path.name}: \\newlabel")
        if not text.startswith("{", num_end):
            continue
        page_end = read_group(text, num_end, f"{path.name}: \\newlabel")
        out[text[o + 1 : c - 1]] = (text[j + 2 : num_end - 1], text[num_end + 1 : page_end - 1])
    return out


