r"""The review layers of the paper's main text: the story beat by beat, each float reduced to its caption and label.

READS (under --src, default writeup/; nothing else)
  paper_rehaul.tex      the preamble, the title, the abstract and the main-text \input lines before \appendix
  rehaul/<name>.tex     each main-text section file those lines read (01_introduction ... 09_conclusion, *_floats)
  generated/<X>.tex     each generated file a section \input's; a float file (a table, table*, figure, figure*,
                        sidewaystable, sidewaysfigure or longtable environment, or an \includegraphics) becomes a stub
  --aux                 the .aux of the full paper (paper_rehaul.tex) built from the same sources

WRITES (under --src)
  paper_rehaul_beats.tex       layer "main text, all bullets"
  paper_rehaul_beats_top.tex   layer "top-level bullets only"
  beats/full/<name>.tex        the section copies of each layer
  beats/top/<name>.tex
  beats/stubs/<X>.tex          one stub a float file (an inline float: beats/stubs/<name>_float<k>.tex)
  Stale .tex files in beats/full, beats/top and beats/stubs are removed.

ENTRIES  The preamble of paper_rehaul.tex verbatim but for its full-line comments, with the subtitle "Review layer:
  ..." added to \title and, after hyperref, a \newlabel block: each label the layer cites (\ref, \pageref, \autoref,
  \eqref) but does not define (the online appendix, lists removed in beats/top), its number and page from --aux and an
  empty anchor, so hyperref prints the number without a link. Then \begin{document}, title, abstract, an \input of each
  section copy in the paper's order, the bibliography and \end{document}. The body's full-line comments and \iffalse
  ... \fi blocks, and everything from \appendix on (the appendix, the author notes), are left out.

SECTION COPIES  The section file without its full-line comments (a line whose first non-blank character is %). Each
  \input{generated/X} of a float file and each inline float environment becomes the \input of its stub. In beats/top
  every itemize or enumerate inside a list is removed, \begin to \end; top-level lists and the text outside lists
  stay. No other line changes; the \ifdefined\X\else\input{generated/...numbers}\fi guards stay (flatten.py drops
  them). Lexing: a % after an even number of backslashes opens a comment; braces count outside comments, \{ and \}
  aside; text in \iffalse ... \fi is dead (its labels, references, bullets and \input's do not count).

STUBS  For each float: its environment and placement, \centering, its \caption verbatim (with any optional argument),
  its \label(s) and the line \textit{[body omitted in this review layer]}. The float file's lines outside its floats
  that define macros (\providecommand ..., the guarded number-file \input's) stay, so the captions' macros resolve.

SELF-CHECKS (exit 1 when one fails; nothing is written)
  every line of a section copy but a stub \input occurs verbatim in its source; no \includegraphics, no float outside
  a stub and no \input of rehaul/ or of the author notes in the outputs or any file an entry reads; no digit in the
  text this script adds (file names and .aux values aside: every number in the PDF comes from the generated macros);
  a second generation is byte-identical.

Run (Git Bash, repository root):  python writeup/make_paper_beats.py --aux writeup/paper_rehaul.aux [--src writeup]
Exit status: 0 done, 1 a self-check failed, 2 the sources or the .aux cannot be used (a cited label the .aux lacks
too). Standard library only.
"""

