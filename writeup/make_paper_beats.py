class BeatsError(Exception):
    """The sources or the .aux cannot be used as they are; the message says where and why."""


# ----------------------------------------------------------------------------------------------------------------
# TeX lexing
# ----------------------------------------------------------------------------------------------------------------


def comment_start(line: str) -> int:
    """Index of the % that opens the line's comment (one after an even number of backslashes), or -1."""
    i, n = 0, len(line)
    while i < n:
        if line[i] == "\\":
            i += 2
        elif line[i] == "%":
            return i
        else:
            i += 1
    return -1


def is_comment_line(line: str) -> bool:
    return line.lstrip(" \t").startswith("%")


def is_conditional(name: str) -> bool:
    return name.startswith("if") and name != "iff"


def skip_blanks(s: str, i: int) -> int:
    while i < len(s) and s[i] in " \t\r\n":
        i += 1
    return i


def read_group(blank: str, j: int, where: str, close: str = "}") -> int:
    """Index after the group opened at blank[j] ({ ... } or, with close="]", [ ... ] outside braces)."""
    depth, k = 0, j + 1
    while k < len(blank):
        c = blank[k]
        if c == "\\":
            k += 2
            continue
        if c == close and depth == 0:
            return k + 1
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        k += 1
    raise BeatsError(f"{where}: unbalanced {blank[j]}")


class Env(NamedTuple):
    name: str
    start: int  # \begin
    head: int  # after \begin{name}
    close: int  # \end
    stop: int  # after \end{name}
    depth: int  # 1 + the number of enclosing environments of the same family


class Src:
    """A TeX file as read (line endings kept) and a copy with its comments blanked out, for lexing."""

    def __init__(self, rel: str, text: str) -> None:
        self.rel = rel
        self.text = text
        self.lines: list[str] = LINE.findall(text)
        self.starts = [0]
        blank = []
        for ln in self.lines:
            self.starts.append(self.starts[-1] + len(ln))
            body = ln.rstrip("\r\n")
            c = comment_start(body)
            blank.append(ln if c < 0 else body[:c] + " " * (len(body) - c) + ln[len(body) :])
        self.blank = "".join(blank)
        self.nl = "\r\n" if "\r\n" in text else "\n"
        self.words = [(m.group(1), m.start(), m.end()) for m in WORD.finditer(self.blank) if m.group(1)]
        self.dead = self._dead_spans()

    def where(self, pos: int) -> str:
        return f"{self.rel}:{self.line_at(pos) + 1}"

    def line_at(self, pos: int) -> int:
        return bisect.bisect_right(self.starts, pos) - 1

    def live_line(self, i: int) -> str:
        """Line i without its comment and line ending."""
        return self.blank[self.starts[i] : self.starts[i + 1]].rstrip("\r\n")

    def is_dead(self, pos: int) -> bool:
        return any(a <= pos < b for a, b, _ in self.dead)

    def group(self, i: int) -> tuple[int, int]:
        """(start, stop) of the {...} argument after position i (blanks skipped)."""
        j = skip_blanks(self.blank, i)
        if j >= len(self.blank) or self.blank[j] != "{":
            raise BeatsError(f"{self.where(i)}: expected a {{...}} argument")
        return j, read_group(self.blank, j, self.where(i))

    def arg(self, i: int) -> str:
        o, c = self.group(i)
        return self.text[o + 1 : c - 1].strip()

    def _dead_spans(self) -> list[tuple[int, int, str]]:
        r"""(start, stop, closing word) of each \iffalse ... \fi (or ... \else) block: text TeX skips."""
        spans = []
        w, k = self.words, 0
        while k < len(w):
            if w[k][0] != "iffalse":
                k += 1
                continue
            depth, j = 1, k + 1
            while j < len(w):
                name = w[j][0]
                if name == "fi":
                    depth -= 1
                    if depth == 0:
                        break
                elif name == "else" and depth == 1:
                    break
                elif is_conditional(name):
                    depth += 1
                j += 1
            else:
                raise BeatsError(f"{self.where(w[k][1])}: \\iffalse without its \\fi")
            spans.append((w[k][1], w[j][2], w[j][0]))
            k = j + 1
        return spans

    def envs(self, names: frozenset[str]) -> list[Env]:
        """The environments named in names, in source order, each with its depth among them."""
        out: list[Env] = []
        stack: list[tuple[str, int, int]] = []
        for word, s, e in self.words:
            if word not in ("begin", "end"):
                continue
            o, c = self.group(e)
            name = self.blank[o + 1 : c - 1].strip()
            if name not in names:
                continue
            if word == "begin":
                stack.append((name, s, c))
                continue
            if not stack or stack[-1][0] != name:
                raise BeatsError(f"{self.where(s)}: \\end{{{name}}} does not close the open environment")
            _, bs, bc = stack.pop()
            out.append(Env(name, bs, bc, s, c, len(stack) + 1))
        if stack:
            raise BeatsError(f"{self.where(stack[-1][1])}: \\begin{{{stack[-1][0]}}} is never closed")
        return sorted(out, key=lambda v: v.start)

    def whole_lines(self, a: int, b: int, what: str) -> range:
        """The lines of text[a:b], which must share no line with other live text and be brace- and if-balanced."""
        i, j = self.line_at(a), self.line_at(b - 1)
        if self.blank[self.starts[i] : a].strip() or self.blank[b : self.starts[j + 1]].strip():
            raise BeatsError(f"{self.where(a)}: {what} shares a line with other text; whole lines cannot go")
        braces, k = 0, a
        while k < b and braces >= 0:
            c = self.blank[k]
            k += 2 if c == "\\" else 1
            braces += (c == "{") - (c == "}")
        conds = 0
        for name, s, _ in self.words:
            if a <= s < b and conds >= 0:
                conds += is_conditional(name) - (name == "fi")
        if braces or conds:
            raise BeatsError(f"{self.where(a)}: {what} is not brace- and conditional-balanced")
        return range(i, j + 1)


