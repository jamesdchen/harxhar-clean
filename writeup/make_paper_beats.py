def self_check(b: Beats, outputs: dict[str, Out]) -> list[str]:
    fails = []
    files = {rel: o.text() for rel, o in outputs.items()}
    for rel, text in files.items():
        src = Src(rel, text)
        if rel.startswith(("beats/full/", "beats/top/")):
            source = {ln.rstrip("\r\n") for ln in b.read("rehaul/" + rel.split("/", 2)[2]).lines}
            for i, ln in enumerate(src.lines):
                if not src.live_line(i).lstrip().startswith(f"\\input{{{STUBS}/") and ln.rstrip("\r\n") not in source:
                    fails.append(f"{rel}:{i + 1}: not a line of its source")
        for arg, s, _, _ in b.inputs(src):
            if arg.startswith("rehaul/") or "99_author" in arg:
                fails.append(f"{src.where(s)}: \\input{{{arg}}}")
        fails += [f"{src.where(s)}: \\includegraphics" for n, s, _ in src.words if n == "includegraphics"]
        fails += [f"{rel}: the script added a digit: {t!r}" for t in outputs[rel].added if DIGIT.search(t)]
    for layer, (entry, _) in LAYERS.items():
        w = b.walk(entry, files)
        fails += w.bad
        undefined = w.refs - w.labels - {m for m, _, _ in b.resolved[layer]}
        fails += [f"{entry}: \\ref{{{m}}} stays undefined" for m in sorted(undefined)]
    return fails


def bullets(text: str) -> collections.Counter[int]:
    """Live \\item's of a section copy by list depth."""
    src = Src("", text)
    depth, out = 0, collections.Counter[int]()
    for name, s, e in src.words:
        if name in ("begin", "end") and src.arg(e) in LISTS:
            depth += 1 if name == "begin" else -1
        elif name == "item" and not src.is_dead(s):
            out[depth] += 1
    return out


def report(b: Beats, outputs: dict[str, Out]) -> None:
    files = {rel: o.text() for rel, o in outputs.items()}
    print("stubs:")
    for rel in sorted(b.stubs):
        src = Src(rel, files[rel])
        floats = [
            f"{env.name} " + ", ".join(src.arg(e) for n, s, e in src.words if n == "label" and env.start < s < env.stop)
            for env in src.envs(FLOATS)
        ]
        dead = rel.removesuffix(".tex") in b.dead_stubs
        print(f"  {rel}: {'; '.join(floats)}" + ("  (\\input inside \\iffalse: not typeset)" if dead else ""))
    for layer, (entry, subtitle) in LAYERS.items():
        count: collections.Counter[int] = collections.Counter()
        for rel in b.walk(entry, files).files:
            if rel.startswith(f"beats/{layer}/"):
                count += bullets(files[rel])
        depths = ", ".join(f"depth {d}: {n}" for d, n in sorted(count.items()))
        print(f"layer {layer} ({subtitle}): {entry}")
        print(f"  bullets (live \\item): {sum(count.values())} ({depths})")
        if layer == "top":
            print(f"  nested lists removed: {sum(b.removed.values())} ({dict(b.removed)})")
        print(f"  labels from the .aux: {len(b.resolved[layer])}")
        for m, num, page in b.resolved[layer]:
            print(f"    {m}: {num}, page {page}")
    for note in b.notes:
        print(f"note: {note}")


def write(root: Path, outputs: dict[str, Out]) -> tuple[int, list[str]]:
    """Write the outputs (changed files only); remove stale .tex files from the beats/ folders."""
    changed = 0
    for rel, out in outputs.items():
        path = root / rel
        data = out.text().encode("utf-8")
        if not path.is_file() or path.read_bytes() != data:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            changed += 1
    stale = []
    for folder in ("beats/full", "beats/top", STUBS):
        for path in sorted((root / folder).glob("*.tex")):
            if path.relative_to(root).as_posix() not in outputs:
                path.unlink()
                stale.append(path.relative_to(root).as_posix())
    return changed, stale


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument(
        "--src", type=Path, default=WRITEUP, help="writeup directory to read and write (default: %(default)s)"
    )
    ap.add_argument("--aux", type=Path, required=True, help="the .aux of the full paper built from the same sources")
    args = ap.parse_args(argv)
    root = args.src.resolve()
    try:
        outputs, b = generate(root, args.aux)
        again, _ = generate(root, args.aux)
        fails = self_check(b, outputs)
    except BeatsError as exc:
        print(f"make_paper_beats.py: {exc}", file=sys.stderr)
        return 2
    if {r: o.text() for r, o in outputs.items()} != {r: o.text() for r, o in again.items()}:
        fails.append("a second generation is not byte-identical")
    print(f"make_paper_beats.py: {root}; {len(outputs)} files; .aux {args.aux}")
    report(b, outputs)
    if fails:
        print(f"self-checks FAILED ({len(fails)}); nothing written:")
        for f in fails:
            print(f"  {f}")
        return 1
    print("self-checks passed: verbatim lines, inputs, no figure, no float body, no added digit, deterministic")
    changed, stale = write(root, outputs)
    print(
        f"wrote {changed} changed of {len(outputs)} files under {root}" + (f"; removed stale {stale}" if stale else "")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
