"""The late-starting series' TreeSHAP shares in the years their value averages are live (Section 8, 2026-10-26).

Pooled over 2014-2024 the trees' attribution of the late-starting series (StockTwits, volatility demand, VIX3M, VVIX,
VIX) mixes years in which the late-start rule of Section 4 keeps their value averages at the neutral 0 with years in
which they are live. This script separates the two from the stored yearly shares of the TreeSHAP study; no model is
refitted and no SHAP value recomputed.

RULE (written before computing)
  Share     a series group's share of the total mean |SHAP| in a calendar year (results/tree_shap_w3000_2014start_
            2026-10-23/m1_by_year.csv; a group sums its series), for LightGBM, XGBoost and the random forest.
  Live-from the day the group's 1-bar value average becomes nonzero in the design (generated/rehaul_live_numbers.tex,
            the comment of \\rhlv<X>LiveYear; StockTwits: attention's day, the earliest of the three series).
  Pre       the mean of the yearly shares over 2014 .. the year before the live-from year.
  Live      the mean of the yearly shares over the calendar years after the live-from year (the full live years)
            through 2024 (January to April); volatility demand: 2023 only (its feed stops on 31 August 2023).
            VVIX is live only from February 2024 and has no full live year (no Live statistic).
  Window    the share of the 3,000-day training window that holds live values at the last origin (5 April 2024):
            trading days from the live-from day to the last origin (to the feed's last day for volatility demand),
            over 3,000; trading days from the constituent panel's calendar. A design row is nonzero only from the
            live-from day on, so a model fit at the last origin has seen the group's values on that share of its
            window only.
  Ranges    min--max over the three trees.

2026-10-28 (decision D13, the paper's design is the FOMC-patched one): Share is read by DEFAULT from the patched
TreeSHAP study, results/tree_shap_w3000_2014start_fomcfix_2026-10-26/m1_by_year.csv (RULE_pointer.txt: the same
RULE_shap.txt on the patched design; gate.txt: every tree bit-equal to its patched walk at 126/126 origins);
--prepatch reads the study of 2026-10-23 named above and writes the *_prepatch outputs.  Nothing else changes.

    python writeup/make_rehaul_fi_live.py [--prepatch]

OUTPUTS (<tag> "" = patched, the names the paper inputs; "_prepatch" with --prepatch)
  writeup/generated/rehaul_fi_live_numbers<tag>.tex   \\rhfil... macros (macro-only)
  writeup/figures/fi_pooled/fi_live<tag>.pdf          the yearly shares, live years shaded
  writeup/generated/rehaul_fi_live_fig<tag>.tex       its float, fig:rh_fi_live
"""

from __future__ import annotations

import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
SHAP_PRE = REPO / "results" / "tree_shap_w3000_2014start_2026-10-23"  # pre-patch design (RULE_shap.txt)
SHAP_FIX = REPO / "results" / "tree_shap_w3000_2014start_fomcfix_2026-10-26"  # FOMC-patched (RULE_pointer.txt; D13)
SHAP, TAG = SHAP_FIX, ""  # set by the command line (--prepatch: SHAP_PRE, "_prepatch")
LIVE = REPO / "writeup" / "generated" / "rehaul_live_numbers.tex"
HEADER = "% AUTO-GENERATED by writeup/make_rehaul_fi_live.py -- do not edit; re-run the script."
W_DAYS = 3_000
LAST_ORIGIN = pd.Timestamp("2024-04-05")  # \rhfipLastOrigin, checked below against the stored shares' span
VD_LAST = pd.Timestamp("2023-08-31")  # the volatility-demand feed's last day (Section 3)
YEAR_LAST = 2024
TREES = [("lgbm", "LightGBM", "#2a78d6", "o"), ("xgb", "XGBoost", "#eb6834", "s"), ("rf_skx", "Forest", "#1baf7a", "^")]
# macro stem, figure title, variables (None = the vol_demand bucket), live-from macro stem
GROUPS = [
    (
        "Stw",
        "StockTwits (attention, sentiment, count)",
        ["stocktwits_attention", "stocktwits_sentiment", "stocktwits_sentcount"],
        "StAtt",
    ),
    ("Vd", "Volatility demand (four series)", None, "Vd"),
    ("VixThree", "VIX3M", ["vix3m"], "VixThree"),
    ("Vvix", "VVIX", ["vvix"], "Vvix"),
    ("Vix", "VIX", ["vix"], "Vix"),
]


def live_from() -> dict[str, pd.Timestamp]:
    txt = LIVE.read_text(encoding="utf-8")
    out = {
        m.group(1): pd.Timestamp(m.group(2))
        for m in re.finditer(r"rhlv([A-Za-z]+)LiveYear\}\{\d{4}\}\s*%[^\n]*?live from (\d{4}-\d{2}-\d{2})", txt)
    }
    assert {"StAtt", "Vd", "VixThree", "Vvix", "Vix"} <= set(out), out
    return out


def trading_days() -> pd.DatetimeIndex:
    t = pd.to_datetime(pd.read_parquet(REPO / "data" / "ewstock_stats.parquet", columns=["endbartime"])["endbartime"])
    mins = t.dt.hour * 60 + t.dt.minute
    return pd.DatetimeIndex(sorted(t[(mins > 9 * 60 + 30) & (mins <= 16 * 60)].dt.normalize().unique()))


def fmt(x: float) -> str:
    return f"{x:.1f}"


def main() -> None:
    src = SHAP / "m1_by_year.csv"
    out_num = REPO / "writeup" / "generated" / f"rehaul_fi_live_numbers{TAG}.tex"
    out_fig = REPO / "writeup" / "figures" / "fi_pooled" / f"fi_live{TAG}.pdf"
    out_float = REPO / "writeup" / "generated" / f"rehaul_fi_live_fig{TAG}.tex"
    if TAG == "":
        assert "FOMC-PATCHED" in (SHAP / "RULE_pointer.txt").read_text(encoding="utf-8"), SHAP
        gate = (SHAP / "gate.txt").read_text(encoding="utf-8")
        for e in ("LightGBM", "XGBoost", "Random forest"):
            line = next(ln for ln in gate.splitlines() if ln.startswith(e))
            assert "walk rows 126/126; bit-equal 126/126" in line and "additivity pass 126/126" in line, line
    print(f"shares: {src.relative_to(REPO).as_posix()}")
    d = pd.read_csv(src)
    assert set(d["est"]) >= {k for k, *_ in TREES}, sorted(set(d["est"]))
    assert d["year"].min() == 2014 and d["year"].max() == YEAR_LAST
    lf = live_from()
    days = trading_days()
    macros: list[tuple[str, str, str]] = []
    series: dict[str, pd.DataFrame] = {}
    for stem, _, var, lstem in GROUPS:
        sub = d[d["bucket"] == "vol_demand"] if var is None else d[d["variable"].isin(var)]
        y = sub.groupby(["est", "year"])["share"].sum().mul(100).unstack("est")
        series[stem] = y
        start = lf[lstem]
        pre_years = list(range(2014, start.year))
        live_years = [2023] if stem == "Vd" else list(range(start.year + 1, YEAR_LAST + 1))
        pre = [y.loc[pre_years, k].mean() for k, *_ in TREES]
        macros += [
            (f"rhfil{stem}PreMin", fmt(min(pre)), f"mean yearly share 2014-{start.year - 1}, min over the trees (%)"),
            (f"rhfil{stem}PreMax", fmt(max(pre)), "the same, max over the trees (%)"),
            (f"rhfil{stem}PreYears", f"2014--{start.year - 1}", "pre-live years"),
            (f"rhfil{stem}LiveFrom", f"{start.day}~{start:%B}~{start.year}", "1-bar value average nonzero from"),
        ]
        if live_years:
            live = [y.loc[live_years, k].mean() for k, *_ in TREES]
            yrs = f"{live_years[0]}" if len(live_years) == 1 else f"{live_years[0]}--{live_years[-1]}"
            macros += [
                (f"rhfil{stem}LiveMin", fmt(min(live)), f"mean yearly share {yrs}, min over the trees (%)"),
                (f"rhfil{stem}LiveMax", fmt(max(live)), "the same, max over the trees (%)"),
                (f"rhfil{stem}LiveYears", yrs, "full live years"),
            ]
            print(f"{stem:8s} pre {min(pre):5.2f}-{max(pre):5.2f}  live {yrs:9s} {min(live):5.2f}-{max(live):5.2f}")
        end = VD_LAST if stem == "Vd" else LAST_ORIGIN
        n_live = int(((days >= start) & (days <= end)).sum())
        macros.append(
            (
                f"rhfil{stem}WinPct",
                f"{100.0 * n_live / W_DAYS:.0f}",
                f"% of the {W_DAYS:,}-day window holding live values at the last origin ({n_live} days)",
            )
        )
    macros += [
        ("rhfilWinDays", f"{W_DAYS:,}".replace(",", "{,}"), "training window, trading days"),
        ("rhfilLastOrigin", f"{LAST_ORIGIN.day}~{LAST_ORIGIN:%B}~{LAST_ORIGIN.year}", "last origin"),
    ]
    lines = [HEADER, "% \\rhfil... macros: the late-starting series' TreeSHAP shares in the years they are live."]
    lines += [f"\\providecommand{{\\{n}}}{{{v}}}  % {c}" for n, v, c in macros]
    out_num.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out_num.name}: {len(macros)} macros")

    plt.rcParams.update(
        {
            "font.size": 8,
            "axes.edgecolor": "#52514e",
            "xtick.color": "#52514e",
            "ytick.color": "#52514e",
            "font.family": "DejaVu Sans",
            "pdf.fonttype": 42,  # TrueType, as the other figures embed
        }
    )
    fig, axes = plt.subplots(2, 3, figsize=(7.2, 4.4), constrained_layout=True)
    for ax, (stem, title, _, lstem) in zip(axes.flat, GROUPS):
        y = series[stem]
        ax.axvspan(lf[lstem].year - 0.5, YEAR_LAST + 0.5, color="#eef3fb", zorder=0, lw=0)
        ends = []
        for key, label, color, marker in TREES:
            ax.plot(y.index, y[key], color=color, lw=1.6, marker=marker, ms=3, zorder=3)
            ends.append([y[key].iloc[-1], label])
        ymax = float(y.max().max()) * 1.15
        ax.set_ylim(0, ymax)
        ends.sort(key=lambda e: e[0])
        pos = [e[0] for e in ends]
        for i in range(1, len(pos)):
            pos[i] = max(pos[i], pos[i - 1] + 0.08 * ymax)
        for (_, label), yv in zip(ends, pos):
            ax.text(YEAR_LAST + 0.3, yv, label, va="center", fontsize=6, color="#0b0b0b")
        ax.set_title(title, fontsize=7.5, loc="left")
        ax.set_xlim(2013.5, 2026.2)
        ax.set_xticks(range(2014, 2025, 4))
        ax.grid(axis="y", color="#e6e5e0", lw=0.6)
        ax.spines[["top", "right"]].set_visible(False)
    axes.flat[-1].axis("off")
    axes[0, 0].set_ylabel("% of total mean |SHAP|")
    axes[1, 0].set_ylabel("% of total mean |SHAP|")
    out_fig.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_fig)
    caption = (
        "The late-starting series in the trees' attribution by calendar year: each group's share of the total mean "
        "absolute SHAP value, LightGBM, XGBoost and the random forest. Shaded: the years from the one in which the "
        "group's one-bar value average becomes nonzero under the late-start rule (Section~\\ref{sec:rh_predictors}); "
        "before it, the group's attribution comes from its availability averages, which record when the series "
        "prints, not what it prints. 2024 covers January to April."
    )
    out_float.write_text(
        "\n".join(
            [
                HEADER,
                f"\\ifdefined\\rhfilWinDays\\else\\input{{generated/rehaul_fi_live_numbers{TAG}}}\\fi",
                "\\begin{figure}[tbp]",
                "\\centering",
                f"\\includegraphics[width=\\linewidth]{{figures/fi_pooled/fi_live{TAG}.pdf}}",
                f"\\caption{{{caption}}}",
                "\\label{fig:rh_fi_live}",
                "\\end{figure}",
            ]
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {out_fig.name}, {out_float.name}")


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--prepatch", action="store_true", help="the pre-patch TreeSHAP study; writes the *_prepatch names")
    if ap.parse_args().prepatch:
        SHAP, TAG = SHAP_PRE, "_prepatch"
    main()
