def day(ts: pd.Timestamp) -> str:
    return f"{ts.day} {ts:%B %Y}"


def thousands(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def naive(s: pd.Series) -> pd.Series:
    t = pd.to_datetime(s)
    if t.dt.tz is not None:
        t = t.dt.tz_convert("America/New_York").dt.tz_localize(None)
    return t


def feed_ends() -> dict[str, Any]:
    """Vendor ends of the VIX family and of volatility demand, the splice's trading days and its agreement."""
    v = pd.read_parquet(DATA / "vix_and_voldemand.parquet")
    v["t"] = naive(v["endbartime"])
    last = {c: v.loc[v[c].notna(), "t"].max() for c in (*VIX_FAMILY, *VOLDEMAND)}
    vix_days = {last[c].normalize() for c in VIX_FAMILY}
    vd_days = {last[c].normalize() for c in VOLDEMAND}
    assert len(vix_days) == 1, f"VIX, VIX3M and VVIX end on different days: {last}"
    assert len(vd_days) == 1, (
        f"the volatility-demand series end on different days: {last}"
    )
    vix_last, vd_last = vix_days.pop(), vd_days.pop()

    end = pd.Timestamp(LD.VIX_SPLICE_END)
    core = pd.read_parquet(
        DATA / "core_stats.parquet", columns=["endbartime", "sumret2"]
    )
    core["t"] = naive(core["endbartime"])
    assert core["t"].max().normalize() == end.normalize(), (core["t"].max(), end)
    at16 = core[(core["t"].dt.strftime("%H:%M") == "16:00") & core["sumret2"].notna()][
        "t"
    ].dt.normalize()
    splice_days = int(((at16 > vix_last) & (at16 <= end)).sum())

    agree: dict[str, int] = {}
    first_overlap = []
    for c in VIX_FAMILY:
        ys = LD._free_feed_bar_ends(str(DATA / "free_feed" / f"{c}_1h_yahoo.parquet"))
        s = v.set_index("t")[c].dropna()
        j = s.to_frame("vendor").join(ys.rename("yahoo"), how="inner")
        assert len(j) > 0, c
        agree[c] = int(
            round(100 * float((np.abs(j["yahoo"] - j["vendor"]) < SAME_PRINT).mean()))
        )
        first_overlap.append(j.index.min())
    return {
        "vix_last": vix_last,
        "vd_last": vd_last,
        "end": end,
        "splice_days": splice_days,
        "agree": agree,
        "overlap_start": min(first_overlap),
    }


def fomc_file() -> dict[str, Any]:
    r = pd.read_parquet(
        DATA / "releases.parquet", columns=["endbartime", LD.FOMC_RAW_COL]
    )
    t = naive(r["endbartime"])
    last = t[pd.to_numeric(r[LD.FOMC_RAW_COL], errors="coerce").fillna(0.0) > 0].max()
    added = [pd.Timestamp(s) for s in LD.FOMC_MISSING_STATEMENTS]
    assert all(a > last for a in added), (last, added)
    assert all(a <= pd.Timestamp(LD.VIX_SPLICE_END) for a in added), added
    return {"last": last, "added": len(added)}


def frame_and_invalid() -> tuple[pd.DataFrame, dict[str, int]]:
    """The loader's frame (the design's data: invalid prints nulled, VIX spliced, FOMC calendar fixed) and the counts
    of its own null_invalid_prints call (on the calendar-open grid, before the dead-session drop)."""
    got: dict[str, int] = {}
    orig = LD.null_invalid_prints

    def capture(df: pd.DataFrame, verbose: bool = True) -> dict[str, int]:
        out = orig(df, verbose=verbose)
        got.update(out)
        return out

    LD.null_invalid_prints = capture  # type: ignore[assignment]
    try:
        df = LD.load_raw_data(str(DATA), allow_missing=True)
    finally:
        LD.null_invalid_prints = orig  # type: ignore[assignment]
    assert got, "load_raw_data did not null any print (NULL_INVALID_PRINTS off?)"
    return df, got


def design_columns(run: Path) -> tuple[list[str], int, dict[str, Any]]:
    """The value-average columns adj_<c>_ma_<k> of the full predictor set, the design log's no-observation count, and
    the design's rows (their number and the row and stamp of the last validation bar, to place them on the grid)."""
    fp = json.loads((run / "frozen_penalties.json").read_text(encoding="utf-8"))
    af = fp["designs"]["all_features"]
    cols = list(af["columns"])
    assert len(cols) == int(af["n_columns"]), len(cols)
    value_cols = [c for c in cols if re.fullmatch(r"adj_.+_ma_\d+", c)]
    fold = fp["info"]["folds"][-1]
    rows: dict[str, Any] = {
        "n": int(af["rows"]),
        "val_last_row": int(fold["val"][1]) - 1,
        "val_last": pd.Timestamp(fold["val_last"]),
    }
    # the trees of the final run read this design (md5-identical copy); their check places its first forecast row
    dc = fr.TREES_RUN / "design" / "design_check.json"
    key = f"w{fr.WINDOW_DAYS}"
    if (
        run == fr.LINEAR_RUN
        and dc.is_file()
        and key in (d := json.loads(dc.read_text(encoding="utf-8")))
    ):
        c = d[key]
        assert int(c["all_features_shape"][0]) == rows["n"], (
            c["all_features_shape"],
            rows,
        )
        rows["anchor_row"] = rows["n"] - int(c["n_oos"])
        rows["anchor_stamp"] = pd.Timestamp(c["oos_first"])
    info = json.loads((run / "run_info.json").read_text(encoding="utf-8"))
    lines = info["design_log_scale_lines"]["all_features"]
    hits = [
        m for ln in lines if (m := re.search(r"unobserved-neutral: (\d+) columns", ln))
    ]
    assert len(hits) == 1, lines
    return value_cols, int(hits[0].group(1)), rows


def unobserved_counts(
    df: pd.DataFrame,
    value_cols: list[str],
    eval_stamps: pd.DatetimeIndex,
    rows: dict[str, Any],
) -> tuple[int, int]:
    """Columns the no-observation rule acts on: on any row of the design (the regular-hours rows of the grid after the
    design's burn-in, placed by the last validation bar), and on the scored bars."""
    t = pd.to_datetime(df["t"])
    hhmm = t.dt.strftime("%H:%M")
    # the design's rows: the 13 regular-hours bars of every session but the NYSE early closes (executor
    # DROP_EARLY_CLOSE_SESSIONS: a time-of-day segment holds no early-close session), from the design's first row
    early = (
        t.dt.normalize()
        .isin(pd.to_datetime(list(LD.NYSE_EARLY_CLOSE_DATES)))
        .to_numpy()
    )
    assert EX.DROP_EARLY_CLOSE_SESSIONS
    rth_pos = np.flatnonzero(((hhmm >= RTH[0]) & (hhmm <= RTH[1])).to_numpy() & ~early)
    at = np.flatnonzero(t.iloc[rth_pos].to_numpy() == np.datetime64(rows["val_last"]))
    assert len(at) == 1, rows
    first = int(at[0]) - rows["val_last_row"]
    assert first >= 0 and len(rth_pos) - first == rows["n"], (first, len(rth_pos), rows)
    if (
        "anchor_row" in rows
    ):  # a second fixed point inside the pre-sample (the trees' design check of the same design)
        assert t.iloc[rth_pos[first + rows["anchor_row"]]] == rows["anchor_stamp"], rows
    rth = np.zeros(len(df), dtype=bool)
    rth[rth_pos[first:]] = True
    scored = t.isin(eval_stamps).to_numpy()
    assert int(scored.sum()) == len(eval_stamps), (int(scored.sum()), len(eval_stamps))
    assert not (scored & ~rth).any(), "a scored bar outside the design's rows"
    n_any, n_eval = 0, 0
    for name in value_cols:
        m = re.fullmatch(r"adj_(.+)_ma_(\d+)", name)
        assert m is not None, name
        c, k = m.group(1), int(m.group(2))
        obs = df[c].notna().astype(np.float64)
        a = obs.rolling(window=k, min_periods=1).mean().shift(1).to_numpy()
        none = (
            a < 0.5 / k
        )  # NaN (the first row) is not "none", as in executor.unobserved_neutral
        n_any += bool((none & rth).any())
        n_eval += bool((none & scored).any())
    return n_any, n_eval


def main() -> None:
    assert LD.NULL_INVALID_PRINTS and LD.SPLICE_VIX_FREE_FEED and LD.FOMC_CALENDAR_FIX
    assert EX.APPLY_FFILL_LIMIT and EX.FFILL_LIMIT is not None and EX.UNOBSERVED_NEUTRAL

    fe = feed_ends()
    fo = fomc_file()
    df, invalid = frame_and_invalid()

    run = fr.LINEAR_RUN
    value_cols, log_count, rows = design_columns(run)
    # the no-observation rule does not depend on the window: the robustness run's log must agree
    other = run.parent / ("w3500" if run.name == "w3000" else "w3000")
    if other.is_dir():
        assert design_columns(other)[1] == log_count, (run, other)
    fc = pd.read_parquet(run / "forecasts.parquet", columns=["date"])
    eval_stamps = pd.DatetimeIndex(
        sorted(
            set(pd.to_datetime(fc["date"])[pd.to_datetime(fc["date"]) >= fr.FIRST_DAY])
        )
    )
    n_any, n_eval = unobserved_counts(df, value_cols, eval_stamps, rows)
    assert n_any == log_count, (
        f"recomputed no-observation count {n_any} != the design log's {log_count}"
    )

    vals: dict[str, tuple[str, str]] = {
        "rhdsSampleEnd": (
            day(fe["end"]),
            "last day of the data (the end of the VIX splice, loading.VIX_SPLICE_END)",
        ),
        "rhdsVixVendorLast": (
            day(fe["vix_last"]),
            "last vendor print of VIX, VIX3M and VVIX (data/vix_and_voldemand.parquet)",
        ),
        "rhdsVixSpliceDays": (
            str(fe["splice_days"]),
            "trading days after it to the end of the data (16:00 futures print), spliced from Yahoo",
        ),
        "rhdsVixOverlapStart": (
            f"{fe['overlap_start']:%B %Y}",
            "first month of the stamps both the vendor file and the Yahoo hourly feed carry",
        ),
        "rhdsVixAgree": (
            str(fe["agree"]["vix"]),
            "percent of overlap stamps on which Yahoo and the vendor print the same VIX (to the second decimal)",
        ),
        "rhdsVixThreeMAgree": (str(fe["agree"]["vix3m"]), "the same, VIX3M"),
        "rhdsVvixAgree": (str(fe["agree"]["vvix"]), "the same, VVIX"),
        "rhdsVdLast": (
            day(fe["vd_last"]),
            "last print of the four volatility-demand series",
        ),
        "rhdsFfillCap": (
            str(EX.FFILL_LIMIT),
            "forward-fill cap of the exogenous series, intervals (executor.FFILL_LIMIT under APPLY_FFILL_LIMIT)",
        ),
        "rhdsFomcFileLast": (
            day(fo["last"]),
            "last scheduled FOMC statement in data/releases.parquet",
        ),
        "rhdsFomcAdded": (
            WORDS[fo["added"]],
            "scheduled statements added after it (loading.FOMC_MISSING_STATEMENTS), as a word",
        ),
        "rhdsInvalidPrints": (
            thousands(sum(invalid.values())),
            "prints set to missing by the domain rule (loading.null_invalid_prints)",
        ),
        "rhdsInvalidVolume": (
            thousands(int(invalid.get("sumvolume", 0))),
            "... of them zero futures volumes (sumvolume)",
        ),
        "rhdsValueCols": (
            str(len(value_cols)),
            "value-average columns adj_<c>_ma_<k> of the full predictor set (final design)",
        ),
        "rhdsUnobsCols": (
            str(log_count),
            "of them set to 0 by the no-observation rule on some row of the design (run_info.json design log)",
        ),
        "rhdsUnobsColsEval": (
            str(n_eval),
            "of them set to 0 on some scored bar from the first evaluation day (recomputed; gate: design log)",
        ),
        "rhdsEvalStart": (
            day(pd.Timestamp(eval_stamps.min()).normalize()),
            "first evaluation day of the final runs: the first scored bar's day (final_run.FIRST_DAY)",
        ),
    }
    bad = {k: (v[0], EXPECT[k]) for k, v in vals.items() if v[0] != EXPECT[k]}
    assert not bad, f"values differ from those checked on 2026-10-23: {bad}"

    lines = [
        HEAD,
        "% \\rhds... macros: the ends of the feeds and the data fixes of the final pooled design (Section 3, note E28).",
        f"% Run files: {Path(fr.rel(run)).as_posix()}; scored bars from {fr.FIRST_DAY.date()}.",
    ]
    for k, (v, note) in vals.items():
        lines.append(
            f"\\providecommand{{\\{k}}}{{}}\\renewcommand{{\\{k}}}{{{v}}}  % {note}"
        )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {fr.rel(OUT)}")
    for k, (v, _) in vals.items():
        print(f"  {k:22s} {v}")


if __name__ == "__main__":
    main()
