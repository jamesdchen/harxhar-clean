"""make_rehaul_disclosures.py -- the disclosure numbers of Section 3 (Data): the ends of the feeds and the data fixes of
the final pooled design (2026-10-23, note E28).

Writes writeup/generated/rehaul_disclosure_numbers.tex (the \\rhds... macros, definitions only).  The file is \\input by
writeup/rehaul/03_data.tex itself, at its top, not by the preamble of paper_rehaul.tex; the macros are used in
03_data.tex and in step 5 of writeup/rehaul/04_features.tex, which follows it.

User (2026-10-22, E28): "disclose the tails in the text"; the final design neutralizes the averages of an unobserved
series (src/backtest/executor.py UNOBSERVED_NEUTRAL).  The closing-interval models are not rerun (James, 2026-10-22):
the text discloses that they were fitted before the data fixes of 15 October 2026.

Every number is computed here from the data files, the code's constants and the final run's own files, never typed,
and asserted against the value checked on 2026-10-23 (EXPECT below), so a changed input stops the script instead of
moving a number in the paper silently.

INPUTS
  data/vix_and_voldemand.parquet         last vendor print of VIX / VIX3M / VVIX and of the four volatility-demand series
  data/free_feed/<s>_1h_yahoo.parquet    the Yahoo Finance hourly closes, keyed by their bar end exactly as the splice
                                         reads them (src.data.loading._free_feed_bar_ends)
  data/core_stats.parquet                the trading days of the splice: days with a futures print at the 16:00 stamp
  data/releases.parquet                  the last scheduled FOMC statement in the release file ("fomc release")
  src/data/loading.py                    NULL_INVALID_PRINTS, SPLICE_VIX_FREE_FEED, VIX_SPLICE_END, FOMC_CALENDAR_FIX,
                                         FOMC_MISSING_STATEMENTS; load_raw_data (the invalid-print counts, captured from
                                         its own null_invalid_prints call on the calendar-open grid)
  src/backtest/executor.py               FFILL_LIMIT, APPLY_FFILL_LIMIT, UNOBSERVED_NEUTRAL
  final_run.LINEAR_RUN                   results/window_sweep_2014start_2026-10-22/w3000: run_info.json (the design log line
                                         of the no-observation rule), frozen_penalties.json (the value-average columns of
                                         the full predictor set), forecasts.parquet (the scored bars from FIRST_DAY)

THE NO-OBSERVATION COUNT
  The run's design log ("[scale] unobserved-neutral: <n> columns, ...") counts the value-average columns adj_<c>_ma_<k>
  set to 0 on at least one row of the 13-bar design.  The count on the scored bars is not in the run's files, so it is
  recomputed here from the availability flags: <c>_avail_ma_<k> at a row is the mean of the flags notna(<c>) (recorded
  before any fill) over the k rows before it on the full 48-interval grid (rolling(k, min_periods=1).mean().shift(1),
  the executor's lag scope "global"), and the rule fires where it is below 0.5 / k (executor.unobserved_neutral).  Gate:
  on the design's rows (the regular-hours rows of the grid after its burn-in: frozen_penalties.json's row count, placed
  by the row and stamp of the last validation bar) the recomputed count equals the design log's count.

Run (from the repository root):  python writeup/make_rehaul_disclosures.py
"""

