"""The predictor-group ablations and augmented-HAR benchmarks (results/ablations_2014start_w3000/RULE.txt) for the paper.

Reads results/ablations_2014start_w3000/scores/ (experiments/ablate_score.py: metrics.csv, dm.csv, checks.json,
latestart_groups.csv) and writes
  writeup/generated/rehaul_ablation_numbers.tex   macros \\rhab... (letters only; no other generated file uses the prefix)
  writeup/generated/rehaul_ablation_table.tex     Table tab:rh_ablation
Nothing else is read or written.  A (class, arm) without forecasts prints "--" in the table and gets no macro.

Macros (C = Ols Ridge Lasso Enet Lgbm Xgb Rf; A = Full Har LoRm .. LoFomc AddRm .. AddFomc Shar Harq Lhar Sharql;
S = All (every bar 2014-2024), Close (16:00 bar 2014-2024), CloseLate (16:00 bar 2020-01-03 .. 2024-04-30)):
  \\rhab<C><A><S>Qlike          QLIKE (4 decimals)
  \\rhab<C><A><S>Mse            MSE x 1e10 (2 decimals)
  \\rhab<C><A><S>Pct            QLIKE change in percent against the arm's reference (lo_*: the full set; add_*, the
                                classical arms and the full set: the HAR benchmark of the same class), 1 decimal
  \\rhab<C><A><S>Dm, ...P        Diebold-Mariano statistic (2 decimals) and p-value against that reference (QLIKE)
  \\rhab<C>FullVsOls<B><S>Dm, ...P   the class's full set against the OLS augmented-HAR benchmark B (AddRm, Shar,
                                Harq, Lhar, Sharql)
  counts and words of the prose (\\rhabNClassesBeatAddRm, ...), the late-start dates (\\rhabLive<Series>...).
"""

