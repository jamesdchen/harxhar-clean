PRE_REF: set[tuple[str, str]] = set()


def fmt(x: float, dp: int) -> str:
    v = round(float(x), dp)
    if v == 0:
        v = 0.0
    return f"{'$-$' if v < 0 else ''}{abs(v):.{dp}f}"


def fmt_p(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def mac(name: str, value: str, comment: str = "") -> str:
    assert name.isalpha(), name
    return f"\\newcommand{{\\rhab{name}}}{{{value}}}" + (f"  % {comment}" if comment else "")


def date_tex(s: str) -> str:
    if not isinstance(s, str) or s[:2] not in ("19", "20"):
        return str(s)
    t = pd.Timestamp(s)
    return f"{t.day}~{t.strftime('%B')} {t.year}"


