"""The predictor-group ablations and augmented-HAR benchmarks (results/ablations_2014start_w3000/RULE.txt) for the paper.

Reads results/ablations_2014start_w3000/scores/ (experiments/ablate_score.py: metrics.csv, dm.csv, checks.json,
latestart_groups.csv) and writes
  writeup/generated/rehaul_ablation_numbers.tex   macros \\rhab... (letters only; no other generated file uses the prefix)
  writeup/generated/rehaul_ablation_table.tex     Table tab:rh_ablation
Nothing else is read or written.  A (class, arm) without forecasts prints "--" in the table and gets no macro.

Macros (C = Ols Ridge Lasso Enet Lgbm Xgb Rf; A = Full Har LoRm .. LoFomc AddRm .. AddFomc Shar Harq Lhar Sharql;
S = All (every bar 2014-2024), Close (16:00 bar 2014-2024), CloseLate (16:00 bar 2020-01-03 .. 2024-04-30)):
  \\rhab<C><A><S>Qlike          QLIKE (4 decimals)
  \\rhab<C><A><S>Mse            MSE x 1e10 (2 decimals)
  \\rhab<C><A><S>Pct            QLIKE change in percent against the arm's reference (lo_*: the full set; add_*, the
                                classical arms and the full set: the HAR benchmark of the same class), 1 decimal
  \\rhab<C><A><S>Dm, ...P        Diebold-Mariano statistic (2 decimals) and p-value against that reference (QLIKE)
  \\rhab<C>FullVsOls<B><S>Dm, ...P   the class's full set against the OLS augmented-HAR benchmark B (AddRm, Shar,
                                Harq, Lhar, Sharql)
  counts and words of the prose (\\rhabNClassesBeatAddRm, ...), the late-start dates (\\rhabLive<Series>...).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
sys.path.insert(0, str(REPO / "experiments"))
import ablate_arms as AA  # noqa: E402

RES = REPO / "results" / "ablations_2014start_w3000" / "scores"
GEN = ROOT / "generated"
OUT_NUM = GEN / "rehaul_ablation_numbers.tex"
OUT_TAB = GEN / "rehaul_ablation_table.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_ablations.py -- do not edit; re-run the script."
CLS = ["ols", "ridge", "lasso", "enet", "lgbm", "xgb", "rf"]
CLS_TEX = {"ols": "Ols", "ridge": "Ridge", "lasso": "Lasso", "enet": "Enet", "lgbm": "Lgbm", "xgb": "Xgb", "rf": "Rf"}
CLS_NAME = {
    "ols": "OLS",
    "ridge": "Ridge",
    "lasso": "Lasso",
    "enet": "Elastic net",
    "lgbm": "LightGBM",
    "xgb": "XGBoost",
    "rf": "Random forest",
}
G_TEX = {"rm": "Rm", "liq": "Liq", "ew": "Ew", "vw": "Vw", "sent": "Sent", "iv": "Iv", "vd": "Vd", "fomc": "Fomc"}
ARM_TEX = {"full": "Full", "har": "Har", "shar": "Shar", "harq": "Harq", "lhar": "Lhar", "sharql": "Sharql"}
ARM_TEX.update({f"lo_{g}": f"Lo{t}" for g, t in G_TEX.items()})
ARM_TEX.update({f"add_{g}": f"Add{t}" for g, t in G_TEX.items()})
SPAN_TEX = {"all": "All", "c16": "Close", "c16_2020": "CloseLate"}
WORDS = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}
SERIES_TEX = {
    "stocktwits_attention": "Attn",
    "stocktwits_sentiment": "Sent",
    "stocktwits_sentcount": "NSent",
    "vix": "Vix",
    "vvix": "Vvix",
    "vix3m": "Vixthreem",
    "voldemand_spx_open_and_close": "VdSpxOc",
    "voldemand_spx_open_only": "VdSpxO",
    "voldemand_all_open_and_close": "VdAllOc",
    "voldemand_all_open_only": "VdAllO",
}


def ref_arm(arm: str) -> str:
    return "full" if arm.startswith("lo_") else "har"


def fmt(x: float, dp: int) -> str:
    v = round(float(x), dp)
    if v == 0:
        v = 0.0
    return f"{'$-$' if v < 0 else ''}{abs(v):.{dp}f}"


def fmt_p(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def mac(name: str, value: str, comment: str = "") -> str:
    assert name.isalpha(), name
    return f"\\newcommand{{\\rhab{name}}}{{{value}}}" + (f"  % {comment}" if comment else "")


def date_tex(s: str) -> str:
    if not isinstance(s, str) or s[:2] not in ("19", "20"):
        return str(s)
    t = pd.Timestamp(s)
    return f"{t.day}~{t.strftime('%B')} {t.year}"


def main() -> int:
    M = pd.read_csv(RES / "metrics.csv")
    D = pd.read_csv(RES / "dm.csv")
    checks = json.loads((RES / "checks.json").read_text())
    assert checks["pass"], checks["fail"]
    have = set(zip(M["cls"], M["arm"]))
    q = M.set_index(["cls", "arm", "span"])
    dq = D[D["loss"] == "qlike"].set_index(["cls", "arm", "vs_cls", "vs_arm", "span"])
    lines = [HEAD, "% results/ablations_2014start_w3000 (RULE.txt): column-subset arms of the final 13-bar design,"]
    lines.append("% frozen hyperparameters, every bar scored as Table 1; DM on daily (average) QLIKE.")

    def pct(c: str, a: str, sp: str) -> float:
        r = ref_arm(a) if a != "full" else "har"
        return 100.0 * (q.loc[(c, a, sp), "qlike"] / q.loc[(c, r, sp), "qlike"] - 1.0)

    def dmref(c: str, a: str, sp: str) -> pd.Series | None:
        r = ref_arm(a) if a != "full" else "har"
        k = (c, a, c, r, sp)
        return dq.loc[k] if k in dq.index else None

    for c, a in sorted(have):
        for sp, st in SPAN_TEX.items():
            if (c, a, sp) not in q.index:
                continue
            nm = f"{CLS_TEX[c]}{ARM_TEX[a]}{st}"
            lines.append(mac(f"{nm}Qlike", fmt(q.loc[(c, a, sp), "qlike"], 4), f"QLIKE {c} {a} {sp}"))
            lines.append(mac(f"{nm}Mse", fmt(q.loc[(c, a, sp), "mse"] * 1e10, 2), f"MSE x 1e10 {c} {a} {sp}"))
            if a == "har":
                continue
            lines.append(
                mac(f"{nm}Pct", fmt(pct(c, a, sp), 1), f"QLIKE change % vs {ref_arm(a) if a != 'full' else 'har'}")
            )
            r = dmref(c, a, sp)
            if r is not None:
                lines.append(mac(f"{nm}Dm", fmt(r["dm"], 2), "DM vs the reference arm"))
                lines.append(mac(f"{nm}P", fmt_p(r["p"]), "p-value"))
    for c in CLS[1:]:
        for b in ("add_rm", "shar", "harq", "lhar", "sharql", "har"):
            for sp, st in SPAN_TEX.items():
                k = (c, "full", "ols", b, sp)
                if k in dq.index:
                    nm = f"{CLS_TEX[c]}FullVsOls{ARM_TEX[b]}{st}"
                    lines.append(mac(f"{nm}Dm", fmt(dq.loc[k, "dm"], 2), f"DM {c} full vs OLS {b}"))
                    lines.append(mac(f"{nm}P", fmt_p(dq.loc[k, "p"]), "p-value"))
    # counts for the prose (every bar)
    cls_pen_tree = [c for c in CLS[1:] if (c, "add_rm") in have]
    beat_addrm = [
        c
        for c in cls_pen_tree
        if (c, "full", c, "add_rm", "all") in dq.index
        and dq.loc[(c, "full", c, "add_rm", "all"), "dm"] < 0
        and dq.loc[(c, "full", c, "add_rm", "all"), "p"] < 0.05
    ]
    lines.append(mac("NClassesAddRm", WORDS[len(cls_pen_tree)], "classes with an add_rm arm"))
    lines.append(mac("NClassesBeatAddRm", WORDS[len(beat_addrm)], "full set beats its own add_rm, DM p < 0.05"))
    best = min(
        ("add_rm", "shar", "harq", "lhar", "sharql"),
        key=lambda b: q.loc[("ols", b, "all"), "qlike"] if ("ols", b, "all") in q.index else np.inf,
    )
    lines.append(
        mac(
            "BestOlsBench",
            {
                "add_rm": "HAR with the futures' realized moments",
                "shar": "SHAR",
                "harq": "HARQ",
                "lhar": "LHAR",
                "sharql": "SHAR + HARQ + LHAR",
            }[best],
            "lowest QLIKE OLS augmented HAR",
        )
    )
    # late series
    ls = RES / "latestart_groups.csv"
    if ls.is_file():
        T = pd.read_csv(ls)
        for _, r in T.iterrows():
            if r["series"] in SERIES_TEX:
                s = SERIES_TEX[r["series"]]
                lines.append(mac(f"Live{s}First", date_tex(str(r["first_print"])), f"first print {r['series']}"))
                lines.append(mac(f"Live{s}Last", date_tex(str(r["last_print"])), f"last print {r['series']}"))
                lines.append(mac(f"Live{s}FromKone", date_tex(str(r["live_from_k1"])), "first non-zeroed value, k = 1"))
                lines.append(mac(f"Live{s}FromKlast", date_tex(str(r["live_from_k3125"])), "the same, k = 3125"))
                lines.append(
                    mac(f"Live{s}SharePct", fmt(100 * r["share_live_max"], 0), "% of evaluation bars live, k = 1")
                )
    GEN.mkdir(parents=True, exist_ok=True)
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT_TAB.write_text(table(M, D, have), encoding="utf-8")
    print(f"wrote {OUT_NUM.name} ({len(lines)} lines) and {OUT_TAB.name}")
    return 0


def cell(q, dq, c: str, a: str, have: set) -> str:
    if (c, a) not in have:
        return "--"
    r = "full" if a.startswith("lo_") else "har"
    p = 100.0 * (q.loc[(c, a, "all"), "qlike"] / q.loc[(c, r, "all"), "qlike"] - 1.0)
    k = (c, a, c, r, "all")
    if k not in dq.index:
        return fmt(p, 1)
    return f"{fmt(p, 1)} ({fmt(dq.loc[k, 'dm'], 1)})"


def table(M: pd.DataFrame, D: pd.DataFrame, have: set) -> str:
    q = M.set_index(["cls", "arm", "span"])
    dq = D[D["loss"] == "qlike"].set_index(["cls", "arm", "vs_cls", "vs_arm", "span"])
    cols = CLS
    out = [
        HEAD,
        "% tab:rh_ablation: every bar 2014-01-02 .. 2024-04-30 (Table 1's scored bars); DM on daily average QLIKE.",
    ]
    out += [
        "\\begin{table}[htbp]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{threeparttable}",
        "\\caption{Predictor-group ablations and augmented-HAR benchmarks: change in QLIKE (\\%)}",
        "\\label{tab:rh_ablation}",
        f"\\begin{{tabular*}}{{\\linewidth}}{{@{{\\extracolsep{{\\fill}}}}l{'r' * len(cols)}@{{}}}}",
        "\\toprule",
        " & " + " & ".join(CLS_NAME[c] for c in cols) + " \\\\",
        "\\midrule",
        f"\\multicolumn{{{len(cols) + 1}}}{{@{{}}l}}{{\\textit{{A. Full set without the group, against the full set}}}} \\\\",
    ]
    for g in AA.GROUPS:
        out.append(f"{AA.GROUP_LABEL[g]} & " + " & ".join(cell(q, dq, c, f"lo_{g}", have) for c in cols) + " \\\\")
    out += [
        "\\addlinespace[4pt]",
        f"\\multicolumn{{{len(cols) + 1}}}{{@{{}}l}}{{\\textit{{B. HAR benchmark plus the group, against the HAR benchmark}}}} \\\\",
    ]
    for g in AA.GROUPS:
        out.append(f"{AA.GROUP_LABEL[g]} & " + " & ".join(cell(q, dq, c, f"add_{g}", have) for c in cols) + " \\\\")
    out += [
        "\\addlinespace[4pt]",
        f"\\multicolumn{{{len(cols) + 1}}}{{@{{}}l}}{{\\textit{{C. Classical HAR extensions, against the HAR benchmark}}}} \\\\",
    ]
    for b in ("shar", "harq", "lhar", "sharql"):
        out.append(f"{AA.CLASSICAL_LABEL[b]} & " + " & ".join(cell(q, dq, c, b, have) for c in cols) + " \\\\")
    out += [
        "\\addlinespace[4pt]",
        f"\\multicolumn{{{len(cols) + 1}}}{{@{{}}l}}{{\\textit{{D. Full set, against the HAR benchmark (Table~\\ref{{tab:rh_oos}})}}}} \\\\",
    ]
    out.append("All features & " + " & ".join(cell(q, dq, c, "full", have) for c in cols) + " \\\\")
    out += [
        "\\bottomrule",
        "\\end{tabular*}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        "\\item \\textit{Notes:} Each cell is the percentage change in QLIKE of a pooled intraday forecast against its"
        " reference, with the Diebold--Mariano statistic of the difference in parentheses (negative: the arm has the lower"
        " loss); every bar of Table~\\ref{tab:rh_oos} is scored (2014--2024) and the test runs on daily average QLIKE."
        " Panel A removes one predictor group (its series' trailing averages and availability shares) from the full"
        " set; Panel B adds one group to the HAR benchmark; Panel C adds the semivariances RS$^{+}$ and RS$^{-}$ of the"
        " last half hour (SHAR), the HARQ interaction of realized variance with the square root of realized quarticity,"
        " and the negative half-hour returns at every HAR horizon (LHAR), all from the same E-mini one-minute data."
        " Every model keeps the full set's frozen hyperparameters (the linear penalties chosen on the 2013 pre-sample"
        " fold for the full set; one configuration per tree method).  The random forest is run for Panel B and for the"
        " realized-moment group of Panel A only.  Series that start after the data enter as zero until the rolling"
        " window holds 3,000 days of their history (Section~\\ref{sec:rh_predictors}), so the implied-volatility,"
        " sentiment and volatility-demand rows measure those series only from the dates in the text.",
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    sys.exit(main())
