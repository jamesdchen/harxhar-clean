PRE_REF: set[tuple[str, str]] = set()


def fmt(x: float, dp: int) -> str:
    v = round(float(x), dp)
    if v == 0:
        v = 0.0
    return f"{'$-$' if v < 0 else ''}{abs(v):.{dp}f}"


def fmt_p(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def mac(name: str, value: str, comment: str = "") -> str:
    assert name.isalpha(), name
    return f"\\newcommand{{\\rhab{name}}}{{{value}}}" + (f"  % {comment}" if comment else "")


def date_tex(s: str) -> str:
    if not isinstance(s, str) or s[:2] not in ("19", "20"):
        return str(s)
    t = pd.Timestamp(s)
    return f"{t.day}~{t.strftime('%B')} {t.year}"


def main() -> int:
    M = pd.read_csv(RES / "metrics.csv")
    D = pd.read_csv(RES / "dm.csv")
    checks = json.loads((RES / "checks.json").read_text())
    assert checks["pass"], checks["fail"]
    have = set(zip(M["cls"], M["arm"]))
    PRE_REF.update(zip(D.loc[D["vs_arm"] == "full_pre", "cls"], D.loc[D["vs_arm"] == "full_pre", "arm"]))
    q = M.set_index(["cls", "arm", "span"])
    dq = D[D["loss"] == "qlike"].set_index(["cls", "arm", "vs_cls", "vs_arm", "span"])
    lines = [
        HEAD,
        f"% {RES.relative_to(REPO).as_posix()} ({'FOMC-patched panel, RULE.txt addendum D' if FIXED else 'pre-patch'})",
    ]
    lines.append("% results/ablations_2014start_w3000 (RULE.txt): column-subset arms of the final 13-bar design,")
    lines.append("% frozen hyperparameters, every bar scored as Table 1; DM on daily (average) QLIKE.")

    def pct(c: str, a: str, sp: str) -> float:
        r = ref_arm(a, c, have)
        return 100.0 * (q.loc[(c, a, sp), "qlike"] / q.loc[(c, r, sp), "qlike"] - 1.0)

    def dmref(c: str, a: str, sp: str) -> pd.Series | None:
        r = ref_arm(a, c, have)
        k = (c, a, c, r, sp)
        return dq.loc[k] if k in dq.index else None

    for c, a in sorted(have):
        if a not in ARM_TEX:  # addendum I: the ladder's rungs have their own generator (make_rehaul_beyond_ladder.py)
            continue
        for sp, st in SPAN_TEX.items():
            if (c, a, sp) not in q.index:
                continue
            nm = f"{CLS_TEX[c]}{ARM_TEX[a]}{st}"
            lines.append(mac(f"{nm}Qlike", fmt(q.loc[(c, a, sp), "qlike"], 4), f"QLIKE {c} {a} {sp}"))
            lines.append(mac(f"{nm}Mse", fmt(q.loc[(c, a, sp), "mse"] * 1e10, 2), f"MSE x 1e10 {c} {a} {sp}"))
            if a == "har":
                continue
            lines.append(mac(f"{nm}Pct", fmt(pct(c, a, sp), 1), f"QLIKE change % vs {ref_arm(a, c, have)}"))
            r = dmref(c, a, sp)
            if r is not None:
                lines.append(mac(f"{nm}Dm", fmt(r["dm"], 2), "DM vs the reference arm"))
                lines.append(mac(f"{nm}P", fmt_p(r["p"]), "p-value"))
    for sp, (st, g, _lab) in LIVE_TEX.items():  # live windows: the group's own arms and the full set
        for c in CLS[1:]:
            for a in ("full", f"lo_{g}", f"add_{g}", "har"):
                if (c, a, sp) not in q.index:
                    continue
                nm = f"{CLS_TEX[c]}{ARM_TEX[a]}{st}"
                lines.append(mac(f"{nm}Qlike", fmt(q.loc[(c, a, sp), "qlike"], 4), f"QLIKE {c} {a} {sp} (subsample)"))
                if a == "har":
                    continue
                lines.append(mac(f"{nm}Pct", fmt(pct(c, a, sp), 1), "QLIKE change % vs the reference (subsample)"))
                r = dmref(c, a, sp)
                if r is not None:
                    lines.append(mac(f"{nm}Dm", fmt(r["dm"], 2), "DM vs the reference arm (subsample)"))
                    lines.append(mac(f"{nm}P", fmt_p(r["p"]), "p-value"))
    for key, w in checks.get("live_windows", {}).items():
        t = LIVE_TEX[f"live_{key}"][0]
        lines.append(mac(f"{t}Start", date_tex(w["start"]), f"first bar of the live window {key}"))
        lines.append(mac(f"{t}End", date_tex(w["end"]), f"last bar of the live window {key}"))
        lines.append(mac(f"{t}Days", f"{w['days']:,}".replace(",", "{,}"), f"trading days of the live window {key}"))
    # the full set against the class's own HAR + realized moments / HAR + FOMC (sign of the stored test flipped)
    for c in CLS[1:]:
        for ga, gt in (("add_rm", "AddRm"), ("add_fomc", "AddFomc")):
            for sp, st in SPAN_TEX.items():
                k = (c, ga, c, "full", sp)
                if k in dq.index:
                    nm = f"{CLS_TEX[c]}FullVs{gt}{st}"
                    pc = 100.0 * (q.loc[(c, "full", sp), "qlike"] / q.loc[(c, ga, sp), "qlike"] - 1.0)
                    lines.append(mac(f"{nm}Pct", fmt(pc, 1), f"QLIKE change % {c} full vs own {ga}"))
                    lines.append(mac(f"{nm}Dm", fmt(-dq.loc[k, "dm"], 2), f"DM full vs own {ga}"))
                    lines.append(mac(f"{nm}P", fmt_p(dq.loc[k, "p"]), "p-value"))
    lines += combo_macros(q, dq, checks)
    lines += beyond_macros(q, dq)
    for c in CLS[1:]:
        for b in ("add_rm", "shar", "harq", "lhar", "sharql", "har"):
            for sp, st in SPAN_TEX.items():
                k = (c, "full", "ols", b, sp)
                if k in dq.index:
                    nm = f"{CLS_TEX[c]}FullVsOls{ARM_TEX[b]}{st}"
                    lines.append(mac(f"{nm}Dm", fmt(dq.loc[k, "dm"], 2), f"DM {c} full vs OLS {b}"))
                    lines.append(mac(f"{nm}P", fmt_p(dq.loc[k, "p"]), "p-value"))
    # counts for the prose (every bar)
    cls_pen_tree = [c for c in CLS[1:] if (c, "add_rm") in have]
    # the stored test is add_rm against the full set: the full set lower <=> DM > 0 there
    beat_addrm = [
        c
        for c in cls_pen_tree
        if (c, "add_rm", c, "full", "all") in dq.index
        and dq.loc[(c, "add_rm", c, "full", "all"), "dm"] > 0
        and dq.loc[(c, "add_rm", c, "full", "all"), "p"] < 0.05
    ]
    lines.append(mac("NClassesAddRm", WORDS[len(cls_pen_tree)], "classes with an add_rm arm"))
    lines.append(mac("NClassesBeatAddRm", WORDS[len(beat_addrm)], "full set beats its own add_rm, DM p < 0.05"))
    # 2026-10-26 (integration, RESULTS / FRONT): the same count at the 16:00 bar (span c16), as a word
    beat_addrm_close = [
        c
        for c in cls_pen_tree
        if (c, "add_rm", c, "full", "c16") in dq.index
        and dq.loc[(c, "add_rm", c, "full", "c16"), "dm"] > 0
        and dq.loc[(c, "add_rm", c, "full", "c16"), "p"] < 0.05
    ]
    lines.append(
        mac("NClassesBeatAddRmClose", WORDS[len(beat_addrm_close)], "16:00: full set beats its own add_rm, DM p < 0.05")
    )
    # 2026-10-26 (integration, VI): the trees' FOMC gain share: the add-FOMC arm's QLIKE change over the full set's
    # (both against the class's HAR arm, every bar), in percent
    tree_share = [
        100.0 * pct(c, "add_fomc", "all") / pct(c, "full", "all")
        for c in ("lgbm", "xgb", "rf")
        if (c, "add_fomc", "all") in q.index and (c, "full", "all") in q.index
    ]
    assert len(tree_share) == 3, "the add-FOMC arm of every tree class"
    lines.append(
        mac("TreeFomcGainShareMin", fmt(min(tree_share), 0), "trees: add-FOMC change / full-set change, %, lowest")
    )
    lines.append(mac("TreeFomcGainShareMax", fmt(max(tree_share), 0), "trees: the same, highest"))
    lines += consolidated_macros(q, dq, have)
    best = min(
        ("add_rm", "shar", "harq", "lhar", "sharql"),
        key=lambda b: q.loc[("ols", b, "all"), "qlike"] if ("ols", b, "all") in q.index else np.inf,
    )
    lines.append(
        mac(
            "BestOlsBench",
            {
                "add_rm": "HAR with the futures' realized moments",
                "shar": "SHAR",
                "harq": "HARQ",
                "lhar": "LHAR",
                "sharql": "SHAR + HARQ + LHAR",
            }[best],
            "lowest QLIKE OLS augmented HAR",
        )
    )
    # late series
    ls = RES / "latestart_groups.csv"
    if ls.is_file():
        T = pd.read_csv(ls)
        for _, r in T.iterrows():
            if r["series"] in SERIES_TEX:
                s = SERIES_TEX[r["series"]]
                lines.append(mac(f"Live{s}First", date_tex(str(r["first_print"])), f"first print {r['series']}"))
                lines.append(mac(f"Live{s}Last", date_tex(str(r["last_print"])), f"last print {r['series']}"))
                lines.append(mac(f"Live{s}FromKone", date_tex(str(r["live_from_k1"])), "first non-zeroed value, k = 1"))
                lines.append(mac(f"Live{s}FromKlast", date_tex(str(r["live_from_k3125"])), "the same, k = 3125"))
                lines.append(
                    mac(f"Live{s}SharePct", fmt(100 * r["share_live_max"], 0), "% of evaluation bars live, k = 1")
                )
    names = [ln.split("}", 1)[0] for ln in lines if ln.startswith("\\newcommand")]
    assert len(names) > 100, len(names)
    dup = sorted({n for n in names if names.count(n) > 1})
    assert not dup, f"macros defined twice: {dup[:5]}"
    GEN.mkdir(parents=True, exist_ok=True)
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT_TAB.write_text(table(M, D, have), encoding="utf-8")
    if any(a in BEYOND for _c, a in have):
        OUT_BEYOND.write_text(beyond_table(q, dq, have), encoding="utf-8")
    print(f"wrote {OUT_NUM.name} ({len(lines)} lines) and {OUT_TAB.name}")
    return 0


def combo_macros(q, dq, checks: dict) -> list[str]:
    """Addendum F: add_rm_fomc against the full set (sign flipped: the full set's change), the class's HAR and the OLS
    HAR; the full set against the OLS add_rm_fomc; every bar, ORDINARY and EVENT days, the 16:00 spans."""
    out: list[str] = []
    lab = "add_rm_fomc (requested by the author after the channel results; not pre-registered)"
    dt = checks.get("day_types")
    if dt:
        out.append(mac("NEventDays", str(dt["event_days"]), "EVENT days: scheduled FOMC statement days scored"))
        out.append(mac("NOrdinaryDays", f"{dt['ordinary_days']:,}".replace(",", "{,}"), "ORDINARY days scored"))

    def put(nm: str, a: tuple, b: tuple, sp: str, flip: bool, what: str) -> None:
        # a against b: QLIKE change of a vs b in %, DM of a vs b (flip: the stored test is b vs a)
        k = (*b, *a, sp) if flip else (*a, *b, sp)
        if (*a, sp) not in q.index or (*b, sp) not in q.index or k not in dq.index:
            return
        pc = 100.0 * (q.loc[(*a, sp), "qlike"] / q.loc[(*b, sp), "qlike"] - 1.0)
        out.append(mac(f"{nm}Pct", fmt(pc, 1), f"QLIKE change % {what}, {sp}; {lab}"))
        out.append(mac(f"{nm}Dm", fmt(-dq.loc[k, "dm"] if flip else dq.loc[k, "dm"], 2), f"DM {what}"))
        out.append(mac(f"{nm}P", fmt_p(dq.loc[k, "p"]), "p-value"))

    for c in CLS:
        t = CLS_TEX[c]
        for sp, st in COMBO_SPAN_TEX.items():
            if sp in ("ord", "ev") and (c, COMBO, sp) in q.index:  # all / 16:00 spans: the general loop's
                out.append(
                    mac(f"{t}AddRmFomc{st}Qlike", fmt(q.loc[(c, COMBO, sp), "qlike"], 4), f"QLIKE {c} {COMBO} {sp}")
                )
            if c == "ols":
                put(f"OlsAddRmFomcVsHar{st}", ("ols", COMBO), ("ols", "har"), sp, False, "OLS add_rm_fomc vs OLS HAR")
                continue
            put(f"{t}FullVsAddRmFomc{st}", (c, "full"), (c, COMBO), sp, True, f"{c} full vs own add_rm_fomc")
            put(f"{t}AddRmFomcVsHar{st}", (c, COMBO), (c, "har"), sp, False, f"{c} add_rm_fomc vs own HAR")
            put(f"{t}AddRmFomcVsOlsHar{st}", (c, COMBO), ("ols", "har"), sp, False, f"{c} add_rm_fomc vs OLS HAR")
            put(f"{t}FullVsOlsAddRmFomc{st}", (c, "full"), ("ols", COMBO), sp, False, f"{c} full vs OLS add_rm_fomc")
            if sp in ("ord", "ev"):  # context: the full set against its own HAR on the same days
                put(f"{t}FullVsHar{st}", (c, "full"), (c, "har"), sp, False, f"{c} full vs own HAR")
    return out


BEYOND_CLS = ("ridge", "lasso", "enet", "lgbm", "xgb")
LIN = ("ridge", "lasso", "enet")


def gain(q, c: str, a: str, b: str, sp: str) -> float:
    """QLIKE change of arm a against arm b, % of b's QLIKE (negative: a lower)."""
    return 100.0 * (q.loc[(c, a, sp), "qlike"] / q.loc[(c, b, sp), "qlike"] - 1.0)


def overlap(q, c: str, sp: str) -> tuple[float, float, float] | None:
    """(iii): the sum of the six (base + g vs base) changes, the full set's change against the base, their ratio."""
    if any((c, a, sp) not in q.index for a in (*BEYOND, COMBO, "full")):
        return None
    s = sum(gain(q, c, a, COMBO, sp) for a in BEYOND)
    f = gain(q, c, "full", COMBO, sp)
    return s, f, s / f


def beyond_macros(q, dq) -> list[str]:
    """Addendum G: (i) base + g vs the base on ORDINARY / EVENT days (every bar and 16:00: the general loop, whose
    reference for these arms is the base); (ii) the full set vs base + g; (iii) the overlap ratio."""
    out: list[str] = []
    lab = "requested by the author after the HAR + RM + FOMC results; not pre-registered"
    for c in BEYOND_CLS:
        t = CLS_TEX[c]
        for a in BEYOND:
            nm = f"{t}{ARM_TEX[a]}"
            for sp, st in COMBO_SPAN_TEX.items():
                if (c, a, sp) not in q.index:
                    continue
                if sp in ("ord", "ev"):
                    out.append(mac(f"{nm}{st}Qlike", fmt(q.loc[(c, a, sp), "qlike"], 4), f"QLIKE {c} {a} {sp}"))
                    k = (c, a, c, COMBO, sp)
                    if k in dq.index:
                        out.append(mac(f"{nm}{st}Pct", fmt(gain(q, c, a, COMBO, sp), 1), f"% vs base, {lab}"))
                        out.append(mac(f"{nm}{st}Dm", fmt(dq.loc[k, "dm"], 2), "DM vs the base add_rm_fomc"))
                        out.append(mac(f"{nm}{st}P", fmt_p(dq.loc[k, "p"]), "p-value"))
                k2 = (c, a, c, "full", sp)  # (ii) the full set vs base + g (stored as base + g vs full: flipped)
                if k2 in dq.index and (c, "full", sp) in q.index:
                    out.append(
                        mac(f"{t}FullVs{ARM_TEX[a]}{st}Pct", fmt(gain(q, c, "full", a, sp), 1), f"% full vs {a}")
                    )
                    out.append(mac(f"{t}FullVs{ARM_TEX[a]}{st}Dm", fmt(-dq.loc[k2, "dm"], 2), f"DM full vs {a}"))
                    out.append(mac(f"{t}FullVs{ARM_TEX[a]}{st}P", fmt_p(dq.loc[k2, "p"]), "p-value"))
        for sp, st in (("all", "All"), ("ord", "Ord"), ("ev", "Ev")):
            o = overlap(q, c, sp)
            if o is not None:
                out.append(mac(f"{t}BeyondSum{st}Pct", fmt(o[0], 1), f"sum of the six base + g changes, {sp}"))
                out.append(mac(f"{t}BeyondFull{st}Pct", fmt(o[1], 1), f"full vs base, {sp}"))
                # (iii) only where the full set's change against the base is significant (DM p < 0.05): the linear
                # full sets and the trees' EVENT days gain about nothing against the base, so the ratio means nothing
                kf = (c, COMBO, c, "full", sp)
                sig = kf in dq.index and dq.loc[kf, "p"] < 0.05
                out.append(
                    mac(
                        f"{t}BeyondRatio{st}",
                        f"{o[2]:.2f}" if sig else "--",
                        "(iii) sum of the six / full vs base" + ("" if sig else " (full vs base not significant)"),
                    )
                )
    return out


