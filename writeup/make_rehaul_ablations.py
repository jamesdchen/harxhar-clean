    dq = D[D["loss"] == "qlike"].set_index(["cls", "arm", "vs_cls", "vs_arm", "span"])
    cols = CLS
    out = [
        HEAD,
        "% tab:rh_ablation: every bar 2014-01-02 .. 2024-04-30 (Table 1's scored bars); DM on daily average QLIKE.",
    ]
    out += [
        "\\begin{table}[htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{1.5pt}",
        "\\begin{threeparttable}",
        "\\caption{Predictor-group ablations and augmented-HAR benchmarks: change in QLIKE (\\%)}",
        "\\label{tab:rh_ablation}",
        f"\\begin{{tabular*}}{{\\linewidth}}{{@{{\\extracolsep{{\\fill}}}}l{'r' * len(cols)}@{{}}}}",
        "\\toprule",
        " & " + " & ".join(CLS_NAME[c] for c in cols) + " \\\\",
        "\\midrule",
        f"\\multicolumn{{{len(cols) + 1}}}{{@{{}}l}}{{\\textit{{A. Full set without the group, against the full set}}}} \\\\",
    ]
