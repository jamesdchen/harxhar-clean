def consolidated_macros(q, dq, have: set) -> list[str]:
    """2026-10-27 (author: consolidated Section 6.2), every bar: (1) the base share 100 (L_har - L_base) /
    (L_har - L_full), base = HAR + RM + FOMC, L_har = the class's own HAR (the reference of \\rhab<C>FullAllPct and
    \\rhab<C>AddRmFomcVsHarAllPct), by class and its ranges; (2) the smallest p-value of the linear full sets against
    their own base; (3) Panel A of tab:rh_ablation: the ranges of the FOMC and RM removals over the classes with the
    row, the smallest RM-removal DM, and the largest absolute change from removing any other group."""
    sp = "all"
    out = [
        "% 2026-10-27 (author: consolidated Section 6.2), every bar.  <C>BaseShareAll = 100 (L_har - L_base) /",
        "% (L_har - L_full), base = HAR + RM + FOMC, L_har = own HAR (the reference of <C>FullAllPct and",
        "% <C>AddRmFomcVsHarAllPct; above 100: the full set worse than the base); PMin: over ridge, lasso, enet;",
        "% Lo*: Panel A of tab:rh_ablation (removal vs the full set, as tabulated) over the classes with the row;",
        "% LoOtherAllMaxAbs: the largest |% change| from removing any group other than RM and FOMC, any class.",
    ]
    share: dict[str, float] = {}
    for c in CLS[1:]:
        assert ref_arm("full", c, have) == "har", c  # combo_macros: AddRmFomcVsHar is against (c, "har") as well
        lr, lb, lf = (q.loc[(c, a, sp), "qlike"] for a in ("har", COMBO, "full"))
        share[c] = 100.0 * (lr - lb) / (lr - lf)
        out.append(mac(f"{CLS_TEX[c]}BaseShareAll", fmt(share[c], 0), "% of the full set's gain over own HAR in base"))
    for nm, cs in (("Lin", LIN), ("Tree", TREE), ("", tuple(share))):
        v = [share[c] for c in cs]
        out.append(mac(f"BaseShare{nm}Min", fmt(min(v), 0), f"lowest base share over {', '.join(cs)}"))
        out.append(mac(f"BaseShare{nm}Max", fmt(max(v), 0), f"highest base share over {', '.join(cs)}"))
    for s, st in (("all", "All"), ("ord", "Ord")):
        ps = [dq.loc[(c, COMBO, c, "full", s), "p"] for c in LIN]
        out.append(mac(f"LinFullVsAddRmFomc{st}PMin", fmt_p(min(ps)), f"smallest p, linear full vs own base, {s}"))

    def panel_a(g: str) -> dict[str, tuple[float, float]]:
        # (class -> (% change, DM)) of lo_g against its Panel A reference (ref_arm: full, or full_pre for PRE_TREE)
        res = {}
        for c in CLS:
            a = f"lo_{g}"
            r = ref_arm(a, c, have)
            if (c, a) not in have or (c, a, sp) not in q.index or (c, r, sp) not in q.index:
                continue
            pc = 100.0 * (q.loc[(c, a, sp), "qlike"] / q.loc[(c, r, sp), "qlike"] - 1.0)
            k = (c, a, c, r, sp)
            res[c] = (pc, dq.loc[k, "dm"] if k in dq.index else np.nan)
        return res

    for g in ("fomc", "rm"):
        pa = panel_a(g)
        assert pa, g
        pcs = [x[0] for x in pa.values()]
        out.append(mac(f"Lo{G_TEX[g]}AllPctMin", fmt(min(pcs), 1), f"lowest Panel A {g} removal %, {', '.join(pa)}"))
        out.append(mac(f"Lo{G_TEX[g]}AllPctMax", fmt(max(pcs), 1), f"highest Panel A {g} removal %, {', '.join(pa)}"))
        if g == "rm":
            dms = [x[1] for x in pa.values()]
            assert not any(np.isnan(dms)), dms
            out.append(mac("LoRmAllDmMin", fmt(min(dms), 2), f"smallest DM of the rm removals, {', '.join(pa)}"))
    other = [abs(x[0]) for g in AA.GROUPS if g not in ("rm", "fomc") for x in panel_a(g).values()]
    assert other
    out.append(mac("LoOtherAllMaxAbs", fmt(max(other), 1), "largest |%| removing a group other than rm, fomc"))
    return out


def beyond_table(q, dq, have: set) -> str:
    """tab:rh_ablation_beyond: base + g against the base, the full set against base + g, and the overlap."""
    spans = (("all", "Every bar"), ("ord", "Ordinary days"))
    cols = [(sp, c) for sp, _l in spans for c in ("lin", "lgbm", "xgb")]

    def one(c: str, a: str, b: str, sp: str, flip: bool) -> str:
        k = (c, b, c, a, sp) if flip else (c, a, c, b, sp)
        if (c, a, sp) not in q.index or (c, b, sp) not in q.index or k not in dq.index:
            return "--"
        dm = -dq.loc[k, "dm"] if flip else dq.loc[k, "dm"]
        return f"{fmt(gain(q, c, a, b, sp), 1)} ({fmt(dm, 1)})"

    def rng(a: str, b: str, sp: str) -> str:
        v = [gain(q, c, a, b, sp) for c in LIN if (c, a, sp) in q.index and (c, b, sp) in q.index]
        if not v:
            return "--"
        lo, hi = min(v), max(v)
        return fmt(lo, 1) if fmt(lo, 1) == fmt(hi, 1) else f"{fmt(lo, 1)} to {fmt(hi, 1)}"

    def row(label: str, a: str, b: str, flip: bool = False) -> str:
        cells = []
        for sp, c in cols:
            cells.append(rng(a, b, sp) if c == "lin" else one(c, a, b, sp, flip))
        return f"{label} & " + " & ".join(cells) + " \\\\"

    out = [
        HEAD,
        "% tab:rh_ablation_beyond (RULE.txt addendum G; requested by the author after the HAR + RM + FOMC results).",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\begin{threeparttable}",
        "\\caption{Beyond HAR, realized moments and the FOMC calendar: change in QLIKE (\\%)}",
        "\\label{tab:rh_ablation_beyond}",
        "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrr@{}}",
        "\\toprule",
        " & \\multicolumn{3}{c}{Every bar} & \\multicolumn{3}{c}{Ordinary days} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(l){5-7}",
        " & Linear & LightGBM & XGBoost & Linear & LightGBM & XGBoost \\\\",
        "\\midrule",
        "\\multicolumn{7}{@{}l}{\\textit{A. HAR + RM + FOMC plus the group, against HAR + RM + FOMC}} \\\\",
    ]
    for a, g in BEYOND.items():
        out.append(row(AA.GROUP_LABEL[g], a, COMBO))
    out.append(row("All six (the full set)", "full", COMBO, flip=True))
    sums = []
    for sp, c in cols:
        if c == "lin":
            v = [overlap(q, x, sp) for x in LIN]
            v2 = [x for x in v if x is not None]
            sums.append(
                "--"
                if not v2
                else (lambda lo, hi: lo if lo == hi else f"{lo} to {hi}")(
                    fmt(min(x[0] for x in v2), 1), fmt(max(x[0] for x in v2), 1)
                )
            )
        else:
            o = overlap(q, c, sp)
            sums.append("--" if o is None else f"{fmt(o[0], 1)} [{o[2]:.2f}]")
    out.append("Sum of the six rows [ratio to the full set] & " + " & ".join(sums) + " \\\\")
    out += [
        "\\addlinespace[4pt]",
        "\\multicolumn{7}{@{}l}{\\textit{B. Full set against HAR + RM + FOMC plus the group}} \\\\",
    ]
    for a, g in BEYOND.items():
        out.append(row(AA.GROUP_LABEL[g], "full", a, flip=True))
    out += [
        "\\bottomrule",
        "\\end{tabular*}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        "\\item \\textit{Notes:} Requested by the author after the results against HAR + RM + FOMC (Table~\\ref{tab:rh_ablation},"
        " Panel~D), not part of the pre-specified design.  Base: the HAR benchmark set plus the futures' realized moments"
        " (RM) and the FOMC calendar (132 columns); each row of Panel~A adds one remaining group to it, Panel~B sets"
        " the full set against that model.  Every model keeps the full set's frozen hyperparameters (FOMC-patched"
        " design); the random forest is not run.  Cells: percentage change in QLIKE with the Diebold--Mariano"
        " statistic in parentheses (negative: the first model has the lower loss; daily average QLIKE); Linear: the"
        " range over ridge, lasso and elastic net.  Ordinary days exclude the \\rhabNEventDays{} scheduled FOMC"
        " statement days.  The bracket (trees) is the sum of the six Panel~A changes divided by the full set's change:"
        " above one, the groups' gains overlap; below one, they complement each other (the linear full sets gain about"
        " nothing against the base, so no ratio is shown for them).",
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
    ]
    return "\n".join(out) + "\n"


def cell(q, dq, c: str, a: str, have: set, sp: str = "all") -> str:
    if (c, a) not in have or (c, a, sp) not in q.index:
        return "--"
    r = ref_arm(a, c, have)
    if (c, r, sp) not in q.index:
        return "--"
    p = 100.0 * (q.loc[(c, a, sp), "qlike"] / q.loc[(c, r, sp), "qlike"] - 1.0)
    k = (c, a, c, r, sp)
    mark = "\\textsuperscript{\\dag}" if r == "full_pre" else ""
    if k not in dq.index:
        return fmt(p, 1) + mark
    return f"{fmt(p, 1)} ({fmt(dq.loc[k, 'dm'], 1)}){mark}"


def full_vs_add(q, dq, c: str, have: set, ga: str = "add_rm", sp: str = "all") -> str:
    """The class's full set against its own HAR + a group (add_rm, add_fomc; the stored test is add vs full: sign
    flipped)."""
    k = (c, ga, c, "full", sp)
    if (c, "full") not in have or (c, ga) not in have or k not in dq.index:
        return "--"
    p = 100.0 * (q.loc[(c, "full", sp), "qlike"] / q.loc[(c, ga, sp), "qlike"] - 1.0)
    return f"{fmt(p, 1)} ({fmt(-dq.loc[k, 'dm'], 1)})"


