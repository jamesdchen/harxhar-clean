"""Prose macros for the variable importance of the pooled intraday linear models at a monthly re-estimation cadence
(note E19).

Reads results/rehaul_fi_pooled_2026-10-19/{48,13}/summary.json (experiments/rehaul_fi_pooled_compute.py) and writes

  writeup/generated/rehaul_fi_pooled_numbers.tex   \\rhfpAll... (all 48 intervals) and \\rhfpRth... (13 regular-hours
                                                    bars), the counterparts of the \\rhfi... macros of the bullets in
                                                    writeup/rehaul/08_feature_importance.tex

Run:  python writeup/make_rehaul_fi_pooled.py [--res DIR]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "writeup"))
from make_rehaul_fi import date_tex, f, grp, pct, rel, word  # noqa: E402

GEN = ROOT / "writeup" / "generated"
RES = ROOT / "results" / "rehaul_fi_pooled_2026-10-19"
SAMPLES = {"48": "All", "13": "Rth"}
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_fi_pooled.py -- do not edit; re-run the script.\n"
NTH = ("One", "Two", "Three")


def num(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def macros(S: dict, tag: str) -> list[tuple[str, str, str]]:
    L, R = S["lasso"], S["ridge"]
    m: list[tuple[str, str, str]] = []

    def put(name: str, val, c: str = "") -> None:
        m.append((f"rhfp{tag}{name}", str(val), c))

    put("Window", num(S["window"]), "W, intervals")
    put("NRefits", num(S["n_refits"]), "K, one re-estimation a month")
    put("First", date_tex(S["first"]), "first re-estimation")
    put("P", num(S["p"]), "predictors")
    put("NUnits", num(S["n_units"]), "predictor groups")
    put("NExog", num(S["n_exog"]), "exogenous series")
    put("NBuckets", word(S["n_buckets"]), "categories")
    put("LassoAlpha", f"{L['alpha']:g}", "frozen pre-sample lambda")
    put("RidgeAlpha", f"{R['alpha']:g}", "frozen pre-sample lambda")
    put("BackbonePf", f"{S['r_bb']:g}", "omega on the HAR benchmark block")
    # lasso, over the sample
    put("LassoNzMed", f"{L['total_nonzero_median']:g}")
    put("LassoNzMin", L["total_nonzero_min"])
    put("LassoNzMax", L["total_nonzero_max"])
    put("LassoExogNzMed", f"{L['exog_nonzero_median']:g}")
    put("LassoColsEver", L["cols_ever"])
    put("LassoColsMajority", L["cols_majority"])
    put("LassoColsAlways", L["cols_always"])
    put("LassoExogEver", L["exog_series_ever"])
    put("LassoExogMajority", L["exog_series_majority"])
    put("LassoExogAlways", L["exog_series_always"])
    put("LassoAlwaysList", ", ".join(grp(u, cap=False) for u in L["exog_always_list"]) or "none")
    put("LassoBackboneShare", pct(L["backbone_share_median"]), "% of sum |beta|, median re-estimation")
    put("LassoW", f(L["W"]), "Kendall's W")
    put("LassoProbeRate", pct(L["probe_rate"], 0))
    put("LassoColsAboveProbe", L["cols_above_probe_rate"])
    put("LassoSeriesAboveProbe", L["series_above_probe_rate"])
    put("NProbe", L["probe_n"])
    for i, q in enumerate(("", "Levels", "Binary")):
        put(f"LassoProbeSel{q}", L["probe_nonzero"][i])
    # ridge
    for i, (u, v) in enumerate(R["top_share"][:3]):
        put(f"RidgeTop{NTH[i]}", grp(u, cap=i == 0))
        put(f"RidgeTop{NTH[i]}Share", pct(v))
    for i, (u, v) in enumerate(R["top_share_sd"][:3]):
        put(f"RidgeSdTop{NTH[i]}", grp(u, cap=i == 0))
        put(f"RidgeSdTop{NTH[i]}Share", pct(v))
    put("RidgeBackboneShare", pct(R["backbone_share_median"]))
    put("RidgeSpearmanSd", f(R["spearman_abs_vs_abs_sd"]))
    put("RidgeW", f(R["W"]))
    put("RidgeAllSelected", R["all_groups_selected"])
    put("RidgeProbeBeat", R["cols_beat_probe"])
    put("RidgeProbeBeatSeries", R["series_beat_probe"])
    put("SpLassoRidge", f(S["spearman_lasso_ridge_meanrank"]))
    # scale check
    sc = S["scale"]
    put("ScaleValueN", sc["value"]["n_cols"])
    put("ScaleValueSd", f(sc["value"]["sd_median"]))
    put("ScaleValueSdLo", f(sc["value"]["sd_p05"]))
    put("ScaleValueSdHi", f(sc["value"]["sd_p95"]))
    put("ScaleValueIqr", f(sc["value"]["iqr_median"]))
    put("ScaleFlagN", sc["flag"]["n_cols"])
    put("ScaleFlagSd", f(sc["flag"].get("sd_median", float("nan"))))
    put("ScaleCalSd", f(sc["calendar"].get("sd_median", float("nan"))))
    put("ScaleHarSd", f(sc["har"].get("sd_median", float("nan"))))
    put("WallLinMin", f(S["wall_sec"] / 60, 0), "minutes")
    return m


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", default=str(RES))
    ap.add_argument("--out", default=str(GEN / "rehaul_fi_pooled_numbers.tex"))
    a = ap.parse_args()
    lines = [HEAD, "% \\rhfp... macros: pooled intraday lasso and ridge, monthly re-estimation (note E19).\n"]
    seen: set = set()
    for s, tag in SAMPLES.items():
        fs = Path(a.res) / s / "summary.json"
        if not fs.is_file():
            print(f"skip {s}: no {fs}")
            continue
        for n, v, c in macros(json.loads(fs.read_text()), tag):
            assert re.fullmatch(r"[A-Za-z]+", n) and n not in seen, n
            seen.add(n)
            lines.append(f"\\providecommand{{\\{n}}}{{}}\\renewcommand{{\\{n}}}{{{v}}}" + (f"  % {c}" if c else "") + "\n")
    Path(a.out).write_text("".join(lines), encoding="utf-8")
    print(f"wrote {rel(Path(a.out))} ({len(seen)} macros)")


if __name__ == "__main__":
    main()
