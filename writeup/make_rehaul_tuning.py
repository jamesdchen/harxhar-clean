"""Tuning provenance and checks (integration plan D14, 2026-10-26): Table tab:rh_tuning and the \\rhtu... macros.

The tuning of the main text only puts off-the-shelf estimators in the forecasting regime; this appendix table discloses
how the frozen values were obtained and reports the checks of results/fomcfix_2026-10-26 (RULE.txt section 7) and the
forest-engine benchmark.  Every number is read from those files; none is recomputed here.

READS
  results/rf_engine_bench_2026-10-23/{accuracy,agreement}.csv, timing.csv   the stock scikit-learn forest (engine A)
        against the oneDAL forest of the main text (engine B: sklearnex, histogram split, max_bins 256; RULE_rf_skx.txt
        of results/pooled_rf_skx_2014start_w3000), pre-test fold 3 (validation 2013), W = 3,000 days, full set, EPYC;
  results/fomcfix_2026-10-26/scores_step4_linear/{summary,dm}.csv   7(a) neighbouring penalties (nbr_<est>_<alpha>),
        7(b) annual re-tuning (ANN) and the frozen arm (cell B), every bar and 16:00, on the FOMC-patched design (cell B):
        full set vs the HAR set of the class (% QLIKE, DM HLN lag 8, p);
  results/fomcfix_2026-10-26/forecasts/tasks_annual_info.json   7(b) the re-selected penalties by year;
  results/fomcfix_2026-10-26/tune2013/{tune2013_scores.csv,tune2013_verdict.json}   7(c) the pre-sample (2013) tree
        neighbourhood: best variant, its MSE gap to the transferred configuration T, DM p (MSE, QLIKE), T's seed range;
  results/window_sweep_2014start_2026-10-22/latestart/latestart_spans.csv   the late-starting series never live in the
        selection fold (fold 3, validation 2013) at W = 3,000;
  experiments/tree_menu_dev.py (DEV_END_DATE), src/unification.py (HAR_BASE), experiments/tree_menu_dev_rf.py (the
        bank-era panel's columns), cluster/pooltree_*_config.json (provenance window) -- read as text and asserted.
WRITES
  writeup/generated/rehaul_tuning_numbers.tex   \\rhtu... macros (definitions only)
  writeup/generated/rehaul_tuning_table.tex     Table tab:rh_tuning (Panels A-C)
NOTE  the linear and tree checks run on the FOMC-patched design (cell B of the fomcfix run); the forest benchmark on the
      final design before the patch (fold 3 only; the patch changes no row before 2020).

Run:  python writeup/make_rehaul_tuning.py     (repository root)
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
GEN = HERE / "generated"
BENCH = ROOT / "results" / "rf_engine_bench_2026-10-23"
FF = ROOT / "results" / "fomcfix_2026-10-26"
LATE = ROOT / "results" / "window_sweep_2014start_2026-10-22" / "latestart" / "latestart_spans.csv"
OUT_NUM = GEN / "rehaul_tuning_numbers.tex"
OUT_TAB = GEN / "rehaul_tuning_table.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_tuning.py -- do not edit; re-run the script."
LIN = ("ridge", "lasso", "enet")
TREES = ("lgbm", "xgb", "rf_skx")
MTAG = {"ridge": "Ridge", "lasso": "Lasso", "enet": "Enet", "lgbm": "Lgbm", "xgb": "Xgb", "rf_skx": "Rf"}
MNAME = {
    "ridge": "Ridge",
    "lasso": "Lasso",
    "enet": "Elastic net",
    "lgbm": "LightGBM",
    "xgb": "XGBoost",
    "rf_skx": "Random forest",
}
FROZEN = {"ridge": 1e3, "lasso": 1e-4, "enet": 1e-3}  # w3000/frozen_penalties.json, all_features (asserted below)
VARIANT_WORDS = {
    "lr_x2": "learning rate x 2",
    "lr_half": "learning rate / 2",
    "n_est_784": "rounds x 2",
    "n_est_196": "rounds / 2",
    "n_est_734": "rounds x 2",
    "n_est_184": "rounds / 2",
    "n_est_970": "trees x 2",
    "n_est_243": "trees / 2",
    "num_leaves_40": "40 leaves",
    "num_leaves_10": "10 leaves",
    "max_depth_6": "depth 6",
    "max_depth_4": "depth 4",
    "max_depth_25": "depth 25",
    "max_depth_15": "depth 15",
    "max_features_0.70": "predictor share 0.70",
    "max_features_1.0": "predictor share 1.0",
    "min_child_samples_159": "leaf size rescaled",
    "min_child_weight_scaled": "leaf weight rescaled",
    "min_leaf_20": "leaf size rescaled",
    "min_leaf_6": "leaf size halved",
}
SIG = 0.05


def thousands(x: int) -> str:
    return f"{x:,}".replace(",", "{,}")


def num(x: float, nd: int = 2) -> str:
    s = f"{x:.{nd}f}"
    if float(s) == 0:
        s = s.lstrip("-")
    return "\\ensuremath{-}" + s[1:] if s.startswith("-") else s


def sgn(x: float, nd: int = 2) -> str:
    s = num(x, nd)
    return s if s.startswith("\\ensuremath") or float(f"{x:.{nd}f}") == 0 else "+" + s


def pval(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def pow10(a: float) -> str:
    e = float(np.log10(a))
    assert abs(e - round(e)) < 1e-9, a
    return f"\\ensuremath{{10^{{{int(round(e))}}}}}"


def main() -> None:
    M: list[tuple[str, str, str]] = []

    def add(name: str, value: str, note: str) -> None:
        assert name.isalpha(), name
        M.append(("rhtu" + name, value, note))

    # ------------------------------------------------------------------ provenance (asserted against the code)
    tmd = (ROOT / "experiments" / "tree_menu_dev.py").read_text(encoding="utf-8")
    m = re.search(r'DEV_END_DATE = np\.datetime64\("(\d{4})-01-01"\)', tmd)
    assert m, "tree_menu_dev.DEV_END_DATE"
    dev_last = int(m.group(1)) - 1
    uni = (ROOT / "src" / "unification.py").read_text(encoding="utf-8")
    m = re.search(r"^HAR_BASE = (\d+)", uni, re.M)
    assert m, "src/unification.HAR_BASE"
    har_base = int(m.group(1))
    rfdev = (ROOT / "experiments" / "tree_menu_dev_rf.py").read_text(encoding="utf-8")
    m = re.search(r"prep_cache_all_features_b2\.npz: ([\d,]+) x (\d+)", rfdev)
    assert m, "tree_menu_dev_rf: the bank-era panel's shape"
    n_cols = int(m.group(2))
    for c in ("pooltree_lgbm_config.json", "xgbtop_xgb_config.json", "pooltree_rf400_config.json"):
        cfg = json.loads((ROOT / "cluster" / c).read_text(encoding="utf-8"))
        assert "24000" in json.dumps(cfg), (c, "provenance window 24,000 intervals")
    # the search's first year: the panel's data start (core_stats from 1998-01-05, the HAR burn-in in early 1998)
    add("TreeSearchSpan", f"1998--{dev_last}", "the Optuna search's pre-sample (tree_menu_dev DEV_END_DATE)")
    add("TreeHarBase", str(har_base), "HAR base of the search's panel (src/unification.py HAR_BASE)")
    add("TreeNCols", thousands(n_cols), "columns of the search's panel (prep_cache_all_features_b2.npz)")
    add("TreeSearchWindow", thousands(24000), "the search's rolling window, intervals (provenance window)")
    # late-starting series never live in the selection fold (fold 3, validation 2013) at W = 3,000
    ls = pd.read_csv(LATE)
    f3 = ls[(ls["window"] == "w3000") & (ls["columns"] == 6)]
    never = f3[f3["fold-3 val 2013 (2014 start): never"] == f3["columns"]]
    assert len(never) == len(f3) == 10, (len(never), len(f3))
    add("NLateSeries", str(len(never)), "late-starting series, never live in the selection fold at W = 3,000")

    # ------------------------------------------------------------------ Panel A: the forest engine
    acc = pd.read_csv(BENCH / "accuracy.csv")
    agr = pd.read_csv(BENCH / "agreement.csv")
    tim = pd.read_csv(BENCH / "timing.csv", header=[0, 1], index_col=[0, 1])
    sel = (acc.set == "all_features") & (acc.W == 3000) & (acc.node == "epyc")
    a = acc[sel & (acc.engine == "A")].iloc[0]
    b = acc[sel & (acc.engine == "B")].iloc[0]
    g = agr[(agr.engine == "B") & (agr.set == "all_features") & (agr.W == 3000) & (agr.node == "epyc")].iloc[0]
    ta = float(tim.loc[("A", "all_features"), ("epyc", "3000")])
    tb = float(tim.loc[("B", "all_features"), ("epyc", "3000")])
    mse_diff = 100.0 * (float(b.mse_adj) / float(a.mse_adj) - 1.0)
    rule_rf = (ROOT / "results" / "pooled_rf_skx_2014start_w3000" / "RULE_rf_skx.txt").read_text(encoding="utf-8")
    assert "max_bins 256" in rule_rf and "engine B" in rule_rf, "the main text's forest is engine B, 256 bins"
    add("RfBins", "256", "histogram bins of the oneDAL forest (RULE_rf_skx.txt)")
    add("RfMseDiffPct", num(mse_diff), "validation MSE, oneDAL vs stock forest, % (fold 3, W 3,000, full set)")
    add("RfQlikeDiffPct", num(100.0 * (float(b.qlike) / float(a.qlike) - 1.0)), "validation QLIKE, same, %")
    add("RfCorr", f"{float(g.corr_vs_A):.4f}", "correlation of the validation forecasts, oneDAL vs stock")
    add("RfSecStock", f"{ta:.0f}", "seconds a refit, stock forest (8 threads, EPYC, W 3,000, full set)")
    add("RfSecOnedal", f"{tb:.0f}", "seconds a refit, oneDAL forest (same)")
    add("RfSpeedup", f"{ta / tb:.1f}", "speed-up of the oneDAL forest")
    add("RfMedRelDiffPct", num(100.0 * float(g.median_rel_diff_vs_A)), "median relative forecast difference, %")

    # ------------------------------------------------------------------ Panel B: linear checks (cell B design)
    sm = pd.read_csv(FF / "scores_step4_linear" / "summary.csv")
    dm = pd.read_csv(FF / "scores_step4_linear" / "dm.csv")
    ann = json.loads((FF / "forecasts" / "tasks_annual_info.json").read_text())
    years = sorted(int(y) for y in ann)
    add("AnnFirstYear", str(years[0]), "first year of the annual re-tuning")
    add("AnnLastYear", str(years[-1]), "last year of the annual re-tuning")
    for e in LIN:
        assert ann[str(years[0])]["penalties"][e]["all_features"] == FROZEN[e], (e, "2014 = the frozen choice")
    n_same = {e: sum(ann[str(y)]["penalties"][e]["all_features"] == FROZEN[e] for y in years) for e in LIN}
    for e in LIN:
        add(f"AnnSame{MTAG[e]}", str(n_same[e]), f"{e}: years whose re-selected full-set penalty is the frozen one")
    add("AnnNYears", str(len(years)), "years re-tuned")
    rows_b = []
    for e in LIN:
        cells = [("B", "frozen", FROZEN[e])]
        cells += sorted(
            [(c, "neighbour", float(c.split("_")[-1])) for c in sm.cell.unique() if c.startswith(f"nbr_{e}_")],
            key=lambda t: t[2],
        )
        cells += [("ANN", "annual", np.nan)]
        for cell, kind, alpha in cells:
            r = sm[(sm.cell == cell) & (sm.model == e)].iloc[0]
            rows_b.append(
                dict(
                    est=e,
                    kind=kind,
                    alpha=alpha,
                    pct_bar=float(r.pct_vs_har_bar),
                    dm_bar=float(r.dm_bar),
                    p_bar=float(r.p_bar),
                    pct_c16=float(r.pct_vs_har_c16),
                    dm_c16=float(r.dm_c16),
                    p_c16=float(r.p_c16),
                )
            )
    B = pd.DataFrame(rows_b)
    nb = B[B.kind == "neighbour"]
    an = B[B.kind == "annual"]
    assert len(nb) == 6 and len(an) == 3
    # the text's claims (A_methods.tex, 2026-10-26): significant every-bar gain at every neighbour and when re-tuned
    assert (nb.dm_bar < 0).all() and (nb.p_bar < SIG).all(), "claim: every neighbour keeps a significant gain"
    assert (an.dm_bar < 0).all() and (an.p_bar < SIG).all(), "claim: annual re-tuning keeps a significant gain"
    add("NbrPctBarMin", num(nb.pct_bar.min(), 1), "neighbouring penalties: most negative every-bar % vs HAR")
    add("NbrPctBarMax", num(nb.pct_bar.max(), 1), "neighbouring penalties: least negative every-bar % vs HAR")
    add("NbrPBarMax", pval(nb.p_bar.max()), "neighbouring penalties: largest every-bar DM p")
    add("AnnPctBarMin", num(an.pct_bar.min(), 1), "annual re-tuning: most negative every-bar % vs HAR")
    add("AnnPctBarMax", num(an.pct_bar.max(), 1), "annual re-tuning: least negative every-bar % vs HAR")
    add("AnnPBarMax", pval(an.p_bar.max()), "annual re-tuning: largest every-bar DM p")
    add("NNbr", str(len(nb)), "neighbouring-penalty arms (two a class)")
    for e in LIN:
        r = an[an.est == e].iloc[0]
        add(f"Ann{MTAG[e]}PctBar", num(r.pct_bar, 1), f"annual re-tuning, {e}: every-bar % vs HAR")
        q = dm[
            (dm.cell == "ANN")
            & (dm.model == e)
            & (dm.set == "all_features")
            & (dm.comparison == "vs frozen (cell B)")
            & (dm.span == "bar")
            & (dm["loss"] == "qlike")
        ].iloc[0]
        add(f"Ann{MTAG[e]}PctVsFrozen", num(float(q.pct), 1), f"annual re-tuning, {e}: every-bar % vs the frozen arm")
        add(f"Ann{MTAG[e]}PVsFrozen", pval(float(q.p)), f"annual re-tuning, {e}: DM p vs the frozen arm")

    # ------------------------------------------------------------------ Panel C: the 2013 tree check (cell B design)
    ts = pd.read_csv(FF / "tune2013" / "tune2013_scores.csv")
    vd = json.loads((FF / "tune2013" / "tune2013_verdict.json").read_text())
    seeds = sorted(set(ts[ts.variant.str.startswith("T_seed")].seed))
    add("TreeNSeeds", str(len(seeds)), "further seeds of the transferred configuration")
    rows_c = []
    for e in TREES:
        v = vd[e]
        t = ts[(ts.est == e) & (ts.variant == "T")].iloc[0]
        sd = ts[(ts.est == e) & ((ts.variant == "T") | ts.variant.str.startswith("T_seed"))]
        gap = 100.0 * (v["best_mse"] / v["T_mse"] - 1.0)
        lo = 100.0 * (sd.mse_adj.min() / float(t.mse_adj) - 1.0)
        hi = 100.0 * (sd.mse_adj.max() / float(t.mse_adj) - 1.0)
        rows_c.append(
            dict(
                est=e,
                best=VARIANT_WORDS[v["best"]],
                gap=gap,
                p_se=v["p_se"],
                p_q=v["p_q"],
                rank=v["T_rank_mse"],
                n=v["n_candidates"],
                lo=lo,
                hi=hi,
                noise=v["T_within_noise_mse"],
            )
        )
        add(f"{MTAG[e]}BestVariant", VARIANT_WORDS[v["best"]], f"{e}: best 2013 variant by validation MSE")
        add(f"{MTAG[e]}BestGapPct", num(gap), f"{e}: best variant's MSE vs T, %")
        add(f"{MTAG[e]}BestPMse", pval(v["p_se"]), f"{e}: DM p, best vs T, daily MSE")
        add(f"{MTAG[e]}BestPQlike", pval(v["p_q"]), f"{e}: DM p, best vs T, daily QLIKE")
        add(f"{MTAG[e]}TRank", str(v["T_rank_mse"]), f"{e}: T's MSE rank among the variants")
        add(f"{MTAG[e]}NVariants", str(v["n_candidates"]), f"{e}: variants incl. T")
    C = pd.DataFrame(rows_c).set_index("est")
    # the text's claims: forest within noise; LightGBM / XGBoost best significantly lower on MSE, not on QLIKE
    assert bool(C.loc["rf_skx", "noise"]) and C.loc["rf_skx", "p_se"] >= SIG, "claim: forest T within noise"
    for e in ("lgbm", "xgb"):
        assert C.loc[e, "p_se"] < SIG and C.loc[e, "p_q"] >= SIG, (e, "claim: lower MSE, not lower QLIKE")
    add("TreeCpuHours", f"{ts.cpu_hours.sum():.0f}", "CPU-hours of the 2013 tree check")

    # ------------------------------------------------------------------ the table
    def alpha_txt(r: pd.Series) -> str:
        if r.kind == "annual":
            return "annual"
        return pow10(r.alpha) + (" (frozen)" if r.kind == "frozen" else "")

    body = [
        "\\multicolumn{7}{@{}l}{\\textit{Panel A: The forest engine (selection fold, validation \\rhorPenYears, "
        "$W = \\rhorWindowDays$ days, full set)}} \\\\",
        "\\addlinespace[2pt]",
        " & Seconds/refit & MSE & QLIKE & Corr. & & \\\\",
        "\\cmidrule(lr){2-5}",
        f"Stock forest & {ta:.0f} & {float(a.mse_adj):.5f} & {float(a.qlike):.4f} & 1 & & \\\\",
        f"oneDAL forest & {tb:.0f} & {float(b.mse_adj):.5f} & {float(b.qlike):.4f} & {float(g.corr_vs_A):.4f} & & \\\\",
        "\\addlinespace[6pt]",
        "\\multicolumn{7}{@{}l}{\\textit{Panel B: Linear penalties, full set against the HAR set of the class "
        "(\\rhorNIntB{} bars and their 16:00 bar)}} \\\\",
        "\\addlinespace[2pt]",
        " & Penalty & \\multicolumn{2}{c}{Every bar} & \\multicolumn{2}{c}{16:00} & \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
        " & & \\% vs HAR & DM ($p$) & \\% vs HAR & DM ($p$) & \\\\",
        "\\cmidrule(lr){2-6}",
    ]
    for e in LIN:
        first = True
        for _, r in B[B.est == e].iterrows():
            lab = MNAME[e] if first else ""
            first = False
            body.append(
                f"{lab} & {alpha_txt(r)} & {sgn(r.pct_bar, 1)} & {num(r.dm_bar)} ({pval(r.p_bar)}) & "
                f"{sgn(r.pct_c16, 1)} & {num(r.dm_c16)} ({pval(r.p_c16)}) & \\\\"
            )
        body.append("\\addlinespace[2pt]")
    body += [
        "\\addlinespace[4pt]",
        "\\multicolumn{7}{@{}l}{\\textit{Panel C: Tree configurations, validation year \\rhorPenYears{} only "
        "(refit daily)}} \\\\",
        "\\addlinespace[2pt]",
        " & Best variant & MSE vs $T$ (\\%) & $p$ (MSE) & $p$ (QLIKE) & Rank of $T$ & Seeds (\\%) \\\\",
        "\\cmidrule(lr){2-7}",
    ]
    for e in TREES:
        r = C.loc[e]
        body.append(
            f"{MNAME[e]} & {r.best} & {num(r.gap)} & {pval(r.p_se)} & {pval(r.p_q)} & {r['rank']} of {r.n} & "
            f"{num(r.lo)} to {sgn(r.hi)} \\\\"
        )
    note = (
        "\\item \\textit{Notes:} Panel A: the stock \\texttt{scikit-learn} random forest, with which the forest's "
        "configuration was selected, and Intel's oneDAL forest of the main text (histogram splits, "
        "\\rhtuRfBins{} bins), fitted with the same configuration on the selection fold of "
        "Appendix~\\ref{app:rh_methods_splits} (fit on the $W$ bars before a gap, scored on the bars of "
        "\\rhorPenYears): seconds a refit on 8 threads (AMD EPYC), validation MSE on the adjusted scale and QLIKE, and the "
        "correlation of the two forests' validation forecasts. Panel B: each full-set penalized regression at its frozen "
        "penalty, at the neighbouring penalties one grid step below and above, and with the penalty re-selected each year "
        "from \\rhtuAnnFirstYear{} to \\rhtuAnnLastYear{} on the \\rhdmPlPreFoldSess{} sessions before the year; % QLIKE "
        "change against the HAR set of the same class (negative: the full set has the lower loss) and the "
        "Diebold--Mariano statistic of the daily average QLIKE (HLN, Newey--West lag \\rhorHacLag) with its $p$-value, "
        "on the bars of Table~\\ref{tab:rh_oos}. Panel C: each tree method at its transferred configuration $T$ and at "
        "one-at-a-time variants, refitted at the first bar of every day of \\rhorPenYears{} on the $W$ bars before it; "
        "the variant with the lowest validation MSE, its MSE relative to $T$, the Diebold--Mariano $p$-values of the "
        "daily validation MSE and QLIKE of the best variant against $T$, $T$'s rank among the variants, and the range "
        "of $T$'s MSE over \\rhtuTreeNSeeds{} further seeds relative to seed 42. Panels B and C use the design with the "
        "FOMC corrections of Section~\\ref{sec:rh_data}; Panel A the design before them (the corrections change no "
        "bar before 2020)."
    )
    table = "\n".join(
        [
            HEAD,
            "% Table tab:rh_tuning (Appendix app:rh_tuning): the forest engine (results/rf_engine_bench_2026-10-23) and",
            "% the tuning checks of results/fomcfix_2026-10-26 (RULE.txt section 7 (a)-(c)).",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\footnotesize",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\begin{threeparttable}",
            "\\caption{Tuning provenance and checks}",
            "\\label{tab:rh_tuning}",
            "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}llrrrrr@{}}",
            "\\toprule",
            *body,
            "\\bottomrule",
            "\\end{tabular*}",
            "\\begin{tablenotes}[flushleft]",
            "\\footnotesize",
            note,
            "\\end{tablenotes}",
            "\\end{threeparttable}",
            "\\end{table}",
            "",
        ]
    )
    names = [n for n, _, _ in M]
    assert len(set(names)) == len(names), "a macro name twice"
    lines = [
        HEAD,
        "% \\rhtu... macros of the tuning appendix (app:rh_tuning, Table tab:rh_tuning): provenance of the frozen",
        "% hyperparameters (asserted against the code) and the checks of results/fomcfix_2026-10-26 (RULE.txt section 7),",
        "% the forest-engine benchmark results/rf_engine_bench_2026-10-23.",
    ]
    for name, value, note_ in M:
        lines.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}  % {note_}")
    GEN.mkdir(parents=True, exist_ok=True)
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    OUT_TAB.write_text(table, encoding="utf-8", newline="\n")
    print(f"wrote {len(M)} macros to {OUT_NUM.relative_to(ROOT)} and {OUT_TAB.relative_to(ROOT)}")
    print(B.round(3).to_string(index=False))
    print(C.round(3).to_string())


if __name__ == "__main__":
    main()
