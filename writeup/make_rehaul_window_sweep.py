"""The rolling-window sweep of the pooled linear models (2014 start; audit #5, decision D8): \\rhws... and tab:rh_window_sweep.

READS   results/window_sweep_2014start_2026-10-22/part2/{gap,econ}.csv (the full set against the HAR set of each penalized
        linear class at every window W = 1,000 .. 3,500 trading days: % QLIKE change and DM (HLN, lag 8) on Table 1's
        33,527 bars and on their 16:00 bar; the D6 Sharpe-ratio difference on the 614 post-warmup option days with its
        bootstrap p) and latestart/latestart_spans.csv (late-starting series never live in the selection fold).  Every
        number is read from those files.
WRITES  writeup/generated/rehaul_window_sweep_numbers.tex   \\rhws... macros (definitions only)
        writeup/generated/rehaul_window_sweep_table.tex     Table tab:rh_window_sweep
NOTE    the sweep runs on the design before the FOMC fix (the window choice does not depend on it; disclosed).

Run:  python writeup/make_rehaul_window_sweep.py     (repository root)
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
WS = ROOT / "results" / "window_sweep_2014start_2026-10-22"
GEN = HERE / "generated"
OUT_NUM = GEN / "rehaul_window_sweep_numbers.tex"
OUT_TAB = GEN / "rehaul_window_sweep_table.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_window_sweep.py -- do not edit; re-run the script."
LIN = ("ridge", "lasso", "enet")
MTAG = {"ridge": "Ridge", "lasso": "Lasso", "enet": "Enet"}
MNAME = {"ridge": "Ridge", "lasso": "Lasso", "enet": "Elastic net"}
WORDS = {4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}
W_MAIN = 3000
SIG = 0.05


def thousands(x: int) -> str:
    return f"{x:,}".replace(",", "{,}")


def num(x: float, nd: int = 1) -> str:
    s = f"{x:.{nd}f}"
    if float(s) == 0:
        s = s.lstrip("-")
    return "\\ensuremath{-}" + s[1:] if s.startswith("-") else s


def pval(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def main() -> None:
    gap = pd.read_csv(WS / "part2" / "gap.csv")
    econ = pd.read_csv(WS / "part2" / "econ.csv")
    late = pd.read_csv(WS / "latestart" / "latestart_spans.csv")
    ws = sorted(int(w) for w in gap["W"].unique())
    assert W_MAIN in ws and set(gap["model"]) == set(LIN), (ws, set(gap["model"]))
    M: list[tuple[str, str, str]] = []

    def add(name: str, value: str, note: str) -> None:
        assert name.isalpha(), name
        M.append(("rhws" + name, value, note))

    add("NWin", WORDS[len(ws)], "windows scored out of sample, as a word (the stop-gap of A_robustness.tex)")
    add("NWinNum", str(len(ws)), "windows scored out of sample, numeral")
    add("NWinWord", WORDS[len(ws)], "the same, as a word")
    add("WinMin", thousands(ws[0]), "shortest window, trading days")
    add("WinMax", thousands(ws[-1]), "longest window, trading days")
    add("WinMain", thousands(W_MAIN), "the main text's window")
    # the shortest window at which no late-start series is live in the selection fold (fold 3, validation 2013)
    col_never, col_part = "fold-3 val 2013 (2014 start): never", "fold-3 val 2013 (2014 start): partly"
    late6 = late[late["columns"] == 6]
    none_live = [
        int(w[1:]) for w, g in late6.groupby("window") if ((g[col_never] == g["columns"]) & (g[col_part] == 0)).all()
    ]
    w_none = min(w for w in none_live if w >= ws[0])
    assert all(w in none_live for w in ws if w >= w_none), "late-start series live again at a longer window"
    add("LateNoneFrom", thousands(w_none), "shortest window at which no late-start column is live in the fold")
    for m in LIN:
        g = gap[gap.model == m]
        for col, span in (("gap_pct_bar", "Bar"), ("gap_pct_16", "Close")):
            add(f"{MTAG[m]}{span}PctMin", num(g[col].min()), f"{m}, {span}: most negative full-vs-HAR % over windows")
            add(f"{MTAG[m]}{span}PctMax", num(g[col].max()), f"{m}, {span}: least negative / largest % over windows")
        add(f"{MTAG[m]}BarPMax", pval(g["gap_p_bar"].max()), f"{m}: largest every-bar DM p over windows")
        add(
            f"{MTAG[m]}BarNSig",
            str(int(((g.gap_pct_bar < 0) & (g.gap_p_bar < SIG)).sum())),
            f"{m}: windows with a significant every-bar gain",
        )
        add(
            f"{MTAG[m]}CloseNSig",
            str(int(((g.gap_pct_16 < 0) & (g.gap_p_16 < SIG)).sum())),
            f"{m}: windows with a significant 16:00 gain",
        )
    bar_sig_all = int(((gap.gap_pct_bar < 0) & (gap.gap_p_bar < SIG)).sum())
    add("BarNSigAll", str(bar_sig_all), "(class, window) cells with a significant every-bar gain")
    add("NCells", str(len(gap)), "(class, window) cells")
    add("BarPctMin", num(gap.gap_pct_bar.min()), "every bar: most negative % over classes and windows")
    add("BarPctMax", num(gap.gap_pct_bar.max()), "every bar: least negative % over classes and windows")

    # ------------------------------------------------------------------ table
    body = []
    for m in LIN:
        first = True
        for w in ws:
            g = gap[(gap.model == m) & (gap.W == w)].iloc[0]
            e = econ[(econ.model == m) & (econ.W == w)].iloc[0]
            lab = MNAME[m] if first else ""
            first = False
            mark = "$^{\\ast}$" if w == W_MAIN else ""
            body.append(
                f"{lab} & {thousands(w)}{mark} & {num(g.gap_pct_bar)} & {num(g.gap_dm_bar, 2)} ({pval(g.gap_p_bar)}) & "
                f"{num(g.gap_pct_16)} & {num(g.gap_dm_16, 2)} ({pval(g.gap_p_16)}) & "
                f"{num(e.dd6_mid, 2)} ({pval(e.d6_boot_p_mid)}) \\\\"
            )
        body.append("\\addlinespace[3pt]")
    body = body[:-1]
    table = "\n".join(
        [
            HEAD,
            "% Table tab:rh_window_sweep (appendix, D8): results/window_sweep_2014start_2026-10-22/part2 (gap.csv, econ.csv).",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\small",
            "\\setlength{\\tabcolsep}{4pt}",
            "\\begin{threeparttable}",
            "\\caption{The full predictor set against the HAR set across rolling windows}",
            "\\label{tab:rh_window_sweep}",
            "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrr@{}}",
            "\\toprule",
            " & & \\multicolumn{2}{c}{Every bar} & \\multicolumn{2}{c}{16:00} & \\\\",
            "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
            "Model & $W$ (days) & \\% vs HAR & DM ($p$) & \\% vs HAR & DM ($p$) & $\\Delta\\SR$ ($p$) \\\\",
            "\\midrule",
            *body,
            "\\bottomrule",
            "\\end{tabular*}",
            "\\begin{tablenotes}[flushleft]",
            "\\footnotesize",
            "\\item \\textit{Notes:} Each penalized linear class estimated on the HAR set and on the full set with a rolling "
            "window of $W$ trading days ($13W$ bars), its penalties chosen on the selection fold at that window and "
            "frozen; $^{\\ast}$ the window of the main text. \\% vs HAR: the full set's QLIKE relative to the HAR set's "
            "(negative: lower loss), on the \\rhorNIntB{} bars of Table~\\ref{tab:rh_oos} and on their 16:00 bar; DM: "
            "Diebold--Mariano statistic of the daily (average) QLIKE, HLN correction, Newey--West lag \\rhorHacLag, "
            "$p$-value in parentheses. $\\Delta\\SR$: the full-set minus the HAR-set Sharpe ratio of the sign strategy "
            "at mid-quotes on the \\rheSzDays{} post-warmup option days, with the bootstrap $p$-value. Design before "
            "the FOMC calendar corrections of Section~\\ref{sec:rh_data}.",
            "\\end{tablenotes}",
            "\\end{threeparttable}",
            "\\end{table}",
            "",
        ]
    )
    names = [n for n, _, _ in M]
    assert len(set(names)) == len(names), "a macro name twice"
    lines = [
        HEAD,
        "% \\rhws... macros of the rolling-window sweep (results/window_sweep_2014start_2026-10-22, part2; Table",
        "% tab:rh_window_sweep). Pre-patch design (the FOMC calendar corrections not applied).",
    ]
    for name, value, note in M:
        lines.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}  % {note}")
    GEN.mkdir(parents=True, exist_ok=True)
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    OUT_TAB.write_text(table, encoding="utf-8", newline="\n")
    print(f"wrote {len(M)} macros to {OUT_NUM.relative_to(ROOT)} and {OUT_TAB.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
