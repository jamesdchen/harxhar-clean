def run(cmd: list[str], cwd: Path, env: dict[str, str], timeout: int = 900) -> subprocess.CompletedProcess[str]:
    for _ in range(10):  # a git command may meet the index lock of a pass committing at the same moment
        r = subprocess.run(
            cmd,
            cwd=cwd,
            env=env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
        if cmd[0] != "git" or r.returncode == 0 or "index.lock" not in r.stderr:
            return r
        time.sleep(1)
    return r


