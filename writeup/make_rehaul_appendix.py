def header_order(stem: str, *parts: str) -> None:
    """The upstream table's header names its columns in this order (guards the column mapping below)."""
    txt = (GEN / f"{stem}.tex").read_text(encoding="utf-8")
    head = txt.split(r"\toprule", 1)[1].split(r"\midrule", 1)[0]
    pos = [head.find(p) for p in parts]
    assert all(p >= 0 for p in pos) and pos == sorted(pos), (stem, parts, pos)


