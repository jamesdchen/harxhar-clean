def mingru_dayclass() -> None:
    dc = pd.read_csv(PF / "wd_enc_study" / "day_class.csv")
    n = dc["day_class"].value_counts()
    assert int(n.sum()) == N_DAYS
    thr = int(dc.loc[dc.day_class == "extreme_inputs", "n_gt_max"].min())
    assert thr > int(dc.loc[dc.day_class == "other", "n_gt_max"].max())
    # month-ends take precedence: some month-ends have extreme inputs too
    n_me_ext = int(((dc.day_class == "month_end") & (dc.n_gt_max >= thr)).sum())
    src = [
        (
            CHAIN[0][0],
            lambda d: one(S_WE, design=d, model="softplus walk of record"),
        ),
        (CHAIN[1][0], lambda d: one(S_WE, design=d, model="wd_enc wegrid")),
        (CHAIN[2][0], lambda d: one(S_LIN, design=d, model="g8 lingrid")),
        (CHAIN[3][0], lambda d: one(S_RI, design=d, model="(b) rinit")),
        (CHAIN[4][0], lambda d: one(S_Q, design=d, run="b_qsel")),
        (CHAIN[5][0], lambda d: one(S_Q, design=d, run="b_qtrain_qsel")),
        ("Elastic net", lambda d: one(S_RI, design=d, model="enet")),
        ("Ridge", lambda d: one(S_RI, design=d, model="ridge")),
    ]
    w = np.array([n[k] for _, k in CLASSES], float)
    vals: dict[str, dict[str, list[float]]] = {}
    for lab, f in src:
        vals[lab] = {}
        for d in DESIGNS:
            s = f(d)
            v = [float(s[c]) for c, _ in CLASSES] + [float(s["qlike"])]
            # the classes partition the days: their day-weighted mean is the overall QLIKE
            assert abs(float(np.dot(w, v[:3]) / w.sum()) - v[3]) < 1e-9, (lab, d, v)
            vals[lab][d] = v
    # the chain's overall QLIKE equals A2's
    for (lab, chain_v), (lab2, _) in zip(CHAIN, src):
        assert lab == lab2
        for d in DESIGNS:
            assert abs(chain_v[d]["qlike"] - vals[lab2][d][3]) < 1e-12, (lab, lab2, d)
    # af_diagnosis/gap_by_dayclass.csv holds the trimmed-target gaps (see the parked block above): the gap shares are
    # computed from the re-scored per-class QLIKEs (d08_decomp's definition: a class's summed daily gap over the gap
    # summed over all days)
    rec = vals[CHAIN[0][0]]
    gap = {
        k: float(n[k]) * (rec["all_features"][i] - rec["baseline"][i])
        for i, (_, k) in enumerate(CLASSES)
    }
    tot = sum(gap.values())
    assert (
        abs(tot / N_DAYS - (rec["all_features"][3] - rec["baseline"][3])) < 1e-9
    )  # the classes partition the days
    share = {k: 100 * gap[k] / tot for _, k in CLASSES}

    def line(lab: str, v: list[float]) -> str:
        return row(lab, [mcell(fnum(x, 4)) for x in v])

    panels = [(DLABEL[d], [line(lab, vals[lab][d]) for lab, _ in src]) for d in DESIGNS]
    panels.append(
        (
            f"{DLABEL['all_features']} minus {DLABEL['baseline']}",
            [
                line(
                    lab,
                    [
                        a - b
                        for a, b in zip(
                            vals[lab]["all_features"], vals[lab]["baseline"]
                        )
                    ],
                )
                for lab, _ in src
            ],
        )
    )
    # the day counts in the header are the macros written below (\rhappNdays by mingru_dev): no typed n
    hdr = [
        r" & \multicolumn{1}{c}{Month-ends} & \multicolumn{1}{c}{Extreme predictors} & \multicolumn{1}{c}{Other days}"
        r" & \multicolumn{1}{c}{All days} \\",
        r"Specification & \multicolumn{1}{c}{(\rhappNmonthEnd{} days)} & \multicolumn{1}{c}{(\rhappNextreme{} days)}"
        r" & \multicolumn{1}{c}{(\rhappNother{} days)} & \multicolumn{1}{c}{(\rhappNdays{} days)} \\",
    ]
    write(
        "rehaul_app_mingru_dayclass.tex",
        tabular(r"@{}l*{4}{r}@{}", hdr, with_panels(panels, 5)),
        "results/puffer_forecast_2026-10-12/{wd_enc_study, lin_study, ridge_init_study, qlike_study}/scores.csv "
        "(ql_month_end, ql_extreme_inputs, ql_other; QLIKE against the actual RV since 2026-10-15); day classes "
        "wd_enc_study/day_class.csv; gap shares from these per-class QLIKEs",
    )
    macro("rhappNmonthEnd", int(n["month_end"]))
    macro("rhappNextreme", int(n["extreme_inputs"]))
    macro("rhappNother", int(n["other"]))
    macro("rhappNmonthEndExtreme", n_me_ext)
    macro("rhappExtremeCols", thr)
    macro("rhappGapShareExtreme", f"{share['extreme_inputs']:.0f}")
    macro("rhappGapShareMonthEnd", f"{share['month_end']:.0f}")
    macro("rhappGapShareOther", neg(f"{share['other']:.0f}"))


