# ----------------------------------------------------------------------------- 2026-10-15 (table legibility): A2 / A4
# Seven columns (QLIKE, Delta %, SR per predictor set): the p column is gone, its information carried by stars on Delta
# % from the stored two-sided normal DM p-value (p_qlike; src/evaluation/diebold_mariano.dm_test); the linear rows have
# no test, so their Delta % carries the padded slots only.  "--": not estimated on that predictor set.
def vrow(label: str, v: dict) -> str:
    cells: list[str] = []
    for d in DESIGNS:
        x = v.get(d)
        if x is None:
            cells += [OUT_DASH, mcell(DASH, 0), OUT_DASH]
        else:
            cells += [
                mcell(fq(x["qlike"])),
                mcell(fnum(x["dpct"], 1), n_stars(x["p"])),
                mcell(fnum(x["sharpe"], 2)),
            ]
    return row(label, cells)


def ref_rows() -> list[str]:
    out = []
    for lab, src in (("Elastic net (comparator)", ENET), ("Ridge", RIDGE)):
        cells = []
        for d in DESIGNS:
            s = src[d]
            dp = 100 * (float(s["qlike"]) / float(ENET[d]["qlike"]) - 1)
            cells += [
                mcell(fq(float(s["qlike"]))),
                mcell(DASH if src is ENET else fnum(dp, 1), 0),
                mcell(fnum(float(s["sharpe_mid"]), 2)),
            ]
        out.append(row(lab, cells))
    return out


