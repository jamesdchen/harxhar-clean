def count_cell(s: str) -> str:
    """'6 (3)' -> both counts padded to two digits by a phantom in front (of the count, of the parenthesis), so the
    counts and the closing parentheses of an r column line up."""
    m = re.fullmatch(r"(\d+) \((\d+)\)", s.strip())
    assert m and max(len(m.group(1)), len(m.group(2))) <= 2, s
    a, b = ((r"\phantom{0}" * (2 - len(x)), x) for x in m.groups())
    return f"{a[0]}{a[1]} {b[0]}({b[1]})"


