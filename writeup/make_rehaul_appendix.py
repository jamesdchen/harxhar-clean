def with_panels(panels: list[tuple[str, list[str]]], ncol: int) -> list[str]:
    """Panel A, B, ... in order, \\addlinespace between them."""
    body: list[str] = []
    for i, (title, rows) in enumerate(panels):
        if i:
            body.append(r"\addlinespace")
        body.append(panel_title("ABCDEFGHIJ"[i], title, ncol))
        body += rows
    return body


