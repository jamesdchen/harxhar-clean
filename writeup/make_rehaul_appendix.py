def by_design_rows(
    stem: str, ncells: int, per_row
) -> dict[str, list[tuple[str, list[str]]]]:
    """For tables with design panels (\\texttt{...} titles) and rows ['', model, cells...]."""
    out: dict[str, list] = {d: [] for d in DESIGNS}
    cur = None
    for r in read_rows(stem):
        if r["kind"] == "panel":
            cur = design_of(r["title"])
        elif r["kind"] == "row":
            c = r["cells"]
            assert len(c) == ncells and c[0] == "" and cur, (stem, c)
            out[cur].append((c[1], per_row(c[2:])))
    for d in DESIGNS:
        assert [m for m, _ in out[d]] == list(MODELS), (stem, d, out[d])
    return out


def stacked_cells(cells: list[str]) -> list[str]:
    res: list[str] = []
    for c in cells:
        if c == DASH:
            res.append(rf"\multicolumn{{2}}{{c}}{{{DASH}}}")
        else:
            res.extend(stack(c))
    return res


