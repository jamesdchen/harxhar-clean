def neg(s: str) -> str:
    return s.replace("-", r"\ensuremath{-}", 1) if s.startswith("-") else s


def fq(x: float) -> str:
    return f"{x:.4f}"


def fpct(x: float) -> str:
    s = f"{x:+.1f}"
    return (r"\ensuremath{+}" + s[1:]) if s.startswith("+") else neg(s)


def fp(p: float) -> str:
    return r"$<$0.001" if p < 0.001 else f"{p:.3f}"


