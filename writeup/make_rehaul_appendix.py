def tabular(colspec: str, header: list[str], body: list[str]) -> str:
    return (
        "\n".join(
            [
                rf"\begin{{tabular}}{{{colspec}}}",
                r"\toprule",
                *header,
                r"\midrule",
                *body,
                r"\bottomrule",
                r"\end{tabular}",
            ]
        )
        + "\n"
    )


def pair_header(
    groups: list[str], first: str, sub=("QLIKE", r"$\Delta$SR")
) -> list[str]:
    """Two header rows: each group spans its (QLIKE %, Delta Sharpe) pair."""
    n = len(sub)
    top = (
        " & " + " & ".join(rf"\multicolumn{{{n}}}{{c}}{{{g}}}" for g in groups) + r" \\"
    )
    rules = "".join(
        rf"\cmidrule(lr){{{2 + n * i}-{1 + n * (i + 1)}}}" for i in range(len(groups))
    )
    bottom = first + " & " + " & ".join(" & ".join(sub) for _ in groups) + r" \\"
    return [top, rules, bottom]


