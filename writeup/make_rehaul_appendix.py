def search_range(s: str) -> str:
    out = s.replace(r"early-stopped rounds $\le$ cap(lr)", r"$B \le \bar B(\eta)$")
    out = re.sub(r"\b10000\b", r"$10^{4}$", out)
    out = out.replace("1e-05", r"$10^{-5}$").replace("0.001", r"$10^{-3}$")
    out = out.replace(" log int", ", log, integer").replace("] log", "], log")
    out = out.replace("] int", "], integer")
    out = out.replace(r"\{3, 5, 10, 20, 40, None\}", r"\{3, 5, 10, 20, 40, none\}")
    assert "lr" not in out and "rounds" not in out and "None" not in out, s
    return out


def pick_cell(x: str) -> str:
    x = x.strip()
