def variant(fn, designs=DESIGNS) -> dict:
    out = {}
    for d in designs:
        s, c = fn(d)
        if "n_days" in s.index:
            assert int(s["n_days"]) == N_DAYS, (d, s)
        # the contrast's QLIKE change is the scores' ratio to the same elastic net
        assert abs(100 * (s["qlike"] / ENET[d]["qlike"] - 1) - c["qlike_pct"]) < 1e-6, (
            d,
            s,
            c,
        )
        out[d] = cell(s, c)
    return out


