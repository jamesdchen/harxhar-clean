"""Counterparts of the prose macros on the pooled linear reruns, under two framings and two panels (2026-10-20).

The abstract, introduction, results and conclusion quote macros of writeup/make_rehaul_results.py
(\\rhrAfPool..., \\rhrPool..., \\rhrNLowerPool...) that were computed from the old pooled forecasts, scored on the
closing half hour only, with the tree ensembles in. That generator cannot run here (its inputs are not in the repo).
This script computes the like-for-like counterpart of each such macro from the committed rerun forecasts only, for
the linear classes (ridge, lasso, elastic net; the OLS on the HAR benchmark), so the author can pick the framing
before any prose changes. It does not touch any existing generated file.

FRAMINGS  All    every interval of the panel's sample on the 1,082 trading days (as Table 1,
                 writeup/make_rehaul_oos_rerun.py: its functions are imported, so the scored intervals, truth,
                 losses and daily averages are the same);
          Close  the closing half hour only: the 16:00 row of the same scored set (the 15:30 forecast), one interval
                 a day, 1,082 intervals.
PANELS    A      trained on all 48 half-hour intervals  (results/pooled_linear_rerun_2026-10-19_48/forecasts)
          B      trained on the 13 regular-hours bars    (results/pooled_linear_rerun_2026-10-19_13/forecasts.parquet)
TESTS     Diebold-Mariano (src/evaluation/diebold_mariano.dm_test, its default lag) on the daily average loss; under
          Close a day has one interval, so the daily average is that interval's loss. Significant: p < 0.05.
          "All features vs HAR": the full predictor set against the HAR benchmark of the same model.
          "vs OLS": each penalized forecast against the pooled OLS on the HAR benchmark of the same panel. The
          closing-interval OLS that the old text calls the HAR benchmark is not in the reruns and is not in the
          repo, so no counterpart of the \\rhrVsBmPool... macros against it is computed.
PCT       100 (Lbar_A / Lbar_B - 1), Lbar the mean loss over the scored intervals; negative favors A.

Macro names: \\rhrr<Name><Framing><Panel>, Framing = All | Close, Panel = A (48 intervals) | B (13 bars). LaTeX
macro names cannot hold digits, so the panels are A and B as in Table 1 (\\rhorNIntA, \\rhorNIntB).

WRITES   writeup/generated/rehaul_rerun_text_numbers.tex      (new; not loaded by the preamble)
         results/rerun_text_numbers_2026-10-20/numbers.csv     every value, unrounded
         results/rerun_text_numbers_2026-10-20/dm.csv          every test

Run:  python writeup/make_rehaul_rerun_text_numbers.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent  # writeup/
REPO = ROOT.parent
sys.path.insert(0, str(ROOT))
import make_rehaul_oos_rerun as T1  # noqa: E402  (Table 1's scoring: imported, not run)
from src.evaluation.diebold_mariano import dm_test  # noqa: E402

OUT_TEX = T1.GEN / "rehaul_rerun_text_numbers.tex"
OUT_RES = REPO / "results" / "rerun_text_numbers_2026-10-20"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_rerun_text_numbers.py -- do not edit."
PEN = [("ridge", "Ridge"), ("lasso", "Lasso"), ("enet", "Enet")]
PANELS = [("48", "A"), ("13", "B")]
FRAMINGS = ["All", "Close"]
ALPHA = 0.05


def pct(a: float, b: float) -> float:
    return 100.0 * (a / b - 1.0)


def signed(x: float, dp: int) -> str:
    v = round(float(x), dp)
    if v == 0:
        v = 0.0
    return f"\\ensuremath{{{'-' if v < 0 else '+'}}}{abs(v):.{dp}f}"


def pstmt(p: float) -> str:
    return "\\ensuremath{p < 0.001}" if p < 0.001 else f"\\ensuremath{{p = {p:.3f}}}"


def scored(pid: str, rv: pd.Series, days: pd.DatetimeIndex) -> dict[str, tuple[dict, pd.DatetimeIndex, pd.Series]]:
    """framing -> (forecasts, scored interval ends, R2_OOS benchmark)."""
    fc = T1.forecasts(pid)
    idx = T1.scored_set(fc, rv, days)
    close = idx[(idx.hour == 16) & (idx.minute == 0)]
    assert len(close) == T1.SPAN_DAYS, (pid, len(close))
    return {f: (fc, ix, T1.slot_benchmark(rv, ix)) for f, ix in (("All", idx), ("Close", close))}


def main() -> None:
    rv = T1.core()
    days = T1.evaluation_days(rv)
    num_rows, dm_rows, mac = [], [], []

    def put(name: str, value: str, comment: str) -> None:
        mac.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}  % {comment}")

    for pid, ptag in PANELS:
        for fr, (fc, idx, bench) in scored(pid, rv, days).items():
            tag = f"{fr}{ptag}"
            y = rv.reindex(idx).to_numpy(float)
            den = float(((y - bench.to_numpy()) ** 2).sum())
            L, M = {}, {}
            for k, f in fc.items():
                q, se = T1.loss(f, idx, rv)
                L[k] = (q, se)
                M[k] = dict(qlike=float(q.mean()), mse=float(se.mean()), r2=float(100.0 * (1.0 - se.sum() / den)))
                num_rows.append(dict(framing=fr, panel=pid, model=k[0], set=k[1], n_intervals=len(idx), **M[k]))

            def dm(a, b, li):
                r = dm_test(T1.daily(L[a][li], idx), T1.daily(L[b][li], idx))
                return float(r["dm"]), float(r["p"]), int(r["hac_lag"]), int(r["T"])

            where = f"{'every interval' if fr == 'All' else 'closing half hour'}, panel {ptag} ({pid})"
            ols = ("ols", "baseline")
            af, vs = {}, {}
            for m, cap in PEN:
                full, har = (m, "all_features"), (m, "baseline")
                aq, am = dm(full, har, 0), dm(full, har, 1)
                af[m] = dict(
                    q_pct=pct(M[full]["qlike"], M[har]["qlike"]), q_dm=aq[0], q_p=aq[1],
                    m_pct=pct(M[full]["mse"], M[har]["mse"]), m_dm=am[0], m_p=am[1],
                )
                for s in ("baseline", "all_features"):
                    k = (m, s)
                    vq, vm = dm(k, ols, 0), dm(k, ols, 1)
                    vs[k] = dict(
                        q_pct=pct(M[k]["qlike"], M[ols]["qlike"]), q_dm=vq[0], q_p=vq[1],
                        m_pct=pct(M[k]["mse"], M[ols]["mse"]), m_dm=vm[0], m_p=vm[1],
                    )
                    for loss, d in (("qlike", vq), ("mse", vm)):
                        dm_rows.append(dict(framing=fr, panel=pid, a=f"{m}_{s}", b="ols_baseline", loss=loss,
                                            dm=d[0], p=d[1], hac_lag=d[2], T=d[3]))
                for loss, d in (("qlike", aq), ("mse", am)):
                    dm_rows.append(dict(framing=fr, panel=pid, a=f"{m}_all_features", b=f"{m}_baseline", loss=loss,
                                        dm=d[0], p=d[1], hac_lag=d[2], T=d[3]))
                c = f"{cap}{tag}"
                put(f"rhrrAf{c}Pct", signed(af[m]["q_pct"], 1), f"{m}: QLIKE % change, all features vs HAR, {where}")
                put(f"rhrrAf{c}Dm", signed(af[m]["q_dm"], 2), "... its DM (daily average QLIKE)")
                put(f"rhrrAf{c}Pval", pstmt(af[m]["q_p"]), "... its two-sided p (the whole statement)")
                put(f"rhrrAf{c}MsePct", signed(af[m]["m_pct"], 1), f"{m}: MSE % change, all features vs HAR, {where}")
                put(f"rhrrAf{c}MseDm", signed(af[m]["m_dm"], 2), "... its DM (daily average squared error)")
                put(f"rhrrAf{c}MsePval", pstmt(af[m]["m_p"]), "... its two-sided p")
                put(f"rhrrQ{cap}Har{tag}", f"{M[(m, 'baseline')]['qlike']:.4f}", f"mean QLIKE, {m}, HAR benchmark, {where}")
                put(f"rhrrQ{cap}Full{tag}", f"{M[full]['qlike']:.4f}", f"mean QLIKE, {m}, all features, {where}")

            a = af.values()
            n = len(PEN)
            put(f"rhrrAfPairs{tag}", str(n), f"linear classes compared, all features vs HAR, {where}")
            put(f"rhrrAfLower{tag}", str(sum(x["q_pct"] < 0 for x in a)), "... QLIKE lower with all features")
            put(f"rhrrAfLowerSig{tag}", str(sum(x["q_pct"] < 0 and x["q_p"] < ALPHA for x in a)), "... and DM p < 0.05")
            put(f"rhrrAfHigherSig{tag}", str(sum(x["q_pct"] > 0 and x["q_p"] < ALPHA for x in a)),
                "... QLIKE higher with all features and DM p < 0.05")
            put(f"rhrrAfMseHigher{tag}", str(sum(x["m_pct"] > 0 for x in a)), "... MSE higher with all features")
            put(f"rhrrAfMseHigherSig{tag}", str(sum(x["m_pct"] > 0 and x["m_p"] < ALPHA for x in a)),
                "... and DM (squared error) p < 0.05")
            put(f"rhrrAfMseLowerSig{tag}", str(sum(x["m_pct"] < 0 and x["m_p"] < ALPHA for x in a)),
                "... MSE lower with all features and DM p < 0.05")
            put(f"rhrrAfPctMin{tag}", signed(min(x["q_pct"] for x in a), 1), "... QLIKE % change: min")
            put(f"rhrrAfPctMax{tag}", signed(max(x["q_pct"] for x in a), 1), "... max")

            v = vs.values()
            put(f"rhrrPoolN{tag}", str(len(fc)), f"pooled linear forecasts (OLS + 3 penalized x 2 sets), {where}")
            put(f"rhrrNSet{tag}", str(len(vs)), "... other than the OLS")
            put(f"rhrrNLower{tag}", str(sum(x["q_pct"] < 0 for x in v)), "... with lower QLIKE than the pooled OLS")
            put(f"rhrrNLowerSig{tag}", str(sum(x["q_pct"] < 0 and x["q_p"] < ALPHA for x in v)), "... and DM p < 0.05")
            put(f"rhrrNWorseSig{tag}", str(sum(x["q_pct"] > 0 and x["q_p"] < ALPHA for x in v)),
                "... with higher QLIKE than the pooled OLS and DM p < 0.05")
            for s, sn in (("all_features", "Full"), ("baseline", "Har")):
                g = [vs[(m, s)] for m, _ in PEN]
                put(f"rhrrNLower{sn}{tag}", str(sum(x["q_pct"] < 0 for x in g)),
                    f"penalized forecasts on {sn} with lower QLIKE than the pooled OLS")
                put(f"rhrrNLowerSig{sn}{tag}", str(sum(x["q_pct"] < 0 and x["q_p"] < ALPHA for x in g)), "... and DM p < 0.05")
                put(f"rhrrNWorseSig{sn}{tag}", str(sum(x["q_pct"] > 0 and x["q_p"] < ALPHA for x in g)),
                    "... higher and DM p < 0.05")
                put(f"rhrrVsOls{sn}PctMin{tag}", signed(min(x["q_pct"] for x in g), 1),
                    f"penalized on {sn} vs the pooled OLS: QLIKE % change, min")
                put(f"rhrrVsOls{sn}PctMax{tag}", signed(max(x["q_pct"] for x in g), 1), "... max")
                put(f"rhrrPoolQLin{sn}Min{tag}", f"{min(M[(m, s)]['qlike'] for m, _ in PEN):.4f}",
                    f"mean QLIKE, penalized linear models on {sn}: min")
                put(f"rhrrPoolQLin{sn}Max{tag}", f"{max(M[(m, s)]['qlike'] for m, _ in PEN):.4f}", "... max")
            put(f"rhrrOlsQ{tag}", f"{M[ols]['qlike']:.4f}", f"mean QLIKE of the pooled OLS on the HAR benchmark, {where}")
            put(f"rhrrNInt{tag}", T1.thousands(len(idx)), f"scored intervals, {where}")

    lag = sorted({r["hac_lag"] for r in dm_rows})
    put("rhrrDMLag", ", ".join(str(x) for x in lag), "Newey-West lag of every test here (dm_test's automatic lag)")
    head = [
        HEAD,
        "% Counterparts of the prose macros of make_rehaul_results.py on the pooled linear reruns (linear classes only),",
        "% for the author's choice of framing. Not loaded by paper_rehaul.tex. \\rhrr<Name><Framing><Panel>:",
        "% Framing All = every interval of the panel's sample, Close = the closing half hour (16:00 row) only;",
        "% Panel A = trained on all 48 intervals, B = trained on the 13 regular-hours bars. 1,082 trading days,",
        "% 3 January 2020 .. 30 April 2024. Tests: dm_test on the daily average loss, p < 0.05 for 'Sig'.",
        "% 'vs OLS' = against the pooled OLS on the HAR benchmark of the same panel (the closing-interval OLS is not",
        "% in the reruns).",
    ]
    OUT_TEX.write_text("\n".join(head + mac) + "\n", encoding="utf-8", newline="\n")
    OUT_RES.mkdir(parents=True, exist_ok=True)
    nums, dms = pd.DataFrame(num_rows), pd.DataFrame(dm_rows)
    nums.to_csv(OUT_RES / "numbers.csv", index=False)
    dms.to_csv(OUT_RES / "dm.csv", index=False)
    with pd.option_context("display.width", 200):
        print(nums.to_string(index=False))
        print(dms.to_string(index=False))
    print(f"wrote {OUT_TEX.relative_to(REPO)} ({len(mac)} macros), {OUT_RES.relative_to(REPO)}/")


if __name__ == "__main__":
    main()
