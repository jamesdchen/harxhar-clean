"""tab:rh_beyond_factor_lin and the \\rhbyFL... macros: the linear factor test beyond HAR + realized moments + FOMC.

Requested by the author after the beyond-base results; not pre-registered (results/beyond_trees_2026-10-27/
RULE_linear.txt with its Amendment A: the earlier linear factor test, tab:rh_factor, with the base changed from the HAR
set to the add_rm_fomc arm and the component block to the six groups outside it).

READS    results/beyond_trees_2026-10-27/linear/ (experiments/beyond_factor_linear.py score): scores.csv, reading.json,
         gates.json, walk.json.  Every number is read from those files; R is re-derived from the stored QLIKEs and the
         reading re-applied only as consistency checks.
WRITES   writeup/generated/rehaul_beyond_factor_lin_numbers.tex   \\rhbyFL... macros (letters only)
         writeup/generated/rehaul_beyond_factor_lin_table.tex     Table tab:rh_beyond_factor_lin
Macros   \\rhbyFL<M><S><Q>: M = PcaOne PcaTwo PcaThree PcaFive PcaTen PcaTwenty PlsOne PlsTwo PlsThree, Full (the span's
         L_full model), S = Ord (ORDINARY days, primary) All (every bar) Ev (the 81 FOMC statement days), Q = Qlike, Pct
         (QLIKE change against BASE_LIN, %), Dm / P (DM against BASE_LIN, QLIKE), DmFull / PFull (DM against the full
         set), R, MsePct; \\rhbyFLBase<S>Qlike; \\rhbyFLFull<S>Model; the reading (\\rhbyFLReading, ...), FULL_LIN vs
         BASE_LIN on ORDINARY days (information: \\rhbyFLFullOrdPct, \\rhbyFLFullOrdDm, \\rhbyFLFullOrdP), the variance
         shares (\\rhbyFLShare...), the first component's loadings by group (\\rhbyFLLoad<G>, ...), counts, gate figures.

Run:  python writeup/make_rehaul_beyond_factor_lin.py     (from the repository root)
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RES = ROOT / "results" / "beyond_trees_2026-10-27" / "linear"
GEN = HERE / "generated"
OUT_NUM = GEN / "rehaul_beyond_factor_lin_numbers.tex"
OUT_TAB = GEN / "rehaul_beyond_factor_lin_table.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_beyond_factor_lin.py -- do not edit; re-run the script."
LABEL = "requested by the author after the beyond-base results; not pre-registered"
K_PCA = (1, 2, 3, 5, 10, 20)
K_PLS = (1, 2, 3)
KW = {1: "One", 2: "Two", 3: "Three", 5: "Five", 10: "Ten", 20: "Twenty"}
MODELS = [f"pca{k}" for k in K_PCA] + [f"pls{k}" for k in K_PLS]
MTAG = {f"pca{k}": f"Pca{KW[k]}" for k in K_PCA} | {f"pls{k}": f"Pls{KW[k]}" for k in K_PLS}
STAG = {"ordinary": "Ord", "all": "All", "event": "Ev"}
FULL_NAME = {"ridge": "ridge", "enet": "elastic net"}
GROUPS = {
    "ew": ("Ew", "Equal-weighted market"),
    "vw": ("Vw", "Value-weighted market"),
    "liq": ("Liq", "Liquidity"),
    "iv": ("Iv", "Implied volatility"),
    "sent": ("Sent", "Sentiment"),
    "vd": ("Vd", "Volatility demand"),
}
READ_WORD = {
    "SHARED FACTOR": "shared factor",
    "DENSE BEYOND A FEW FACTORS": "dense beyond a few factors",
    "INTERMEDIATE": "intermediate",
}
N_FC, N_SCORED, N_EVENT, N_ORD, N_BASE, N_BLOCK, N_SERIES = 33_970, 33_527, 81, 2_498, 132, 216, 36


def num(x: float, nd: int = 2) -> str:
    s = f"{x:.{nd}f}"
    if s.startswith("-") and float(s) == 0.0:
        s = s[1:]
    return "$-$" + s[1:] if s.startswith("-") else s


def pval(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def sci(x: float) -> str:
    m, e = f"{x:.0e}".split("e")
    return f"${m} \\times 10^{{{int(e)}}}$"


def thousands(x: int) -> str:
    return f"{x:,}".replace(",", "{,}")


def model_tex(m: str) -> str:
    return ("PCA" if m.startswith("pca") else "PLS") + f", $k = {int(m[3:])}$"


def main() -> None:
    gates = json.loads((RES / "gates.json").read_text())
    walk = json.loads((RES / "walk.json").read_text())
    rd = json.loads((RES / "reading.json").read_text())
    S = pd.read_csv(RES / "scores.csv")
    # ---------------------------------------------------------------- gates and design, asserted
    assert gates["pass"], gates["fail"]
    assert gates["G1"]["pass"] and gates["G1"]["max_rel_pred"] <= 1e-10 and gates["G1"]["rows"] == walk["bars"] == N_FC
    assert gates["G2"]["pass"] and gates["G2"]["max_rel"] <= 1e-8 and len(gates["G2"]["days"]) >= 5
    g3 = gates["G3"]
    assert g3["pass"] and g3["n_bars"] == N_SCORED and g3["n_event_days"] == N_EVENT and g3["ordinary_days"] == N_ORD
    assert walk["base_columns"] == N_BASE and walk["block_columns"] == N_BLOCK and walk["block_series"] == N_SERIES
    assert walk["models"] == ["k0", *MODELS], walk["models"]
    for sp in STAG:
        s = S[S["span"] == sp].set_index("model")
        assert int(s["n_bars"].iloc[0]) == {"all": N_SCORED, "event": 13 * N_EVENT, "ordinary": 13 * N_ORD}[sp]
        full = s["full_ref"].iloc[0]
        lb, lf = s.loc["base_lin", "qlike"], s.loc[f"{full}_full", "qlike"]
        assert lf == min(s.loc["ridge_full", "qlike"], s.loc["enet_full", "qlike"])
        for m in MODELS:
            assert np.isclose(s.loc[m, "R"], (lb - s.loc[m, "qlike"]) / (lb - lf), rtol=1e-9, atol=1e-12), (sp, m)
        assert abs(s.loc["k0", "qlike"] / lb - 1.0) < 1e-9, "k = 0 is BASE_LIN"
    r = rd["reading"]
    d = rd["descriptive"]
    o = S[S["span"] == "ordinary"].set_index("model")
    small = [m for m in MODELS if int(m[3:]) <= 3]
    shared = [
        m
        for m in small
        if o.loc[m, "R"] >= 0.75 and not (o.loc[m, "p_full_qlike"] < 0.05 and o.loc[m, "diff_full_qlike"] > 0)
    ]
    dense = bool(
        o.loc["pca10", "R"] < 0.5 and o.loc["pca10", "p_full_qlike"] < 0.05 and o.loc["pca10", "diff_full_qlike"] > 0
    )
    word = "SHARED FACTOR" if shared else ("DENSE BEYOND A FEW FACTORS" if dense else "INTERMEDIATE")
    assert word == r["reading"] and shared == r["shared_factor_models"], (word, r["reading"])

    # ---------------------------------------------------------------- macros
    M: list[tuple[str, str, str]] = []

    def add(name: str, value: str, note: str) -> None:
        assert name.isalpha() and name.startswith("rhbyFL") and name[6].isupper(), name
        M.append((name, value, note))

    for sp, st in STAG.items():
        s = S[S["span"] == sp].set_index("model")
        full = s["full_ref"].iloc[0]
        add(f"rhbyFLBase{st}Qlike", num(s.loc["base_lin", "qlike"], 4), f"BASE_LIN {sp}: QLIKE")
        for m in MODELS:
            x = s.loc[m]
            t = f"rhbyFL{MTAG[m]}{st}"
            add(f"{t}Qlike", num(x["qlike"], 4), f"{m} {sp}: QLIKE")
            add(f"{t}Pct", num(x["qlike_pct_vs_base"]), f"{m} {sp}: QLIKE change vs BASE_LIN, %")
            add(f"{t}MsePct", num(x["mse_pct_vs_base"]), f"{m} {sp}: MSE change vs BASE_LIN, %")
            add(f"{t}Dm", num(x["dm_base_qlike"]), f"{m} {sp}: DM vs BASE_LIN (QLIKE; HLN, daily means, lag 8)")
            add(f"{t}P", pval(x["p_base_qlike"]), f"{m} {sp}: p")
            add(f"{t}DmFull", num(x["dm_full_qlike"]), f"{m} {sp}: DM vs the full set ({full})")
            add(f"{t}PFull", pval(x["p_full_qlike"]), f"{m} {sp}: p")
            add(f"{t}R", num(x["R"]), f"{m} {sp}: R = (L_BASE - L_arm) / (L_BASE - L_full)")
        f = s.loc[f"{full}_full"]
        add(f"rhbyFLFull{st}Model", FULL_NAME[full], f"{sp}: L_full model (lower QLIKE of ridge, elastic net)")
        add(f"rhbyFLFull{st}Qlike", num(f["qlike"], 4), f"{sp}: full set QLIKE")
        add(f"rhbyFLFull{st}Pct", num(f["qlike_pct_vs_base"]), f"{sp}: full set QLIKE change vs BASE_LIN, %")
        add(f"rhbyFLFull{st}MsePct", num(f["mse_pct_vs_base"]), f"{sp}: full set MSE change vs BASE_LIN, %")
        add(f"rhbyFLFull{st}Dm", num(f["dm_base_qlike"]), f"{sp}: full set DM vs BASE_LIN (information)")
        add(f"rhbyFLFull{st}P", pval(f["p_base_qlike"]), f"{sp}: p")
        add(f"rhbyFLN{st}Days", thousands(int(s["n_days"].iloc[0])), f"{sp}: days")
        add(f"rhbyFLN{st}Bars", thousands(int(s["n_bars"].iloc[0])), f"{sp}: bars")
    add("rhbyFLReading", READ_WORD[r["reading"]], "the RULE's reading (Amendment A), ORDINARY days")
    best = r["best_small_k"]
    add("rhbyFLBestSmall", model_tex(best), "the k <= 3 model with the highest R on ORDINARY days")
    add("rhbyFLBestSmallR", num(o.loc[best, "R"]), "its R")
    add("rhbyFLBestSmallPFull", pval(o.loc[best, "p_full_qlike"]), "its DM p against the full set")
    add("rhbyFLNSharedModels", str(len(shared)), "k <= 3 models meeting the SHARED FACTOR condition")
    add("rhbyFLShareThreshold", "0.75", "SHARED FACTOR: R threshold")
    add("rhbyFLDenseThreshold", "0.5", "DENSE: R(PCA 10) threshold")
    add(
        "rhbyFLFullOrdSignificant",
        "yes" if r["full_vs_base"]["ordinary"]["full_beats_base_significantly"] else "no",
        "FULL_LIN significantly below BASE_LIN on ORDINARY days (information)",
    )
    add("rhbyFLNBase", str(N_BASE), "BASE_LIN columns (HAR set + realized moments + FOMC)")
    add("rhbyFLNBlock", str(N_BLOCK), "block columns (value averages, 36 series x 6 horizons)")
    add("rhbyFLNSeries", str(N_SERIES), "block series (ew, vw, liq, iv, sent, vd)")
    add("rhbyFLNActiveMin", str(d["n_active_min"]), "fewest active block columns on a scored day")
    add("rhbyFLNActiveMax", str(d["n_active_max"]), "most active block columns on a scored day")
    for j, w in ((1, "One"), (2, "Two"), (3, "Three")):
        add(f"rhbyFLSharePc{w}", num(100 * d["share_pc"][str(j)], 1), f"mean share of block variance, component {j}, %")
    for k in K_PCA:
        add(f"rhbyFLShareCum{KW[k]}", num(100 * d["share_cum"][str(k)], 1), f"mean share in components 1-{k}, %")
    add("rhbyFLShareCumThreeMin", num(100 * d["share_cum3_min"], 1), "components 1-3: lowest day, %")
    add("rhbyFLShareCumThreeMax", num(100 * d["share_cum3_max"], 1), "components 1-3: highest day, %")
    for g, (gt, label) in GROUPS.items():
        add(f"rhbyFLLoad{gt}", num(d["pc1_abs"][g]), f"PC1: sum of |loadings|, {label}")
        add(f"rhbyFLLoadSq{gt}", num(100 * d["pc1_sq"][g], 1), f"PC1: share of squared loadings, {label}, %")
        add(f"rhbyFLPlsLoad{gt}", num(d["pls1_abs"][g]), f"PLS1: sum of |weights|, {label}")
        add(f"rhbyFLPlsLoadSq{gt}", num(100 * d["pls1_sq"][g], 1), f"PLS1: share of squared weights, {label}, %")
        add(f"rhbyFLNCols{gt}", num(d["n_cols"][g], 1), f"active block columns of {label} (mean over days)")
    top = max(GROUPS, key=lambda g: d["pc1_sq"][g])
    add("rhbyFLLoadTopGroup", GROUPS[top][1].lower(), "group with the largest PC1 share of squared loadings")
    add("rhbyFLGOneMaxRel", sci(gates["G1"]["max_rel_pred"]), "G1: k = 0 vs the ablation's OLS add_rm_fomc, max rel.")
    add("rhbyFLGTwoMaxRel", sci(gates["G2"]["max_rel"]), "G2: Gram route vs direct lstsq, max relative difference")
    add("rhbyFLGTwoNDays", str(len(gates["G2"]["days"])), "G2 days")
    add("rhbyFLLabel", LABEL, "disclosure label")
    names = [n for n, _, _ in M]
    assert len(set(names)) == len(names), "a macro name twice"
    GEN.mkdir(parents=True, exist_ok=True)
    lines = [
        HEAD,
        f"% \\rhbyFL... macros: the linear factor test beyond HAR + RM + FOMC ({LABEL};",
        "% results/beyond_trees_2026-10-27/RULE_linear.txt, Amendment A; results/beyond_trees_2026-10-27/linear).",
        "% Spans: Ord = ORDINARY days (primary), All = every bar, Ev = the 81 FOMC statement days.  Models: Pca<k>,",
        "% Pls<k>, Base (BASE_LIN), Full (the span's L_full model).",
    ]
    for name, value, note in M:
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}  % {note}")
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_NUM.name}: {len(M)} macros")
    table(S, r)


def table(S: pd.DataFrame, r: dict) -> None:
    def cells(s: pd.DataFrame, m: str, full: str) -> list[str]:
        x = s.loc[m]
        a = f"{num(x['qlike_pct_vs_base'])} ({num(x['dm_base_qlike'])})"
        if m.endswith("_full"):
            return [a, "1.00" if m == f"{full}_full" else num(x["R"]), "--"]
        return [a, num(x["R"]), num(x["dm_full_qlike"])]

    so = S[S["span"] == "ordinary"].set_index("model")
    sa = S[S["span"] == "all"].set_index("model")
    fo, fa = so["full_ref"].iloc[0], sa["full_ref"].iloc[0]
    body = []
    for meth, ks, label in (("pca", K_PCA, "Base + principal components"), ("pls", K_PLS, "Base + PLS components")):
        body.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\textit{{{label}}}}} \\\\")
        for k in ks:
            m = f"{meth}{k}"
            body.append(" & ".join([f"$k = {k}$", *cells(so, m, fo), *cells(sa, m, fa)]) + " \\\\")
        body.append("\\addlinespace[3pt]")
    fr = [f"Full set ({FULL_NAME[fo]}" + (")" if fo == fa else f" / {FULL_NAME[fa]})")]
    body.append(" & ".join([*fr, *cells(so, f"{fo}_full", fo), *cells(sa, f"{fa}_full", fa)]) + " \\\\")
    fsig = r["full_vs_base"]["ordinary"]["full_beats_base_significantly"]
    fnote = (
        "The full-set row is $R$'s denominator: on ordinary days the full set's QLIKE is \\rhbyFLFullOrdPct{}\\%"
        " against the base (DM \\rhbyFLFullOrdDm{}, $p$ = \\rhbyFLFullOrdP{})"
        + (
            "."
            if fsig
            else ", not significantly below it, so $R$ divides by a difference that is itself not significant"
            " (reported as information; the reading's rule is unchanged)."
        )
    )
    if sa.loc[f"{fa}_full", "qlike_pct_vs_base"] > 0:  # the every-bar full set is worse than the base
        fnote += (
            "  On every bar the full set's QLIKE is \\rhbyFLFullAllPct{}\\% against the base (DM \\rhbyFLFullAllDm{}):"
            " its losses on the FOMC statement days put it above the base, $R$'s denominator is negative there and"
            " $R$ is not a recovered share."
        )
    tex = [
        HEAD,
        f"% tab:rh_beyond_factor_lin (results/beyond_trees_2026-10-27/RULE_linear.txt, Amendment A; {LABEL}).",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{threeparttable}",
        "\\caption{Beyond HAR, realized moments and the FOMC calendar: OLS with a few components of the remaining"
        " predictors}",
        "\\label{tab:rh_beyond_factor_lin}",
        "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrr@{}}",
        "\\toprule",
        " & \\multicolumn{3}{c}{Ordinary days (\\rhbyFLNOrdDays{} days)} & \\multicolumn{3}{c}{Every bar"
        " (\\rhbyFLNAllDays{} days)} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(l){5-7}",
        " & QLIKE \\% (DM) & $R$ & DM vs full & QLIKE \\% (DM) & $R$ & DM vs full \\\\",
        "\\midrule",
        *body,
        "\\bottomrule",
        "\\end{tabular*}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        "\\item \\textit{Notes:} Requested by the author after the results beyond HAR + RM + FOMC"
        " (Table~\\ref{tab:rh_ablation_beyond}); not part of the pre-specified design.  The factor test of"
        " Table~\\ref{tab:rh_factor} with its base changed: OLS on the HAR benchmark set plus the futures' realized"
        " moments and the FOMC calendar (\\rhbyFLNBase{} columns, the base of Table~\\ref{tab:rh_ablation_beyond}),"
        " plus the first $k$ principal components, or partial-least-squares components against the target, of the"
        " remaining predictors' value averages (the equal- and value-weighted market, liquidity, implied volatility,"
        " sentiment and volatility demand: \\rhbyFLNBlock{} columns of \\rhbyFLNSeries{} series), standardized within"
        " the rolling window, the loadings re-estimated once a trading day from the window ending at the previous bar;"
        " min-norm OLS re-estimated at every bar on the 39{,}000-row window, FOMC-patched design.  QLIKE \\%: change"
        " against the base, with the Diebold--Mariano statistic (HLN, daily mean losses, lag 8) in parentheses;"
        " negative favours the row.  $R = (L_{\\mathrm{base}} - L_k)/(L_{\\mathrm{base}} - L_{\\mathrm{full}})$,"
        " $L_{\\mathrm{full}}$ the lower QLIKE of Table~\\ref{tab:rh_oos}'s full-set ridge and elastic net on the same"
        " days; DM vs full: the row against that full set (negative favours the row).  "
        + fnote
        + "  Ordinary days exclude the \\rhbyFLNEvDays{} scheduled FOMC statement days.  Reading on ordinary days,"
        " fixed before scoring (the rule of Table~\\ref{tab:rh_factor}): \\rhbyFLReading{}.",
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
    ]
    OUT_TAB.write_text("\n".join(tex) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_TAB.name}")


if __name__ == "__main__":
    main()
