"""Summary numbers of the macro release calendar ablations for the prose of app:rh_results_macro: \\rhms...

RULE    results/ablations_2014start_w3000/RULE.txt addendum L (29 Oct 2026) and its amendment (iii) (30 Oct 2026).
READS   results/ablations_2014start_w3000/scores_fomcfix/ (experiments/ablate_score.py: metrics.csv, dm.csv,
        checks.json; experiments/mac_robust2019.py: robust2019.csv) and the excluded window LO, HI of
        experiments/mac_robust2019.py (read from its source text).  Every number summarizes those files; no forecast is
        read and no loss is recomputed.
WRITES  writeup/generated/rehaul_macro_summary_numbers.tex   \\rhms... macros (definitions only, letters only; no other
        generated file uses the prefix).

Panels as tab:rh_ablation_macro: A = HAR + one release calendar against the class's HAR (add_mac_<r> vs har); B = HAR +
RM + FOMC + one release calendar against HAR + RM + FOMC (add_rm_fomc_mac_<r> vs add_rm_fomc).  Spans S: All (every
scored bar), Nrel (the scored days without the row's release), Rel (the days with it).  Class groups G: Pen (ridge,
lasso, elastic net), Ols (Panel B only: the OLS is walked on the HAR + RM + FOMC arms only), Tree (LightGBM, XGBoost);
no G: the three groups together.  The random forest's macro arms are pending and enter no macro.  A cell is one
(class, release) pair with forecasts for the arm and its reference; it is significant when its Diebold-Mariano p-value
is below ALPHA, lower or higher by the sign of the DM statistic (asserted equal to the sign of the QLIKE change).
  \\rhmsSigLevel                                       ALPHA in percent
  \\rhmsPan<P><S>[<G>]MaxAbsPct                        largest |QLIKE change, %| over the cells (1 decimal, as the table)
  \\rhmsPan<P><S>[<G>]PMin                             smallest DM p-value over the cells
  \\rhmsPan<P><S>[<G>]NSigLower, ...NSigHigher         cells with a significantly lower / higher loss
  \\rhmsPan<P><S>[<G>]NCells                           cells
  \\rhmsFomcAllGainMin, ...GainMax, ...PMax            the FOMC row of Panel B of tab:rh_ablation (add_fomc vs har, every
                                                      bar) over the Pen and Tree classes: smallest / largest fall in QLIKE
                                                      (%; asserted to be a fall in each class), largest p
  \\rhmsPanBCpiRelLin{PctMin,PctMax,DmMin,DmMax,PMax,NSigHigher,NCls}
                                                      Panel B, CPI release days, the linear classes (OLS and Pen)
  \\rhmsRobustExclFirst, ...ExclLast                   first and last calendar day of the excluded window [LO, HI)
  \\rhmsRobustOls{All,Ex}{Pct,Dm,P}                    OLS, HAR + RM + FOMC + all six calendars against HAR + RM + FOMC,
                                                      every bar (All) and without the window (Ex)
  \\rhmsRobustNOther, \\rhmsRobustOtherMaxMove          the other pairs of robust2019.csv: their number and the largest
                                                      |change of the QLIKE change| without the window (percentage points,
                                                      2 decimals rounded up, so "at most" holds)
  \\rhmsRobustNSigCross                                pairs whose significance at ALPHA differs with and without it

usage: python writeup/make_rehaul_macro_summary.py   (any working directory)
"""

from __future__ import annotations

import json
import math
import re
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
RES = REPO / "results" / "ablations_2014start_w3000" / "scores_fomcfix"
ROBUST_SRC = REPO / "experiments" / "mac_robust2019.py"
OUT = HERE / "generated" / "rehaul_macro_summary_numbers.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_macro_summary.py -- do not edit; re-run the script."
# the paper's level (Appendix rehaul/10_statistical_tests.tex: "significance at the 5% level (p < 0.05)")
ALPHA = 0.05
REL_TEX = {
    "cpi": "Cpi",
    "emp": "Emp",
    "ppi": "Ppi",
    "gdp": "Gdp",
    "trade": "Trade",
    "retail": "Retail",
}
GROUPS = {"Pen": ("ridge", "lasso", "enet"), "Ols": ("ols",), "Tree": ("lgbm", "xgb")}
# panel -> (arm prefix + release, reference arm), as make_rehaul_ablations.py MAC_PER
PANELS = {"A": ("add_mac_", "har"), "B": ("add_rm_fomc_mac_", "add_rm_fomc")}
SPANS = {"all": "All", "nrel": "Nrel", "rel": "Rel"}


def fmt(x: float, dp: int) -> str:
    """As make_rehaul_ablations.fmt: rounded, a minus as $-$, no negative zero."""
    v = round(float(x), dp)
    if v == 0:
        v = 0.0
    return f"{'$-$' if v < 0 else ''}{abs(v):.{dp}f}"


def fmt_p(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def date_tex(t: pd.Timestamp) -> str:
    return f"{t.day}~{t.strftime('%B')} {t.year}"


def span(sp: str, r: str) -> str:
    """The scorer's span of the day split sp for release r (as make_rehaul_ablations.mac_span)."""
    return sp if sp == "all" else f"{sp}_{r}"


def main() -> int:
    M = pd.read_csv(RES / "metrics.csv")
    D = pd.read_csv(RES / "dm.csv")
    checks = json.loads((RES / "checks.json").read_text())
    assert checks["pass"], checks["fail"]
    rels = list(checks["macro_releases"]["releases"])
    assert rels == list(REL_TEX), rels
    q = M.set_index(["cls", "arm", "span"])["qlike"]
    dq = D[D["loss"] == "qlike"].set_index(["cls", "arm", "vs_cls", "vs_arm", "span"])

    out: list[tuple[str, str, str]] = []

    def add(name: str, value: str, note: str) -> None:
        assert name.isalpha(), name
        out.append(("rhms" + name, value, note))

    def cell(c: str, a: str, b: str, sp: str) -> tuple[float, float, float] | None:
        """(% QLIKE change of arm a against b, DM, p) of class c on span sp; None without forecasts or test."""
        k = (c, a, c, b, sp)
        if (c, a, sp) not in q.index or (c, b, sp) not in q.index or k not in dq.index:
            return None
        pc = 100.0 * (q[(c, a, sp)] / q[(c, b, sp)] - 1.0)
        return pc, float(dq.loc[k, "dm"]), float(dq.loc[k, "p"])

    add(
        "SigLevel",
        f"{100 * ALPHA:.0f}",
        "significance level of the counts, % (the paper's 5% level)",
    )
    for P, (pre, ref) in PANELS.items():
        for sp, st in SPANS.items():
            cells: dict[str, list[tuple[float, float, float]]] = {}
            for g, classes in GROUPS.items():
                cells[g] = [x for c in classes for r in rels if (x := cell(c, pre + r, ref, span(sp, r))) is not None]
            cells[""] = [x for g in GROUPS for x in cells[g]]
            for g, xs in cells.items():
                if not xs:  # the OLS in Panel A: not walked
                    continue
                nm = f"Pan{P}{st}{g}"
                who = f"Panel {P} {sp} {g or 'Pen + Ols + Tree'}"
                sig = [(pc, d) for pc, d, p in xs if p < ALPHA]
                assert all((pc > 0) == (d > 0) for pc, d in sig), f"{who}: a significant cell with opposite signs"
                add(
                    f"{nm}MaxAbsPct",
                    fmt(max(abs(pc) for pc, _d, _p in xs), 1),
                    f"{who}: largest |QLIKE change|, %",
                )
                add(
                    f"{nm}PMin",
                    fmt_p(min(p for _pc, _d, p in xs)),
                    f"{who}: smallest DM p",
                )
                add(
                    f"{nm}NSigLower",
                    str(sum(d < 0 for _pc, d in sig)),
                    f"{who}: cells significantly lower, p < ALPHA",
                )
                add(
                    f"{nm}NSigHigher",
                    str(sum(d > 0 for _pc, d in sig)),
                    f"{who}: cells significantly higher",
                )
                add(
                    f"{nm}NCells",
                    str(len(xs)),
                    f"{who}: (class, release) cells with forecasts",
                )

    # the FOMC row of Panel B of tab:rh_ablation, every bar, over the classes of the macro Panel A
    fomc = [x for g in ("Pen", "Tree") for c in GROUPS[g] if (x := cell(c, "add_fomc", "har", "all")) is not None]
    assert len(fomc) == len(GROUPS["Pen"]) + len(GROUPS["Tree"]), len(fomc)
    assert all(pc < 0 for pc, _d, _p in fomc), "the FOMC calendar no longer lowers the loss in each class"
    add(
        "FomcAllGainMin",
        fmt(min(-pc for pc, _d, _p in fomc), 1),
        "HAR + FOMC vs HAR, every bar: smallest fall, %",
    )
    add(
        "FomcAllGainMax",
        fmt(max(-pc for pc, _d, _p in fomc), 1),
        "... largest fall, % (ridge, lasso, enet, lgbm, xgb)",
    )
    add("FomcAllPMax", fmt_p(max(p for _pc, _d, p in fomc)), "... largest DM p")

    # Panel B, CPI release days, the linear classes
    lin = GROUPS["Ols"] + GROUPS["Pen"]
    cpi = [x for c in lin if (x := cell(c, "add_rm_fomc_mac_cpi", "add_rm_fomc", "rel_cpi")) is not None]
    assert len(cpi) == len(lin), len(cpi)
    w = "Panel B, CPI release days, OLS ridge lasso enet"
    add(
        "PanBCpiRelLinPctMin",
        fmt(min(pc for pc, _d, _p in cpi), 1),
        f"{w}: smallest QLIKE change, %",
    )
    add(
        "PanBCpiRelLinPctMax",
        fmt(max(pc for pc, _d, _p in cpi), 1),
        f"{w}: largest QLIKE change, %",
    )
    add("PanBCpiRelLinDmMin", fmt(min(d for _pc, d, _p in cpi), 2), f"{w}: smallest DM")
    add("PanBCpiRelLinDmMax", fmt(max(d for _pc, d, _p in cpi), 2), f"{w}: largest DM")
    add("PanBCpiRelLinPMax", fmt_p(max(p for _pc, _d, p in cpi)), f"{w}: largest p")
    add(
        "PanBCpiRelLinNSigHigher",
        str(sum(p < ALPHA and d > 0 for _pc, d, p in cpi)),
        f"{w}: significantly higher",
    )
    add("PanBCpiRelLinNCls", str(len(cpi)), f"{w}: classes")

    # the excluded window of experiments/mac_robust2019.py and its scores
    m = re.search(
        r'^LO, HI = pd\.Timestamp\("([\d-]+)"\), pd\.Timestamp\("([\d-]+)"\)',
        ROBUST_SRC.read_text(),
        re.M,
    )
    assert m, f"LO, HI not found in {ROBUST_SRC.name}"
    lo, hi = pd.Timestamp(m.group(1)), pd.Timestamp(m.group(2))
    add(
        "RobustExclFirst",
        date_tex(lo),
        "first day of the window left out (mac_robust2019.LO)",
    )
    add(
        "RobustExclLast",
        date_tex(hi - pd.Timedelta(days=1)),
        "last day of it (the day before mac_robust2019.HI)",
    )
    R = pd.read_csv(RES / "robust2019.csv")
    for row in R[R["span"] == "all"].itertuples():  # the robustness file's every-bar scores = the scorer's
        x = cell(str(row.cls), str(row.arm), str(row.ref), "all")
        assert x is not None and abs(x[0] - float(row.pct)) < 1e-8, (row.cls, row.arm)
    W = R.pivot_table(index=["cls", "arm"], columns="span", values=["pct", "dm", "p"])
    ols = W.loc[("ols", "add_rm_fomc_mac")]
    for sp, st in (("all", "All"), ("ex2019h1", "Ex")):
        w = f"OLS HAR + RM + FOMC + all six vs HAR + RM + FOMC, {sp}"
        add(f"RobustOls{st}Pct", fmt(ols[("pct", sp)], 1), f"{w}: QLIKE change, %")
        add(f"RobustOls{st}Dm", fmt(ols[("dm", sp)], 2), f"{w}: DM")
        add(f"RobustOls{st}P", fmt_p(ols[("p", sp)]), f"{w}: p")
    other = W.drop(index=("ols", "add_rm_fomc_mac"))
    move = (other[("pct", "ex2019h1")] - other[("pct", "all")]).abs().max()
    add("RobustNOther", str(len(other)), "other macro pairs of robust2019.csv")
    add(
        "RobustOtherMaxMove",
        f"{math.ceil(100 * move) / 100:.2f}",
        "their largest |change| without the window, pp",
    )
    cross = ((other[("p", "all")] < ALPHA) != (other[("p", "ex2019h1")] < ALPHA)).sum()
    cross += int((ols[("p", "all")] < ALPHA) != (ols[("p", "ex2019h1")] < ALPHA))
    add(
        "RobustNSigCross",
        str(int(cross)),
        "pairs significant at ALPHA on one of the two spans only",
    )

    names = [n for n, _v, _c in out]
    assert len(set(names)) == len(names), "a macro defined twice"
    lines = [
        HEAD,
        "% \\rhms...: summary numbers of the macro release calendar ablations (RULE.txt addendum L and (iii)) for",
        "% app:rh_results_macro; from results/ablations_2014start_w3000/scores_fomcfix/ (metrics, dm, checks, robust2019).",
        "% Panels P = A (HAR + one calendar vs HAR), B (HAR + RM + FOMC + one calendar vs HAR + RM + FOMC); spans S = All,",
        "% Nrel, Rel; groups G = Pen (ridge, lasso, elastic net), Ols (Panel B), Tree (LightGBM, XGBoost), none = all three.",
        "% The random forest's macro cells are pending and enter no macro.  Macros:",
        "%   \\rhmsSigLevel; \\rhmsPan<P><S>[<G>]{MaxAbsPct,PMin,NSigLower,NSigHigher,NCells};",
        "%   \\rhmsFomcAll{GainMin,GainMax,PMax}; \\rhmsPanBCpiRelLin{PctMin,PctMax,DmMin,DmMax,PMax,NSigHigher,NCls};",
        "%   \\rhmsRobust{ExclFirst,ExclLast}, \\rhmsRobustOls{All,Ex}{Pct,Dm,P}, \\rhmsRobust{NOther,OtherMaxMove,NSigCross}.",
    ]
    lines += [f"\\providecommand{{\\{n}}}{{}}\\renewcommand{{\\{n}}}{{{v}}}  % {c}" for n, v, c in out]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(out)} macros to {OUT.relative_to(REPO).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
