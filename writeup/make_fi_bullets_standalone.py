def parked_block(text: str) -> str:
    """The lines strictly between the first \\iffalse after the subsection heading and its \\fi."""
    lines = text.splitlines()
    head = next(i for i, s in enumerate(lines) if s.startswith(r"\subsection{Variable importance}"))
    start = next(i for i in range(head, len(lines)) if lines[i].strip() == r"\iffalse")
    end = next(i for i in range(start + 1, len(lines)) if lines[i].strip() == r"\fi")
    body = [s for s in lines[start + 1 : end]]
    first = next(s for s in body if s.strip() and not s.lstrip().startswith("%"))
    last = next(s for s in reversed(body) if s.strip() and not s.lstrip().startswith("%"))
    assert first.strip() == r"\begin{itemize}" and last.strip() == r"\end{itemize}", (first, last)
    return "\n".join(body) + "\n"


def build() -> None:
    def run(*cmd: str) -> None:
        r = subprocess.run(cmd, cwd=WRITEUP, capture_output=True, text=True)
        if r.returncode != 0:
            sys.stdout.write(r.stdout[-4000:])
            raise SystemExit(f"{' '.join(cmd)} failed")

    tex = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", OUT.stem]
    run(*tex)
    run("bibtex", OUT.stem)
    run(*tex)
    run(*tex)


def main() -> None:
    OUT.write_text(PREAMBLE + parked_block(SRC.read_text(encoding="utf-8")) + POSTAMBLE, encoding="utf-8")
    print(f"wrote {OUT.relative_to(WRITEUP.parent)}")
    if "--build" in sys.argv[1:]:
        build()
        print(f"built {OUT.with_suffix('.pdf').relative_to(WRITEUP.parent)}")


if __name__ == "__main__":
    main()
