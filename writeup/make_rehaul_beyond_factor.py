"""tab:rh_beyond_factor and the \\rhbyF... macros: the trees' factor test beyond HAR + realized moments + FOMC.

Requested by the author after the beyond-base results; not pre-registered (results/beyond_trees_2026-10-27/RULE.txt
sections 0, 1, 3 and addendum 1).  Reads results/beyond_trees_2026-10-27/factor/scores.csv and reading.json (written by
experiments/beyond_factor_score.py); writes
  writeup/generated/rehaul_beyond_factor_table.tex    tab:rh_beyond_factor
  writeup/generated/rehaul_beyond_factor_numbers.tex  \\rhbyF<Model><Arm><Span><Quantity>, \\rhbyF<Model>Reading, ...
Model: Lgbm, Xgb.  Arm: Base, PcaOne, PcaTwo, PcaThree, PcaFive, PcaTen, PlsOne, PlsThree, Full.  Span: Ord (ORDINARY
days, primary), All (every bar), Ev (the 81 FOMC statement days).  Quantity: Qlike, Pct (QLIKE change in % against
BASE), Dm / P (against BASE), DmFull / PFull (against FULL), R (recovery (L_BASE - L_arm) / (L_BASE - L_FULL)).

usage: python writeup/make_rehaul_beyond_factor.py [--gen writeup/generated]
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
RES = REPO / "results" / "beyond_trees_2026-10-27" / "factor"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_beyond_factor.py -- do not edit; re-run the script."
LABEL = "requested by the author after the beyond-base results; not pre-registered"
MODELS = {"lgbm": ("Lgbm", "LightGBM"), "xgb": ("Xgb", "XGBoost")}
ARMS = {
    "base": ("Base", "Base (HAR + RM + FOMC)"),
    "pca1": ("PcaOne", "Base + 1 principal component"),
    "pca2": ("PcaTwo", "Base + 2 principal components"),
    "pca3": ("PcaThree", "Base + 3 principal components"),
    "pca5": ("PcaFive", "Base + 5 principal components"),
    "pca10": ("PcaTen", "Base + 10 principal components"),
    "pls1": ("PlsOne", "Base + 1 PLS component"),
    "pls3": ("PlsThree", "Base + 3 PLS components"),
    "full": ("Full", "Full set"),
}
SPANS = {"ordinary": "Ord", "all": "All", "event": "Ev"}
READ = {
    "SHARED COMPONENT": "shared component",
    "DENSE BEYOND A FEW COMPONENTS": "dense beyond a few components",
    "INTERMEDIATE": "intermediate",
}


def fmt(x: float, dp: int) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    s = f"{x:.{dp}f}"
    if float(s) == 0.0:
        s = f"{0.0:.{dp}f}"
    return "$-$" + s[1:] if s.startswith("-") else s


def fmt_p(p: float) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    return r"\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def mac(name: str, value: str, comment: str = "") -> str:
    return f"\\newcommand{{\\rhbyF{name}}}{{{value}}}" + (f"  % {comment}" if comment else "")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen", default=str(ROOT / "generated"))
    a = ap.parse_args()
    gen = Path(a.gen)
    S = pd.read_csv(RES / "scores.csv")
    rd = json.loads((RES / "reading.json").read_text())
    M = [HEAD, f"% The trees' factor test beyond HAR + RM + FOMC ({LABEL}); results/beyond_trees_2026-10-27/factor."]
    for est, (me, _) in MODELS.items():
        for sp, ms in SPANS.items():
            for arm, (ma, _) in ARMS.items():
                x = S[(S["est"] == est) & (S["span"] == sp) & (S["arm"] == arm)].iloc[0]
                pre = f"{me}{ma}{ms}"
                M.append(mac(f"{pre}Qlike", fmt(x.qlike, 4), f"QLIKE {est} {arm} {sp}"))
                if arm != "base":
                    M.append(mac(f"{pre}Pct", fmt(x.pct_vs_base, 2), "QLIKE change % vs BASE"))
                    M.append(mac(f"{pre}Dm", fmt(x.dm_vs_base, 2), "DM vs BASE (HLN, daily means, lag 8)"))
                    M.append(mac(f"{pre}P", fmt_p(x.p_vs_base), "p vs BASE"))
                    M.append(mac(f"{pre}R", fmt(x.R, 2), "recovery R"))
                if arm != "full":
                    M.append(mac(f"{pre}DmFull", fmt(x.dm_vs_full, 2), "DM vs FULL"))
                    M.append(mac(f"{pre}PFull", fmt_p(x.p_vs_full), "p vs FULL"))
        r = rd["models"][est]
        M.append(mac(f"{me}Reading", READ[r["reading"]], "section 1 reading, ORDINARY days"))
        M.append(mac(f"{me}RPcaTenOrd", fmt(r["R_pca10"], 2), "R of BASE + 10 PCs, ORDINARY"))
        M.append(mac(f"{me}BestShortOrdR", fmt(r["R_best_short"], 2), f"best k <= 3 arm ({r['best_short']}), R"))
    M.append(mac("Agreement", rd["agreement"], "the two models' readings"))
    M.append(mac("Label", LABEL))
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "rehaul_beyond_factor_numbers.tex").write_text("\n".join(M) + "\n", encoding="utf-8")

    def cell(est: str, arm: str, sp: str) -> list[str]:
        x = S[(S["est"] == est) & (S["span"] == sp) & (S["arm"] == arm)].iloc[0]
        if arm == "base":
            return ["0.0", "0.00", f"{fmt(x.dm_vs_full, 1)}"]
        dmf = "--" if arm == "full" else fmt(x.dm_vs_full, 1)
        return [f"{fmt(x.pct_vs_base, 1)} ({fmt(x.dm_vs_base, 1)})", fmt(x.R, 2), dmf]

    L = [
        HEAD,
        f"% tab:rh_beyond_factor (results/beyond_trees_2026-10-27/RULE.txt; {LABEL}).",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{threeparttable}",
        r"\caption{Beyond HAR, realized moments and the FOMC calendar: the trees with a few components of the"
        r" remaining predictors}",
        r"\label{tab:rh_beyond_factor}",
        r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrrrrrr@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{LightGBM} & \multicolumn{3}{c}{XGBoost} \\",
        r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
        r" & \% (DM) & $R$ & DM vs full & \% (DM) & $R$ & DM vs full \\",
        r"\midrule",
    ]
    # 2026-10-28 (author: make the meaning of positive and negative changes abundantly clear): the sign of both signed
    # columns in each panel heading (short enough not to widen the table) and a sign key opening the notes; the scorer's
    # pct_vs_base, dm_vs_base and dm_vs_full are all row minus reference (experiments/beyond_factor_score.py)
    sign = r" (\%: $-$, the addition adds accuracy; DM vs full: $+$, the full set is better)"
    for sp, title in (("ordinary", "A. Ordinary days"), ("all", "B. Every bar")):
        L.append(rf"\multicolumn{{7}}{{@{{}}l}}{{\textit{{{title}{sign}}}}} \\")
        for arm, (_, lab) in ARMS.items():
            L.append(" & ".join([lab, *cell("lgbm", arm, sp), *cell("xgb", arm, sp)]) + r" \\")
        if sp == "ordinary":
            L.append(r"\addlinespace[4pt]")
    rl, rx = (READ[rd["models"][e]["reading"]] for e in ("lgbm", "xgb"))
    L += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\begin{tablenotes}[flushleft]",
        r"\footnotesize",
        r"\item \textit{Sign:} \%: $100\,(L_{\text{row}}/L_{\text{base}} - 1)$, the percentage change in mean QLIKE of"
        r" the row's forecast against the base, with the Diebold--Mariano statistic (HLN, daily average QLIKE, lag 8) in"
        r" parentheses (same sign): negative, the loss falls when the components (in the last row, the six groups) are"
        r" added, i.e.\ they add accuracy; positive, they hurt.  $R = (L_{\text{base}} - L_{\text{row}}) /"
        r" (L_{\text{base}} - L_{\text{full}})$, the share of the full set's gain over the base that the row recovers:"
        r" 1, all of it; 0, none; below 0, worse than the base.  DM vs full: the row against the full set; positive,"
        r" the full set is more accurate.",
        # 2026-10-28 (author): the note's opening "Requested by the author after the results beyond HAR + RM + FOMC
        # (Table tab:rh_ablation_beyond); not part of the pre-specified design." removed.
        r"\item \textit{Notes:} Base: the HAR benchmark set plus"
        r" the futures' realized moments and the FOMC calendar (132 columns).  Each row adds to it the first $k$"
        r" principal components, or partial-least-squares components against the target, of the remaining predictors'"
        r" value averages (the equal- and value-weighted market, liquidity, implied volatility, sentiment and volatility"
        r" demand: 216 columns), standardized within the rolling window; the loadings are re-estimated once a trading"
        r" day from the window ending at the previous bar.  Frozen hyperparameters, refit at every bar, FOMC-patched"
        rf" design.  Ordinary days exclude the 81 scheduled FOMC statement days.  Reading on ordinary days: LightGBM, {rl}; XGBoost, {rx}.",
        r"\end{tablenotes}",
        r"\end{threeparttable}",
        r"\end{table}",
    ]
    (gen / "rehaul_beyond_factor_table.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {gen / 'rehaul_beyond_factor_table.tex'} and the numbers ({len(M) - 2} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
