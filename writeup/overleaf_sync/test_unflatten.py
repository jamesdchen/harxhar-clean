class Hunks(unittest.TestCase):
    """SPEC 5.1: line diff, one hunk for each non-equal block, trimmed to the changed characters."""

    def test_trimming_keeps_neighbouring_numbers_out(self):
        hunks = unflatten.compute_hunks("a\nover 1{,}082 trading days\nb\n", "a\nover 1{,}082 market days\nb\n")
        self.assertEqual(len(hunks), 1)
        h = hunks[0]
        base = "a\nover 1{,}082 trading days\nb\n"
        self.assertEqual((base[h.a:h.b], h.new), ("trading", "market"))
        self.assertEqual(h.edited_line, 2)

    def test_insertion_and_deletion(self):
        base = "x\ny\nz\n"
        (ins,) = unflatten.compute_hunks(base, "x\nnew\ny\nz\n")
        self.assertEqual((ins.a, ins.b, ins.new), (2, 2, "new\n"))
        (dele,) = unflatten.compute_hunks(base, "x\nz\n")
        self.assertEqual((base[dele.a:dele.b], dele.new), ("y\n", ""))

    def test_strip_comment_honours_escaped_percent(self):
        self.assertEqual(unflatten.strip_comment("5\\% of days % note\n"), "5\\% of days ")
        self.assertEqual(unflatten.strip_comment("a \\\\% b\n"), "a \\\\")

    def test_prose_numbers_ignore_comments_and_labels(self):
        nums = unflatten.prose_numbers("see Table~\\ref{tab:t1} and \\citet{Corsi2009}, 30 seeds % 7 lags\n")
        self.assertEqual(list(nums.elements()), ["30"])


