class MapBuilder:
    """Assembles flat_text and the segments of SPEC section 4 from explicit pieces of the fixture sources."""

    def __init__(self, float_macro_kind: str = "macro"):
        self.float_macro_kind = float_macro_kind  # SPEC 4 allows "macro" or "gen" for a number inside a float
        self.flat: list[str] = []
        self.pos = 0
        self.segments: list[dict] = []
        self.cursor = {rel: 0 for rel in FILES}

    def _take(self, rel: str, text: str) -> tuple[int, int]:
        src = FILES[rel][0]
        s = self.cursor[rel]
        assert src[s:s + len(text)] == text, f"{rel}@{s}: expected {text!r}, found {src[s:s + len(text)]!r}"
        self.cursor[rel] = s + len(text)
        return s, s + len(text)

    def _emit(self, kind: str, flat: str, rel=None, src=None, macro=None, generator=None):
        a = self.pos
        self.flat.append(flat)
        self.pos += len(flat)
        self.segments.append({"flat": [a, self.pos], "kind": kind, "file": rel, "src": src, "macro": macro,
                              "generator": generator})

    def synthetic(self, text: str):
        self._emit("synthetic", text)

    def src(self, rel: str, text: str):
        self._emit("src", text, rel, list(self._take(rel, text)))

    def drop(self, rel: str, text: str):
        self._emit("drop", "", rel, list(self._take(rel, text)))

    def macro(self, rel: str, name: str, call: str, generator="writeup/make_nums.py"):
        self._emit("macro", MACROS[name], rel, list(self._take(rel, call)), name, generator)

    def float_macro(self, rel: str, name: str, call: str, generator: str):
        """A number macro inside a generated float, as a macro segment or as a gen segment naming the macro."""
        if self.float_macro_kind == "macro":
            self.macro(rel, name, call)
        else:
            self._emit("gen", MACROS[name], rel, list(self._take(rel, call)), name, generator)

    def gen(self, rel: str, text: str, generator: str):
        self._emit("gen", text, rel, list(self._take(rel, text)), None, generator)

    def done(self, rel: str):
        assert self.cursor[rel] == len(FILES[rel][0]), f"{rel} not consumed: stopped at {self.cursor[rel]}"

    def build(self) -> dict:
        b = self
        P, I, R, T = "paper.tex", "rehaul/01_introduction.tex", "rehaul/06_results.tex", "generated/tab_oos.tex"
        b.synthetic("%% main.tex -- generated by flatten.py from commit abc1234 (test fixture). Edits are brought\n"
                    "%% back by unflatten.py; numbers and tables come from generators, editing them is flagged.\n")
        b.src(P, "% paper.tex -- tiny fixture paper (test_unflatten.py).\n\\documentclass{article}\n")
        b.drop(P, "\\input{generated/nums}\n")
        b._take("generated/nums.tex", NUMS)  # the number file is consumed by its drop
        b.src(P, "\\begin{document}\n")
        # \input{rehaul/01_introduction}
        b.drop(P, "\\input{rehaul/01_introduction}")
        b.synthetic(f"%% >>> begin {I} (hand-written)\n")
        b.src(I, "% 01_introduction.tex -- fixture section.\n"
                 "% Macros used here: \\nDays, \\nPairs, \\spanStart, \\nLag.\n"
                 "\\section{Introduction}\nWe evaluate the forecasts from ")
        b.macro(I, "spanStart", "\\spanStart{}")
        b.src(I, " over $T = ")
        b.macro(I, "nDays", "\\nDays")
        b.src(I, "$ trading days, and the full\nset is more accurate across all ")
        b.macro(I, "nPairs", "\\nPairs{}")
        b.src(I, " model classes.\nThe Newey--West lag is ")
        b.macro(I, "nLag", "\\nLag\n")  # end-of-line swallowed: the next line is not blank
        b.src(I, "on every test.\n\nA second paragraph without numbers.\nA third line.\n")
        b.done(I)
        b.synthetic(f"%% <<< end {I}")
        b.src(P, "\n")
        # \input{rehaul/06_results}
        b.drop(P, "\\input{rehaul/06_results}")
        b.synthetic(f"%% >>> begin {R} (hand-written)\n")
        b.src(R, "% 06_results.tex -- fixture section.\n\\section{Results}\n"
                 "Table~\\ref{tab:oos} reports the accuracy.\n% a comment the editors may fix: teh typo\n")
        b.drop(R, "\\input{generated/tab_oos}")
        b.synthetic(f"%% >>> begin {T} (generated by writeup/make_tab.py)\n")
        b.gen(T, "% AUTO-GENERATED by writeup/make_tab.py -- do not edit.\n\\begin{table}\n\\begin{tabular}{lr}\n"
                 "OLS & 0.1291 \\\\\nTrees & 0.1302 \\\\\n\\end{tabular}\n\\caption{Accuracy on ",
              "writeup/make_tab.py")
        b.float_macro(T, "nDays", "\\nDays{}", "writeup/make_tab.py")
        b.gen(T, " days.}\n\\end{table}\n", "writeup/make_tab.py")
        b.done(T)
        b.synthetic(f"%% <<< end {T}")
        b.src(R, "\nThe pooled model wins.\nIts lag is ")
        b.macro(R, "nLag", "\\nLag{}")
        b.src(R, " days.\n")
        b.done(R)
        b.synthetic(f"%% <<< end {R}")
        b.src(P, "\n\\end{document}\n")
        b.done(P)

        flat = "".join(b.flat)
        sources = {rel: {"sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(), "text": text, "kind": kind}
                   for rel, (text, kind) in FILES.items()}
        macros = {name: {"value": value, "expanded": value, "file": "generated/nums.tex",
                         "generator": "writeup/make_nums.py"} for name, value in MACROS.items()}
        return {
            "version": 1,
            "created": "2026-10-20T00:00:00Z",
            "entry": "paper.tex",
            "source_commit": "abc1234",
            "source_dirty": False,
            "flat_file": "main.tex",
            "flat_sha256": hashlib.sha256(flat.encode("utf-8")).hexdigest(),
            "flat_text": flat,
            "sources": sources,
            "macros": macros,
            "segments": b.segments,
        }


def expand_live(text: str) -> str:
    """The fixture's flatten of one source file, enough to check a re-flatten: comments kept, macros expanded."""
    out = []
    for line in unflatten.split_lines(text):
        live = unflatten.strip_comment(line)
        comment = line[len(live):]
        for name, value in MACROS.items():
            live = re.sub(r"\\" + name + r"(?![A-Za-z])(\{\}|[ \t]*\n(?![ \t]*\n)|[ \t]*)",
                          lambda m, v=value: v, live)
        out.append(live + comment)
    return "".join(out)


