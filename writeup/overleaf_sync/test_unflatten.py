        code, report = self.run_unflatten()
        self.assertEqual(code, 0, report)
        intro = self.text("rehaul/01_introduction.tex")
        self.assertIn(f"{PARK}\n% The Newey--West lag is \\nLag\n% on every test.\n"
                      "The HAC lag is \\nLag\non each test.\n", intro)

