"""The factor-augmented HAR (results/channels_2026-10-26/RULE.txt section 4: shared factor or dense?) for the paper.

READS    results/channels_2026-10-26/factor/ (experiments/factor_har_2026_10_26.py score): scores.csv, reading.json,
         gates.json, walk.json.  Every number below is read from those files; none is recomputed from forecasts here
         (R_k is re-derived from the stored QLIKEs only as a consistency check).
DESIGN   Table 1's (D13): OLS on the HAR set plus the first k principal components (k = 1, 2, 3, 5, 10, 20) or partial
         least squares components (k = 1, 2, 3) of the 258 value averages of the 43 non-FOMC exogenous series,
         standardized in each estimation window, loadings once a trading day; re-estimated at every bar on the
         39,000-row window.  QLIKE on ORDINARY days (the 2,498 sessions that are not one of the 81 scheduled FOMC
         statement days; primary), every bar and EVENT days; DM (HLN, daily mean losses, lag 8) against Table 1's
         OLS-HAR and against the full set (the lower-QLIKE of Table 1's full-set ridge and elastic net on the span);
         R_k = (L_HAR - L_k) / (L_HAR - L_full).
WRITES   writeup/generated/rehaul_factor_numbers.tex   \\rhfa... macros (letters only)
         writeup/generated/rehaul_factor_table.tex     Table tab:rh_factor
         writeup/figures/rehaul_factor_recovery.pdf    R_k against k on ORDINARY days, PCA and PLS
         writeup/generated/rehaul_factor_fig.tex       its float, fig:rh_factor
Macros   \\rhfa<M><S><Q>: M = PcaOne PcaTwo PcaThree PcaFive PcaTen PcaTwenty PlsOne PlsTwo PlsThree Full (the span's
         L_full model), S = Ord (ORDINARY days) All (every bar) Ev (EVENT days), Q = Pct (QLIKE change against the
         OLS-HAR, %), Dm / P (DM against the OLS-HAR, QLIKE), DmFull / PFull (DM against the full set, QLIKE), R (R_k),
         MsePct (MSE change, %); \\rhfaFull<S>Model (ridge / elastic net); the reading (\\rhfaReading, ...), the
         variance shares (\\rhfaShare...), the first component's loadings by group (\\rhfaLoad<G>, \\rhfaLoadSq<G>,
         \\rhfaPlsLoad<G>, \\rhfaPlsLoadSq<G>), counts and gate figures.

Run:  python writeup/make_rehaul_factor.py     (from the repository root)
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RES = ROOT / "results" / "channels_2026-10-26" / "factor"
GEN = HERE / "generated"
FIG = HERE / "figures"
OUT_NUM = GEN / "rehaul_factor_numbers.tex"
OUT_TAB = GEN / "rehaul_factor_table.tex"
OUT_FIG = FIG / "rehaul_factor_recovery.pdf"
OUT_FLOAT = GEN / "rehaul_factor_fig.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_factor.py -- do not edit; re-run the script."
K_PCA = (1, 2, 3, 5, 10, 20)
K_PLS = (1, 2, 3)
KW = {1: "One", 2: "Two", 3: "Three", 5: "Five", 10: "Ten", 20: "Twenty"}
MODELS = [f"pca{k}" for k in K_PCA] + [f"pls{k}" for k in K_PLS]
MTAG = {f"pca{k}": f"Pca{KW[k]}" for k in K_PCA} | {f"pls{k}": f"Pls{KW[k]}" for k in K_PLS}
STAG = {"ordinary": "Ord", "all": "All", "event": "Ev"}
FULL_NAME = {"ridge": "ridge", "enet": "elastic net"}
GROUPS = {
    "rm": ("Rm", "Realized moments"),
    "liq": ("Liq", "Liquidity"),
    "ew": ("Ew", "Equal-weighted market"),
    "vw": ("Vw", "Value-weighted market"),
    "sent": ("Sent", "Sentiment"),
    "iv": ("Iv", "Implied volatility"),
    "vd": ("Vd", "Volatility demand"),
}
READ_WORD = {
    "SHARED FACTOR": "shared factor",
    "DENSE BEYOND A FEW FACTORS": "dense beyond a few factors",
    "INTERMEDIATE": "intermediate",
}
N_SCORED, N_EVENT, N_ORD = 33_527, 81, 2_498


def num(x: float, nd: int = 2) -> str:
    s = f"{x:.{nd}f}"
    if s.startswith("-") and float(s) == 0.0:
        s = s[1:]
    return "$-$" + s[1:] if s.startswith("-") else s


def pval(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def sci(x: float) -> str:
    m, e = f"{x:.0e}".split("e")
    return f"${m} \\times 10^{{{int(e)}}}$"


def thousands(x: int) -> str:
    return f"{x:,}".replace(",", "{,}")


def model_tex(m: str) -> str:
    return ("PCA" if m.startswith("pca") else "PLS") + f", $k = {int(m[3:])}$"


def main() -> None:
    gates = json.loads((RES / "gates.json").read_text())
    walk = json.loads((RES / "walk.json").read_text())
    rd = json.loads((RES / "reading.json").read_text())
    S = pd.read_csv(RES / "scores.csv")
    # ---------------------------------------------------------------- gates, asserted
    assert gates["pass"], gates["fail"]
    assert gates["G1"]["pass"] and gates["G1"]["max_rel_pred"] <= 1e-10 and gates["G1"]["rows"] == walk["bars"]
    assert gates["G2"]["pass"] and gates["G2"]["max_rel"] <= 1e-8 and len(gates["G2"]["days"]) >= 5
    g3 = gates["G3"]
    assert g3["pass"] and g3["n_bars"] == N_SCORED and g3["n_event_days"] == N_EVENT and g3["ordinary_days"] == N_ORD
    assert walk["block_columns"] == 258 and walk["block_series"] == 43 and walk["rank_11_plus_k_every_bar"]
    S = S[S["entry"] == "table1"]
    for sp in STAG:
        s = S[S["span"] == sp].set_index("model")
        assert int(s["n_bars"].iloc[0]) == {"all": N_SCORED, "event": 13 * N_EVENT, "ordinary": 13 * N_ORD}[sp]
        full = s["full_ref"].iloc[0]
        lh, lf = s.loc["ols_har", "qlike"], s.loc[f"{full}_full", "qlike"]
        assert lf == min(s.loc["ridge_full", "qlike"], s.loc["enet_full", "qlike"])
        for m in MODELS:
            assert np.isclose(s.loc[m, "R"], (lh - s.loc[m, "qlike"]) / (lh - lf), rtol=1e-9, atol=1e-12), (sp, m)
        assert abs(s.loc["k0", "qlike"] / lh - 1.0) < 1e-9, "k = 0 is Table 1's OLS-HAR"
    r = rd["reading"]["table1"]
    d = rd["descriptive"]["table1"]
    o = S[S["span"] == "ordinary"].set_index("model")
    small = [m for m in MODELS if int(m[3:]) <= 3]
    shared = [
        m
        for m in small
        if o.loc[m, "R"] >= 0.75 and not (o.loc[m, "p_full_qlike"] < 0.05 and o.loc[m, "diff_full_qlike"] > 0)
    ]
    dense = bool(
        o.loc["pca10", "R"] < 0.5 and o.loc["pca10", "p_full_qlike"] < 0.05 and o.loc["pca10", "diff_full_qlike"] > 0
    )
    word = "SHARED FACTOR" if shared else ("DENSE BEYOND A FEW FACTORS" if dense else "INTERMEDIATE")
    assert word == r["reading"] and shared == r["shared_factor_models"], (word, r["reading"])

    # ---------------------------------------------------------------- macros
    M: list[tuple[str, str, str]] = []

    def add(name: str, value: str, note: str) -> None:
        assert name.isalpha() and name.startswith("rhfa"), name
        M.append((name, value, note))

    for sp, st in STAG.items():
        s = S[S["span"] == sp].set_index("model")
        full = s["full_ref"].iloc[0]
        for m in MODELS:
            x = s.loc[m]
            t = f"rhfa{MTAG[m]}{st}"
            add(f"{t}Pct", num(x["qlike_pct_vs_har"]), f"{m} {sp}: QLIKE change vs OLS-HAR, %")
            add(f"{t}MsePct", num(x["mse_pct_vs_har"]), f"{m} {sp}: MSE change vs OLS-HAR, %")
            add(f"{t}Dm", num(x["dm_har_qlike"]), f"{m} {sp}: DM vs OLS-HAR (QLIKE)")
            add(f"{t}P", pval(x["p_har_qlike"]), f"{m} {sp}: p")
            add(f"{t}DmFull", num(x["dm_full_qlike"]), f"{m} {sp}: DM vs the full set ({full})")
            add(f"{t}PFull", pval(x["p_full_qlike"]), f"{m} {sp}: p")
            add(f"{t}R", num(x["R"]), f"{m} {sp}: R_k")
        f = s.loc[f"{full}_full"]
        add(f"rhfaFull{st}Model", FULL_NAME[full], f"{sp}: L_full model (lower QLIKE of ridge, elastic net)")
        add(f"rhfaFull{st}Pct", num(f["qlike_pct_vs_har"]), f"{sp}: full set QLIKE change vs OLS-HAR, %")
        add(f"rhfaFull{st}MsePct", num(f["mse_pct_vs_har"]), f"{sp}: full set MSE change vs OLS-HAR, %")
        add(f"rhfaFull{st}Dm", num(f["dm_har_qlike"]), f"{sp}: full set DM vs OLS-HAR")
        add(f"rhfaFull{st}P", pval(f["p_har_qlike"]), f"{sp}: p")
        add(f"rhfaN{st}Days", thousands(int(s["n_days"].iloc[0])), f"{sp}: days")
        add(f"rhfaN{st}Bars", thousands(int(s["n_bars"].iloc[0])), f"{sp}: bars")
    add("rhfaReading", READ_WORD[r["reading"]], "the RULE's reading, ORDINARY days")
    best = r["best_small_k"]
    add("rhfaBestSmall", model_tex(best), "the k <= 3 model with the highest R_k on ORDINARY days")
    add("rhfaBestSmallR", num(o.loc[best, "R"]), "its R_k")
    add("rhfaBestSmallPFull", pval(o.loc[best, "p_full_qlike"]), "its DM p against the full set")
    add("rhfaNSharedModels", str(len(shared)), "k <= 3 models meeting the SHARED FACTOR condition")
    add("rhfaShareThreshold", "0.75", "SHARED FACTOR: R_k threshold")
    add("rhfaDenseThreshold", "0.5", "DENSE: R_10 threshold")
    add("rhfaNBlock", "258", "block columns (value averages, 43 series x 6 horizons)")
    add("rhfaNSeries", "43", "non-FOMC exogenous series")
    add("rhfaNActiveMin", str(d["n_active_min"]), "fewest active block columns on a scored day")
    add("rhfaNActiveMax", str(d["n_active_max"]), "most active block columns on a scored day")
    for j, w in ((1, "One"), (2, "Two"), (3, "Three")):
        add(f"rhfaSharePc{w}", num(100 * d["share_pc"][str(j)], 1), f"mean share of block variance, component {j}, %")
    for k in K_PCA:
        add(f"rhfaShareCum{KW[k]}", num(100 * d["share_cum"][str(k)], 1), f"mean share in components 1-{k}, %")
    add("rhfaShareCumThreeMin", num(100 * d["share_cum3_min"], 1), "components 1-3: lowest day, %")
    add("rhfaShareCumThreeMax", num(100 * d["share_cum3_max"], 1), "components 1-3: highest day, %")
    for g, (gt, label) in GROUPS.items():
        add(f"rhfaLoad{gt}", num(d["pc1_abs"][g]), f"PC1: sum of |loadings|, {label}")
        add(f"rhfaLoadSq{gt}", num(100 * d["pc1_sq"][g], 1), f"PC1: share of squared loadings, {label}, %")
        add(f"rhfaPlsLoad{gt}", num(d["pls1_abs"][g]), f"PLS1: sum of |weights|, {label}")
        add(f"rhfaPlsLoadSq{gt}", num(100 * d["pls1_sq"][g], 1), f"PLS1: share of squared weights, {label}, %")
        add(f"rhfaNCols{gt}", num(d["n_cols"][g], 1), f"active block columns of {label} (mean over days)")
    top = max(GROUPS, key=lambda g: d["pc1_sq"][g])
    add("rhfaLoadTopGroup", GROUPS[top][1].lower(), "group with the largest PC1 share of squared loadings")
    add("rhfaGOneMaxRel", sci(gates["G1"]["max_rel_pred"]), "G1: k = 0 vs Table 1's OLS-HAR, max relative difference")
    add("rhfaGTwoMaxRel", sci(gates["G2"]["max_rel"]), "G2: Gram route vs direct lstsq, max relative difference")
    add("rhfaGTwoNDays", str(len(gates["G2"]["days"])), "G2 days")
    if "sd" in rd["reading"]:
        rs = rd["reading"]["sd"]
        add("rhfaSdReading", READ_WORD[rs["reading"]], "sensitivity (s.d.-only entry rule): reading")
        for m in small:
            add(f"rhfaSd{MTAG[m]}OrdR", num(rs["R_ordinary"][m]), f"sensitivity: {m} R_k, ORDINARY days")
        add("rhfaSdPcaTenOrdR", num(rs["R_ordinary"]["pca10"]), "sensitivity: pca10 R_k, ORDINARY days")
    names = [n for n, _, _ in M]
    assert len(set(names)) == len(names), "a macro name twice"
    GEN.mkdir(parents=True, exist_ok=True)
    lines = [
        HEAD,
        "% \\rhfa... macros: factor-augmented HAR (diffusion index) on Table 1's design (results/channels_2026-10-26/",
        "% RULE.txt section 4; results/channels_2026-10-26/factor).  Spans: Ord = ORDINARY days (primary), All = every",
        "% bar, Ev = the 81 FOMC statement days.  Models: Pca<k>, Pls<k>, Full (the span's L_full model).",
    ]
    for name, value, note in M:
        lines.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}  % {note}")
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_NUM.name}: {len(M)} macros")
    table(S)
    figure(S)


def table(S: pd.DataFrame) -> None:
    def cells(s: pd.DataFrame, m: str, full: str) -> list[str]:
        x = s.loc[m]
        a = f"{num(x['qlike_pct_vs_har'])} ({num(x['dm_har_qlike'])})"
        if m.endswith("_full"):
            return [a, "1.00" if m == f"{full}_full" else num(x["R"]), "--"]
        return [a, num(x["R"]), num(x["dm_full_qlike"])]

    so = S[S["span"] == "ordinary"].set_index("model")
    sa = S[S["span"] == "all"].set_index("model")
    fo, fa = so["full_ref"].iloc[0], sa["full_ref"].iloc[0]
    body = []
    # 2026-10-28 (author: make the meaning of positive and negative changes abundantly clear): the sign of both signed
    # columns in each block heading (short enough not to widen the table) and a sign key opening the notes; the
    # scorer's qlike_pct_vs_har, dm_har_qlike and dm_full_qlike are all row minus reference (factor_har_2026_10_26.py)
    sign = " (\\%: $-$, they add accuracy; DM vs full: $+$, the full set is better)"
    for meth, ks, label in (("pca", K_PCA, "Principal components"), ("pls", K_PLS, "Partial least squares")):
        body.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\textit{{{label}{sign}}}}} \\\\")
        for k in ks:
            m = f"{meth}{k}"
            body.append(" & ".join([f"$k = {k}$", *cells(so, m, fo), *cells(sa, m, fa)]) + " \\\\")
        body.append("\\addlinespace[3pt]")
    fr = [f"Full set ({FULL_NAME[fo]}" + (")" if fo == fa else f" / {FULL_NAME[fa]})")]
    body.append(" & ".join([*fr, *cells(so, f"{fo}_full", fo), *cells(sa, f"{fa}_full", fa)]) + " \\\\")
    tex = [
        HEAD,
        "% tab:rh_factor: factor-augmented HAR, ORDINARY days and every bar (results/channels_2026-10-26/factor).",
        "\\ifdefined\\rhfaReading\\else\\input{generated/rehaul_factor_numbers}\\fi",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{threeparttable}",
        "\\caption{Factor-augmented HAR: how much of the full set's gain a few components recover}",
        "\\label{tab:rh_factor}",
        "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrrrrr@{}}",
        "\\toprule",
        " & \\multicolumn{3}{c}{Ordinary days (\\rhfaNOrdDays{} days)} & \\multicolumn{3}{c}{Every bar (\\rhfaNAllDays{} days)} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(l){5-7}",
        " & QLIKE \\% (DM) & $R_k$ & DM vs full & QLIKE \\% (DM) & $R_k$ & DM vs full \\\\",
        "\\midrule",
        *body,
        "\\bottomrule",
        "\\end{tabular*}",
        "\\begin{tablenotes}[flushleft]",
        "\\footnotesize",
        "\\item \\textit{Sign:} QLIKE \\%: $100\\,(L_k/L_{\\mathrm{HAR}} - 1)$, the percentage change in mean QLIKE of the"
        " row's forecast against Table~\\ref{tab:rh_oos}'s OLS on the HAR set, with the Diebold--Mariano statistic (HLN,"
        " daily mean losses, lag 8) in parentheses (same sign): negative, the loss falls when the components are added"
        " to the HAR set, i.e.\\ they add accuracy; positive, they hurt; in the full-set row, negative: the full set is"
        " more accurate. $R_k = (L_{\\mathrm{HAR}} - L_k)/(L_{\\mathrm{HAR}} - L_{\\mathrm{full}})$, $L_{\\mathrm{full}}$"
        " the lower QLIKE of Table~\\ref{tab:rh_oos}'s full-set ridge and elastic net on the same days: 1, all of the"
        " full set's gain over the HAR set; 0, none; below 0, worse than the HAR set. DM vs full: the row against that"
        " full set; positive, the full set is more accurate.",
        "\\item OLS on the HAR benchmark set plus the first $k$ components of the \\rhfaNBlock{} value averages of the"
        " \\rhfaNSeries{} exogenous series outside the FOMC group, standardized in each estimation window; principal"
        " components of the window's correlation matrix or partial least squares components against the target, both"
        " recomputed once a trading day from the window ending at the previous bar and held for the day; the regression"
        " re-estimated at every bar on Table~\\ref{tab:rh_oos}'s 39{,}000-row window."
        " Ordinary days: the scored sessions that are not one of the \\rhfaNEvDays{} scheduled FOMC statement days."
        " The full sets are penalized and include availability averages; the component regressions are OLS on value"
        " averages only, so the comparison is of forecast accuracy, not a nesting.",
        "\\end{tablenotes}",
        "\\end{threeparttable}",
        "\\end{table}",
    ]
    OUT_TAB.write_text("\n".join(tex) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_TAB.name}")


def figure(S: pd.DataFrame) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    INK, INK2, GRIDC = "#0b0b0b", "#52514e", "#e6e5e0"
    COL = {"pca": "#2a78d6", "pls": "#eb6834"}
    plt.rcParams.update(
        {
            "font.size": 8,
            "axes.edgecolor": INK2,
            "xtick.color": INK2,
            "ytick.color": INK2,
            "font.family": "DejaVu Sans",
            "pdf.fonttype": 42,
        }
    )
    o = S[S["span"] == "ordinary"].set_index("model")
    fo = o["full_ref"].iloc[0]
    fig, ax = plt.subplots(figsize=(4.8, 3.0), constrained_layout=True)
    xs = {k: i for i, k in enumerate(K_PCA)}
    for meth, ks, label, mk in (
        ("pca", K_PCA, "principal components", "o"),
        ("pls", K_PLS, "partial least squares", "s"),
    ):
        ax.plot(
            [xs[k] for k in ks],
            [o.loc[f"{meth}{k}", "R"] for k in ks],
            color=COL[meth],
            lw=1.6,
            marker=mk,
            ms=4,
            label=label,
            zorder=3,
        )
    xr = len(K_PCA) - 1 + 0.3
    ax.axhline(1.0, color=INK, lw=1.0, zorder=2)
    ax.text(xr, 1.02, f"full set ({FULL_NAME[fo]})", va="bottom", ha="right", fontsize=6.5, color=INK)
    ax.axhline(0.0, color=INK2, lw=0.8, zorder=2)
    ax.text(xr, 0.02, "OLS on the HAR set", va="bottom", ha="right", fontsize=6.5, color=INK2)
    ax.axhline(0.75, color=INK2, lw=0.6, ls=":", zorder=1)
    ax.text(xr, 0.77, f"$R_k$ = {0.75}", va="bottom", ha="right", fontsize=6, color=INK2)
    ax.set_xticks(range(len(K_PCA)), [str(k) for k in K_PCA])
    ax.set_xlim(-0.3, xr)
    lo = min(0.0, float(o.loc[MODELS, "R"].min())) - 0.1
    hi = max(1.0, float(o.loc[MODELS, "R"].max())) + 0.15
    ax.set_ylim(lo, hi)
    ax.set_xlabel("components $k$", fontsize=8, color=INK2)
    ax.set_ylabel("$R_k$, ordinary days", fontsize=8)
    ax.grid(axis="y", color=GRIDC, lw=0.6)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(loc="lower right", frameon=False, fontsize=7)
    OUT_FIG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT_FIG)
    plt.close(fig)
    caption = (
        "Share of the full set's ordinary-day gain recovered by $k$ components: $R_k = (L_{\\mathrm{HAR}} - L_k)/"
        "(L_{\\mathrm{HAR}} - L_{\\mathrm{full}})$ on the \\rhfaNOrdDays{} ordinary days (QLIKE), for OLS on the HAR set"
        " plus the first $k$ principal components (blue) or partial least squares components (orange) of the"
        " \\rhfaNBlock{} non-FOMC value averages. $R_k = 1$: the full set (Table~\\ref{tab:rh_oos}'s "
        "\\rhfaFullOrdModel{}); $R_k = 0$: the OLS on the HAR set. Dotted: $R_k = \\rhfaShareThreshold$. Reading:"
        " \\rhfaReading{} (Table~\\ref{tab:rh_factor})."
    )
    OUT_FLOAT.write_text(
        "\n".join(
            [
                HEAD,
                "\\ifdefined\\rhfaReading\\else\\input{generated/rehaul_factor_numbers}\\fi",
                "\\begin{figure}[tbp]",
                "\\centering",
                "\\includegraphics[width=0.75\\linewidth]{figures/rehaul_factor_recovery.pdf}",
                f"\\caption{{{caption}}}",
                "\\label{fig:rh_factor}",
                "\\end{figure}",
            ]
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT_FIG.name}, {OUT_FLOAT.name}")


if __name__ == "__main__":
    main()
