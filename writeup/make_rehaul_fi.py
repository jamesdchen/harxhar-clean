def f(x: float, nd: int = 2) -> str:
    s = f"{x:.{nd}f}"
    return s.replace("-", r"\ensuremath{-}") if s.startswith("-") else s


def pct(x: float, nd: int = 1) -> str:
    return f(100 * x, nd)


def date_tex(d) -> str:
    d = pd.Timestamp(d)
