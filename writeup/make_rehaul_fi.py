def fig_inter(T: dict) -> None:
    S = T["summary"]
    tot = None
    for m in MODELS:
        M = T[m + "_mat"].copy()
        v = M.to_numpy()
        np.fill_diagonal(v, 0)
        s = pd.Series(v.sum(axis=1) / v.sum(), index=M.index)
        tot = s if tot is None else tot + s
    assert tot is not None
    top = tot.sort_values(ascending=False).index[:10].tolist()
    vals = []
    for m in MODELS:
        vals.append(1e3 * T[m + "_mat"].loc[top, top].to_numpy())
    allv = np.concatenate([v[v > 0] for v in vals])
    norm = LogNorm(vmin=max(allv.min(), allv.max() * 1e-3), vmax=allv.max())
    fig, axes = plt.subplots(1, 3, figsize=(FIG_W, 2.45), layout="constrained")
    n = len(top)
    for ax, m, V in zip(axes, MODELS, vals):
        Vm = np.ma.masked_where(np.triu(np.ones_like(V, bool), 1) | (V <= 0), V)
        im = ax.imshow(
            Vm, cmap=_cmap(), norm=norm, interpolation="none", extent=(0, n, n, 0)
        )
        ax.set_xlim(0, n)
        ax.set_ylim(n, 0)
        ax.set_aspect("equal")
        ax.set_title(MLABEL[m])
        ax.set_xticks(np.arange(n) + 0.5)
        ax.set_xticklabels([str(i + 1) for i in range(n)], fontsize=7)
        ax.set_yticks(np.arange(n) + 0.5)
        ax.set_yticklabels(
            [f"{short(u)} {i + 1}" for i, u in enumerate(top)]
            if m == "lgbm"
            else [str(i + 1) for i in range(n)],
            fontsize=6.5 if m == "lgbm" else 7,
        )
        ax.tick_params(length=0)
        for s in ("left", "bottom"):
            ax.spines[s].set_visible(False)
    cb = fig.colorbar(im, ax=axes, shrink=0.7, aspect=22, pad=0.01)
    cb.set_label(r"$\bar I_{AB}\times 10^{3}$")
    _save(fig, "rehaul_fi_inter_heatmap")
    cap = (
        r"The trees' series-level SHAP interactions: $\bar I_{AB}$, the mean over the "
        + S["n_oos_tex"]
        + r" scored sessions of $|\phi_{t,AB}|$, $\phi_{t,AB} = \sum_{j\in A}\sum_{l\in B}(\phi_{t,jl} + "
        r"\phi_{t,lj})$, $\times 10^{3}$, log colour scale shared by the panels; lower triangle, the diagonal is "
        r"the interaction among a unit's own columns, $\sum_{j \ne l \in A}\phi_{t,jl}$. Units: the 10 with the "
        r"largest share of their model's off-diagonal interaction mass, summed over the three models; numbered as "
        r"in the left panel. Local refits on the held-out rows of each of the "
        + str(S["n_refits"])
        + " refits."
    )
    float_fig(
        GEN / "rehaul_fi_fig_inter.tex",
        "rehaul_fi_inter_heatmap.pdf",
        cap,
        "fig:rh_fi_inter",
    )


