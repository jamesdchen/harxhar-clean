# ============================================================================ figures
def _save(fig, stem: str) -> None:
    w, h = fig.get_size_inches()
    assert abs(w - FIG_W) < 1e-9, (stem, w)
    fig.savefig(FIG / f"{stem}.pdf")
    if PREVIEW is not None:
        PREVIEW.mkdir(parents=True, exist_ok=True)
        fig.savefig(PREVIEW / f"{stem}.png", dpi=170)
    plt.close(fig)
    print(f"wrote {rel(FIG / (stem + '.pdf'))} ({w:.2f} x {h:.2f} in)")


def float_fig(path: Path, pdf: str, caption: str, label: str, pre: str = "") -> None:
    path.write_text(
        HEAD
        + (
            pre + "\n" if pre else ""
        )  # 2026-10-15 (table legibility): macros the caption uses
        + "\n".join(
            [
                r"\begin{figure}[tbp]",
                r"\centering",
                rf"\includegraphics[width=\linewidth]{{figures/{pdf}}}",
                rf"\caption{{{caption}}}",
                rf"\label{{{label}}}",
                r"\end{figure}",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {rel(path)}")


def _cmap():
    cm = plt.get_cmap(CMAP).copy()
    cm.set_bad((1.0, 1.0, 1.0, 0.0))  # masked = blank
    return cm


def _edges(dates: pd.Series) -> np.ndarray:
    d = mdates.date2num(pd.to_datetime(dates))
    mid = (d[1:] + d[:-1]) / 2
    return np.concatenate([[d[0] - (mid[0] - d[0])], mid, [d[-1] + (d[-1] - mid[-1])]])


