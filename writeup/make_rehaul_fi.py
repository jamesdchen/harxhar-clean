# ============================================================================ macros
class Macros:
    def __init__(self):
        self.rows: list[tuple[str, str, str]] = []

    def __setitem__(self, name: str, val):
        assert re.fullmatch(r"[A-Za-z]+", name), name
        v, c = val if isinstance(val, tuple) else (val, "")
        self.rows.append((name, str(v), c))

    def write(self, path: Path) -> None:
        lines = [
            HEAD,
            "% \\rhfi... macros for writeup/rehaul/08_feature_importance.tex (results/rehaul_fi/).\n",
        ]
        seen = set()
        for n, v, c in self.rows:
            assert n not in seen, n
            seen.add(n)
            lines.append(
                f"\\providecommand{{\\rhfi{n}}}{{}}\\renewcommand{{\\rhfi{n}}}{{{v}}}"
                + (f"  % {c}" if c else "")
                + "\n"
            )
        path.write_text("".join(lines), encoding="utf-8")
        print(f"wrote {rel(path)} ({len(self.rows)} macros)")


