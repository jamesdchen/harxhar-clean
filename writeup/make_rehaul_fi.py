def _math(base: str, sup: tuple[str, ...], sub: tuple[str, ...]) -> str:
    s = base + (f"^{{{','.join(sup)}}}" if sup else "")
    return s + (f"_{{{','.join(sub)}}}" if sub else "")


def _series_parts(s: str) -> tuple[str, tuple[str, ...], str]:
    if s in SERIES_TEX:
        return SERIES_TEX[s]
    stem, _, agg = s.rpartition("_")
    base, sup, sub = SERIES_TEX[stem]
    return base, (*sup, AGG_TEX[agg]), sub


def series_tex(s: str) -> str:
    """Math symbol (no $) of an exogenous series, e.g. 'sumpret2_ewstock' -> \\mathrm{RS}^{+,\\mathrm{EW}}."""
    base, sup, sub = _series_parts(s)
    return _math(base, sup, (sub,) if sub else ())


def column_tex(c: str) -> str:
    """Math name (no $) of a predictor of the closing-interval design, e.g. adj_vix_ma_25 -> VIX^{(25)}_t."""
    if c in CAL_TEX:
        return CAL_TEX[c] + "_t"
    if m := re.fullmatch(r"har_ma_(\d+)", c):
        return rf"\bar y^{{({m.group(1)})}}_t"
    if m := re.fullmatch(r"adj_(.+)_ma_(\d+)", c):
        base, sup, sub = _series_parts(m.group(1))
        return _math(base, (*sup, f"({m.group(2)})"), (sub, "t") if sub else ("t",))
    if m := re.fullmatch(r"(.+)_(avail|active)_ma_(\d+)", c):
        ind = r"\bar a" if m.group(2) == "avail" else r"\bar\chi"
        return f"{ind}^{{({m.group(3)})}}_t({series_tex(m.group(1))})"
    raise KeyError(c)


def grp(u: str, cap: bool = True) -> str:
    """Predictor-group name for LaTeX (text or math mode)."""
    if u in GROUP_WORDS:
        w = GROUP_WORDS[u]
        return w if cap or u != "calendar" else w.lower()
    return rf"\ensuremath{{{series_tex(u)}}}"


def col(c: str) -> str:
    """Predictor name for LaTeX (text or math mode)."""
    return rf"\ensuremath{{{column_tex(c)}}}"


def grp_mpl(u: str) -> str:
    """Predictor-group name for matplotlib's mathtext."""
    return GROUP_WORDS[u] if u in GROUP_WORDS else f"${series_tex(u)}$"


