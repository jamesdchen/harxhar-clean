# 2026-10-15 (table legibility): the four tables in finance-journal style (NOTATION_GUIDE_2026-10-15.md section 8):
# a short caption title; Panel A / B rows; at most seven right-aligned columns with fixed decimals per column; readable
# predictor-group and predictor names (grp / col); notes of about five sentences that use the \rhfi... macros for the
# sample and refer to the section's definitions. No measure here is a test statistic, so no table carries stars.
def table(
    path: Path,
    caption: str,
    label: str,
    spec: str,
    rows: list[str],
    notes: str,
    tabcolsep: str = "4pt",
) -> None:
    lines = [
        HEAD,
        # the notes use the \rhfi... macros: load them when the table is input on its own
        r"\ifdefined\rhfiNRefits\else\input{generated/rehaul_fi_numbers}\fi",
        r"\begin{table}[tbp]",
        r"\centering",
        r"\small",
        rf"\setlength{{\tabcolsep}}{{{tabcolsep}}}",
        r"\begin{threeparttable}",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{spec}}}",
        r"\toprule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\begin{tablenotes}[flushleft]",
        r"\footnotesize",
        rf"\item \textit{{Notes:}} {notes}",
        r"\end{tablenotes}",
        r"\end{threeparttable}",
        r"\end{table}",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {rel(path)}")


