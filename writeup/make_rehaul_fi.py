def ridge_sd(T: dict) -> pd.DataFrame:
    """Groups by the ridge's share of the absolute standardized coefficients |beta_kj| sd_kj."""
    rz = T["ridge"]
    return (
        rz.assign(sh=rz["sum_abs_sd"] / rz["sum_abs_sd"].sum())
        .sort_values("sh", ascending=False)
        .reset_index(drop=True)
    )


