def pretune_penalties() -> dict:
    s = (GEN / "close_main_numbers.tex").read_text(encoding="utf-8")
    out: dict[str, object] = {}
    for n in ("Ridge", "Lasso"):
        m = re.search(
            rf"\\newcommand{{\\cmPtPen{n}All}}{{\\ensuremath{{10\^{{(-?\d+)}}}}}}", s
        )
        assert m is not None, n
        out[n.lower()] = 10.0 ** int(m.group(1))
        m2 = re.search(rf"\\newcommand{{\\cmPtFired{n}All}}{{(\w+)}}", s)
        assert m2 is not None, n
        out[n.lower() + "_fired"] = m2.group(1)
    return out


