"""Write writeup/generated/external_maisch_numbers.tex: numbers reported by another paper that our text cites.

The paper's house rule is that every number in the prose comes from a generated macro. These are not results of
ours: they are the numbers Maisch, Zhang, Ulrich and Zimmer (SSRN 7269778, PDF dated 12 August 2026; references.bib
key MaischZhangUlrichZimmer2026) report, copied by hand from their PDF with the page and table of each, for the
comparison in the conclusion (09_conclusion.tex). Re-run after checking any value against their text:

    python writeup/make_external_numbers.py
"""

from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parent / "generated" / "external_maisch_numbers.tex"

# name, value, source in their PDF (page numbers are the printed page numbers of the main text)
NUMBERS: list[tuple[str, str, str]] = [
    ("extMaischYear", "2015", "the single sample year, section 4 (p. 14)"),
    ("extMaischTestMonths", "eight", "test months May to December 2015, rolling windows, section 3.2 (p. 12)"),
    ("extMaischSrGbrt", "0.55", "30-minute Sharpe ratio, decile long-short, GBRT-AV 3, Table 9 Panel A (p. 31)"),
    ("extMaischSrEns", "0.67", "30-minute Sharpe ratio, decile long-short, Adj. N-En 5, Table 9 Panel B (p. 31)"),
    ("extMaischSrGbrtAnn", "31.27", "the same, annualized by them, section 6.1 (p. 30)"),
    ("extMaischSrEnsAnn", "38.47", "the same, annualized by them, section 6.1 (p. 30)"),
    ("extMaischSrGbrtOi", "0.35", "GBRT-AV 3 with open-interest weights, section 6.1 (p. 30, their Table 14)"),
    ("extMaischSrEnsOi", "0.56", "Adj. N-En 5 with open-interest weights, section 6.1 (p. 30, their Table 14)"),
]


def main() -> None:
    lines = [
        "% AUTO-GENERATED by writeup/make_external_numbers.py -- do not edit; re-run the script.",
        "% Numbers reported by Maisch, Zhang, Ulrich and Zimmer (SSRN 7269778), not results of ours; each with its",
        "% source in their PDF. Their Sharpe ratios are gross, at mid-quotes, per 30-minute interval unless annualized.",
    ]
    for name, value, source in NUMBERS:
        lines.append(f"\\providecommand{{\\{name}}}{{{value}}}  % {source}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(NUMBERS)} macros")


if __name__ == "__main__":
    main()
