"""NYSE-holiday sessions: the measured linear 2 x 2 (integration plan D15, 2026-10-26): Table tab:rh_holiday, \\rhhol...

On full NYSE holidays the E-mini trades a shortened session; its regular-hours bars are rows of the 13-bar design and
enter the target's diurnal factor B, and they are forecast but not scored (33,970 forecasts against Table 1's 33,527
scored bars).  The paper keeps them (D15) and discloses the measured effect of dropping them on the linear models.
NOTE FOR OFFICIAL PUBLICATION (D15): rerun with DROP_HOLIDAY_SESSIONS on (all models) before the final version.

READS   results/fomcfix_2026-10-26/ (RULE.txt ADDENDUM A): holiday_sessions.csv (the 123 holiday dates from the sample's
        own calendar, code/holiday_sessions.py), scores_linear/{summary,effects}.csv (the 2 x 2 factorial of the FOMC
        patches P1 = P2 in {0, 1} and DROP_HOLIDAY_SESSIONS in {0, 1}, cells A-D, ridge / lasso / elastic net on both
        predictor sets with the frozen penalties, scored on Table 1's 33,527 bars and their 16:00 bar: QLIKE, % of the
        full set vs the HAR set of the class, DM HLN lag 8; D6 Sharpe ratios on the 614 post-warmup option days).
        Every number is read from those files; none is recomputed here.
CELLS   A current design (holidays kept, FOMC unpatched; the printed forecasts), B FOMC patches (the paper's design after
        D13), C holidays dropped, D both.  Holiday effect: C - A and D - B; the table prints all four cells.
WRITES  writeup/generated/rehaul_holiday_numbers.tex   \\rhhol... macros (definitions only)
        writeup/generated/rehaul_holiday_table.tex     Table tab:rh_holiday

Run:  python writeup/make_rehaul_holiday.py     (repository root)
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
FF = ROOT / "results" / "fomcfix_2026-10-26"
GEN = HERE / "generated"
OUT_NUM = GEN / "rehaul_holiday_numbers.tex"
OUT_TAB = GEN / "rehaul_holiday_table.tex"
HEAD = "% AUTO-GENERATED by writeup/make_rehaul_holiday.py -- do not edit; re-run the script."
LIN = ("ridge", "lasso", "enet")
MTAG = {"ridge": "Ridge", "lasso": "Lasso", "enet": "Enet"}
MNAME = {"ridge": "Ridge", "lasso": "Lasso", "enet": "Elastic net"}
CELLS = {
    "A": ("kept", "before"),
    "B": ("kept", "after"),
    "C": ("dropped", "before"),
    "D": ("dropped", "after"),
}
FIRST, LAST = pd.Timestamp("2014-01-02"), pd.Timestamp("2024-04-30")
SIG = 0.05


def thousands(x: int) -> str:
    return f"{x:,}".replace(",", "{,}")


def num(x: float, nd: int = 2) -> str:
    s = f"{x:.{nd}f}"
    if float(s) == 0:
        s = s.lstrip("-")
    return "\\ensuremath{-}" + s[1:] if s.startswith("-") else s


def sgn(x: float, nd: int = 2) -> str:
    s = num(x, nd)
    return s if s.startswith("\\ensuremath") or float(s) == 0 else "+" + s


def pval(p: float) -> str:
    return "\\ensuremath{<}0.001" if p < 0.001 else f"{p:.3f}"


def rng(lo: float, hi: float, nd: int = 2) -> str:
    """A range for the text: "a--b" when both are non-negative (unsigned), else "a to b" with signs."""
    if num(lo, nd) == num(hi, nd):
        return sgn(lo, nd)
    if lo >= 0:
        return f"{num(lo, nd)}--{num(hi, nd)}"
    return f"{sgn(lo, nd)} to {sgn(hi, nd)}"


def main() -> None:
    M: list[tuple[str, str, str]] = []

    def add(name: str, value: str, note: str) -> None:
        assert name.isalpha(), name
        M.append(("rhhol" + name, value, note))

    h = pd.read_csv(FF / "holiday_sessions.csv", parse_dates=["date"])
    assert not h["nyse_rule_session"].any(), "a holiday date is an NYSE session"
    span = h[(h.date >= FIRST) & (h.date <= LAST)]
    n_bars = int(span["n_rth_bars"].sum())
    assert (len(span), n_bars) == (64, 443), (len(span), n_bars)  # 33,970 - 33,527 (RULE ADDENDUM A)
    add("NDatesAll", str(len(h)), "holiday dates with a shortened E-mini session in the sample")
    add("FirstYearAll", str(h.date.min().year), "first year of such a date")
    add("NSessions", str(len(span)), "holiday sessions in the evaluation span 2014-01-02 .. 2024-04-30")
    add("NBars", str(n_bars), "their regular-hours bars (forecast, not scored)")
    add("NForecast", thousands(33527 + n_bars), "bars forecast in the span (33,527 scored + the holiday bars)")
    add("NScored", thousands(33527), "bars scored (Table 1)")
    add(
        "LastBar",
        f"{span['last_rth_bar'].mode().iloc[0][:5]}",
        "the usual last regular-hours bar end of a holiday session (ET)",
    )

    sm = pd.read_csv(FF / "scores_linear" / "summary.csv")
    ef = pd.read_csv(FF / "scores_linear" / "effects.csv")
    assert set(sm.cell) == set(CELLS) and set(sm.model) == set(LIN), (set(sm.cell), set(sm.model))
    # every cell keeps a significant every-bar gain (the disclosure's claim: dropping the holidays changes no reading)
    assert ((sm.dm_bar < 0) & (sm.p_bar < SIG)).all(), "claim: the full set's every-bar gain significant in every cell"
    for eff, tag in (("C-A", "CA"), ("D-B", "DB")):
        e = ef[ef.effect == eff].set_index("model")
        for col, ctag, nd in (
            ("pct_vs_har_bar", "BarPp", 2),
            ("pct_vs_har_c16", "ClosePp", 2),
            ("d6_mid_full", "ShFull", 2),
            ("dd6_mid", "DSh", 2),
        ):
            v = e.loc[list(LIN), col].astype(float)
            add(f"Eff{tag}{ctag}Min", sgn(v.min(), nd), f"holiday effect {eff}, linear: lowest change of {col}")
            add(f"Eff{tag}{ctag}Max", sgn(v.max(), nd), f"holiday effect {eff}, linear: highest change of {col}")
            add(f"Eff{tag}{ctag}Rng", rng(v.min(), v.max(), nd), f"holiday effect {eff}: range of {col}")
            for m in LIN:
                add(f"Eff{tag}{MTAG[m]}{ctag}", sgn(float(e.loc[m, col]), nd), f"holiday effect {eff}, {m}: {col}")
    # the size statement of the disclosure: the every-bar change is a fraction of a percentage point
    e_ca = ef[ef.effect == "C-A"].set_index("model").loc[list(LIN), "pct_vs_har_bar"].abs()
    assert e_ca.max() < 0.5, "claim: dropping the holidays moves the every-bar full-vs-HAR comparison by < 0.5 pp"
    for c in CELLS:
        for m in LIN:
            r = sm[(sm.cell == c) & (sm.model == m)].iloc[0]
            t = f"{MTAG[m]}{c}"
            add(f"{t}PctBar", num(float(r.pct_vs_har_bar), 1), f"cell {c}, {m}: every-bar % vs HAR")
            add(f"{t}PBar", pval(float(r.p_bar)), f"cell {c}, {m}: every-bar DM p")
            add(f"{t}PctClose", num(float(r.pct_vs_har_c16), 1), f"cell {c}, {m}: 16:00 % vs HAR")
            add(f"{t}ShFull", num(float(r.d6_mid_full)), f"cell {c}, {m}: D6 Sharpe ratio, full set, mid")

    # ------------------------------------------------------------------ table
    body = []
    for m in LIN:
        first = True
        for c, (hol, fomc) in CELLS.items():
            r = sm[(sm.cell == c) & (sm.model == m)].iloc[0]
            lab = MNAME[m] if first else ""
            first = False
            body.append(
                f"{lab} & {c} & {hol} & {fomc} & {sgn(float(r.pct_vs_har_bar), 1)} & {num(float(r.dm_bar))} "
                f"({pval(float(r.p_bar))}) & {sgn(float(r.pct_vs_har_c16), 1)} & {num(float(r.dm_c16))} "
                f"({pval(float(r.p_c16))}) & {num(float(r.d6_mid_full))} / {num(float(r.d6_mid_har))} \\\\"
            )
        body.append("\\addlinespace[3pt]")
    body = body[:-1]
    note = (
        "\\item \\textit{Notes:} The penalized linear models of Table~\\ref{tab:rh_oos} on four designs: the \\rhholNSessions{} "
        "NYSE-holiday sessions of the evaluation span (\\rhholNBars{} regular-hours bars, a shortened futures session "
        "ending about \\rhholLastBar~ET) kept in or dropped from the estimation rows and the diurnal factor $B$, and the "
        "FOMC calendar corrections of Section~\\ref{sec:rh_data} before or after; cell B is the design of the main text. "
        "Every cell keeps its frozen penalty and is scored on the same \\rhholNScored{} bars of Table~\\ref{tab:rh_oos} "
        "(the holiday bars are never scored) and on their 16:00 bar. \\% vs HAR: the full set's QLIKE against the HAR set "
        "of the same class (negative: the full set has the lower loss); DM: the Diebold--Mariano statistic of the daily "
        "average (every bar) or 16:00 QLIKE, HLN correction, Newey--West lag \\rhorHacLag, $p$-value in parentheses. "
        "$\\SR$: the annualized Sharpe ratio of the sign strategy at mid-quotes, full set / HAR set, on the "
        "\\rheSzDays{} post-warmup option days."
    )
    table = "\n".join(
        [
            HEAD,
            "% Table tab:rh_holiday (appendix, D15): the linear 2 x 2 of results/fomcfix_2026-10-26 (RULE.txt ADDENDUM A).",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\footnotesize",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\begin{threeparttable}",
            "\\caption{NYSE-holiday sessions: kept or dropped}",
            "\\label{tab:rh_holiday}",
            "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}llllrrrrr@{}}",
            "\\toprule",
            " & & & & \\multicolumn{2}{c}{Every bar} & \\multicolumn{2}{c}{16:00} & \\\\",
            "\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}",
            "Model & Cell & Holidays & FOMC fix & \\% vs HAR & DM ($p$) & \\% vs HAR & DM ($p$) & $\\SR$ full / HAR \\\\",
            "\\midrule",
            *body,
            "\\bottomrule",
            "\\end{tabular*}",
            "\\begin{tablenotes}[flushleft]",
            "\\footnotesize",
            note,
            "\\end{tablenotes}",
            "\\end{threeparttable}",
            "\\end{table}",
            "",
        ]
    )
    names = [n for n, _, _ in M]
    assert len(set(names)) == len(names), "a macro name twice"
    lines = [
        HEAD,
        "% \\rhhol... macros of the NYSE-holiday disclosure (D15; Table tab:rh_holiday): results/fomcfix_2026-10-26,",
        "% RULE.txt ADDENDUM A (cells A-D; Eff CA = C - A, Eff DB = D - B, the holiday effect without / with the FOMC fix).",
        "% NOTE FOR OFFICIAL PUBLICATION (D15): rerun with DROP_HOLIDAY_SESSIONS on (all models) before the final version.",
    ]
    for name, value, n_ in M:
        lines.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{value}}}  % {n_}")
    GEN.mkdir(parents=True, exist_ok=True)
    OUT_NUM.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    OUT_TAB.write_text(table, encoding="utf-8", newline="\n")
    print(f"wrote {len(M)} macros to {OUT_NUM.relative_to(ROOT)} and {OUT_TAB.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
